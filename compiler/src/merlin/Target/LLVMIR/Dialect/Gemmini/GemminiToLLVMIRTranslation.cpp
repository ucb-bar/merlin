// Implements a small `LLVMTranslationDialectInterface` that maps each
// `gemmini.intr.*` op to the corresponding `llvm.intr.riscv.*` builtin
// emitted by `mlir-translate --mlir-to-llvmir`. The actual dispatch table is
// generated by `mlir-tblgen -gen-llvmir-conversions` and included as
