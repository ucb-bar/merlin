namespace {
/// Implementation of the dialect interface that converts operations belonging
/// to the Gemmini dialect to LLVM IR.
class GemminiDialectLLVMIRTranslationInterface
	: public LLVMTranslationDialectInterface {
  public:
	using LLVMTranslationDialectInterface::LLVMTranslationDialectInterface;

	/// Translates the given operation to LLVM IR using the provided IR builder
	/// and saving the state in `moduleTranslation`.
	LogicalResult convertOperation(Operation *op, llvm::IRBuilderBase &builder,
		LLVM::ModuleTranslation &moduleTranslation) const final {
		Operation &opInst = *op;
#include "compiler/src/merlin/Dialect/Gemmini/IR/GemminiConversions.inc"

		return failure();
	}
};
} // namespace

void merlin::registerGemminiDialectTranslation(DialectRegistry &registry) {
	registry.insert<mlir::iree_compiler::Gemmini::GemminiDialect>();
	registry.addExtension(
		+[](MLIRContext *ctx,
			 mlir::iree_compiler::Gemmini::GemminiDialect *dialect) {
			dialect->addInterfaces<GemminiDialectLLVMIRTranslationInterface>();
		});
}

void merlin::registerGemminiDialectTranslation(MLIRContext &context) {
	DialectRegistry registry;
	registerGemminiDialectTranslation(registry);
	context.appendDialectRegistry(registry);
}
