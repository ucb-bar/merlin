"""Render merlin's block schedule into this package's Gemmini instructions.

GENERATED by merlin/experiments/scheduled_backend_v0/scripts/mint.py -- do not edit; re-mint instead.
``lowering/block_schedule.py`` beside this file is merlin's scheduling pass copied byte for byte (its
sha256 is recorded in ``manifest.yaml`` under ``lineage.pass_module_sha256``), so the ORDER of every block
move is decided by that pass under the knobs below, and this module only spells each abstract move in the
instruction vocabulary the parent package already defines (``isa.Instruction``, ``isa._tile_word``,
``isa._config_ld``/``_ex``/``_st``). No address, stride or accumulator flag is computed here that the
parent's own helpers and constants do not already define.

The geometry below was DERIVED from the target's RTL facts at mint time and checked against the
parent's baked ``DIM``/``SPAD_ROWS``/``ACC_ROWS`` constants before this file was written.
"""

from __future__ import annotations

from typing import Any

from lowering import isa
from lowering.block_schedule import (  # noqa: F401 -- Geometry/Knobs are named by the rendered literals below
    LHS,
    WEIGHT,
    Compute,
    Contraction,
    ConvContraction,
    Geometry,
    Knobs,
    Load,
    Preload,
    Store,
    schedule_contraction,
    schedule_convolution,
)

GEOMETRY = "@GEOMETRY@"
KNOBS = "@KNOBS@"
CONV_KNOBS = "@CONV_KNOBS@"

#: Epilogue stages the block schedule models (applied by the CONFIG_ST word, not by a block move).
_SCHEDULED_EPILOGUE = ("relu", "acc_scale")


def supports(attrs: dict[str, Any]) -> bool:
    """Whether this renderer handles a command's epilogue; anything else stays with the parent lowering."""
    return all(stage in _SCHEDULED_EPILOGUE for stage in (attrs.get("epilogue") or []))


def _accumulator_base(out: Any) -> int:
    return (3 << 30) | (isa.ACC_FULL if out.dtype == "i32" else 0)


def _render(schedule: Any, tensors: dict[str, tuple[str, Any]], out_name: str, out: Any) -> list[Any]:
    """Spell each block move of ``schedule``. ``tensors`` maps a role to ``(name, TensorSpec)``."""
    base = _accumulator_base(out)
    out_stride, out_elem = isa._row_stride(out), isa._elem_bytes(out.dtype)
    trace: list[Any] = []
    for op in schedule.ops:
        if isinstance(op, Load):
            name, spec = tensors[op.role]
            stride, elem = isa._row_stride(spec), isa._elem_bytes(spec.dtype)
            trace.append(isa._config_ld(stride, channel=0))
            if op.gather is None:
                trace.append(
                    isa.Instruction(
                        "MVIN",
                        isa.Address(name, op.dram_row * stride + op.dram_col * elem),
                        isa._tile_word(op.row, op.cols, op.rows),
                    )
                )
            else:
                for offset, entry in enumerate(op.gather):
                    source = 0 if entry is None else isa.Address(name, entry[0] * stride + entry[1] * elem)
                    trace.append(isa.Instruction("MVIN", source, isa._tile_word(op.row + offset, op.cols, 1)))
        elif isinstance(op, Preload):
            weight_row = op.weight_row if op.weight_row is not None else isa.GARBAGE_ADDR
            destination = base + op.accumulator_row
            if not op.accumulate:
                destination &= ~isa.ACC_ACCUMULATE
            trace.append(
                isa.Instruction(
                    "PRELOAD",
                    isa._tile_word(weight_row, op.cols, op.weight_rows),
                    isa._tile_word(destination, op.cols, op.rows),
                )
            )
        elif isinstance(op, Compute):
            name = "COMPUTE_PRELOADED" if op.fresh_weights else "COMPUTE_ACCUMULATE"
            trace.append(
                isa.Instruction(
                    name,
                    isa._tile_word(op.input_row, op.cols, op.rows),
                    isa._tile_word(isa.GARBAGE_ADDR, isa.DIM, isa.DIM),
                )
            )
        elif isinstance(op, Store):
            trace.append(
                isa.Instruction(
                    "MVOUT",
                    isa.Address(out_name, op.dram_row * out_stride + op.dram_col * out_elem),
                    isa._tile_word(base + op.accumulator_row, op.cols, op.rows),
                )
            )
    return trace


def matmul(program: Any, lhs_name: str, weight_name: str, out_name: str, attrs: dict[str, Any]) -> list[Any]:
    lhs, weight, out = program.tensors[lhs_name], program.tensors[weight_name], program.tensors[out_name]
    m, k = lhs.shape
    wk, n = weight.shape
    if wk != k:
        raise ValueError("matmul contraction mismatch")
    schedule = schedule_contraction(Contraction(m, k, n, lhs_name, weight_name, out_name), GEOMETRY, KNOBS)
    return [
        isa._config_ex(transpose_b=False, weight_stationary=True),
        isa._config_st(isa._row_stride(out), attrs, out.dtype),
    ] + _render(schedule, {LHS: (lhs_name, lhs), WEIGHT: (weight_name, weight)}, out_name, out)


def conv(program: Any, command: dict[str, Any], weight_name: str) -> list[Any]:
    attrs, ops = command["attributes"], command["operands"]
    ifm, weight, out = program.tensors[ops["ifm"]], program.tensors[weight_name], program.tensors[ops["dst"]]
    batch, in_h, in_w, ci = ifm.shape
    kh, kw, kci, co = attrs["kernel"]
    if attrs.get("layout") != "nhwc" or ci != kci:
        raise ValueError("conv primitive lowering requires matching NHWC channels")
    if list(weight.shape) != [kh * kw * ci, co]:
        raise ValueError("conv weight must use pre-im2col [Kh*Kw*Ci, Co] layout")
    spec = ConvContraction(
        batch,
        in_h,
        in_w,
        ci,
        kh,
        kw,
        co,
        tuple(attrs["stride"]),
        tuple(attrs["padding"]),
        tuple(attrs["dilation"]),
        ops["ifm"],
        weight_name,
        ops["dst"],
    )
    schedule = schedule_convolution(spec, GEOMETRY, CONV_KNOBS)
    return [isa._config_ex(weight_stationary=True), isa._config_st(isa._row_stride(out), attrs, out.dtype)] + _render(
        schedule, {LHS: (ops["ifm"], ifm), WEIGHT: (weight_name, weight)}, ops["dst"], out
    )
