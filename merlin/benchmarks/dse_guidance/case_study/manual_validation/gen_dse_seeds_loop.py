"""Regenerate the Timeloop-style mapspace seeds FROM the P21 loop-preserving contract.

The original ``gen_dse_seeds.py`` built seeds from the flat one-step capture, so (per
``mapspace_seed_gaps.md``) every seed "covered ONE step": the outer K denoise/decode loop was
unrolled/absent, the prefix-vs-x-K region split was missing, and the KV state was blocked. P21's
loop-preserving capture closed exactly those gaps in the IR. This generator re-derives the seeds
with those facts now present — reading only the committed artifacts (``operator_shape_table.csv`` +
``loop_aware_contract.csv``), so it is re-derivable + verifiable.

Outputs (into case_study/):
  mapspace_seeds_loop.csv          flat: per (workload, op_class, region_role, shape) + outer K + KV
  mapspace_seeds_loop.yaml         Timeloop problem shapes grouped per workload with the outer K loop
  mapspace_seed_gaps_resolved.md   which P19 gaps P21 closed, which remain

Structural search-space seeds only — no mapping / cycles / area / energy / perf is chosen.
"""
from __future__ import annotations

import csv
import io
from pathlib import Path

from merlin.common.artifacts import yaml_artifact
from merlin.dse_guidance import mapspace as MS

HERE = Path(__file__).resolve().parent
CS = HERE.parent  # case_study/


def main() -> None:
    rows = MS.loop_aware_seed_rows(CS)
    if not rows:
        raise SystemExit("no loop-aware seed rows — is operator_shape_table.csv present?")

    # --- flat CSV ---
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=MS._LOOP_SEED_COLS, extrasaction="ignore")
    w.writeheader()
    for r in rows:
        w.writerow(r)
    (CS / "mapspace_seeds_loop.csv").write_text(buf.getvalue())

    # --- grouped YAML (Timeloop problem shapes + outer K loop + KV node) ---
    yaml_artifact("mapspace_seeds_loop.yaml", MS.loop_aware_problem_shapes(CS),
                  header="loop_aware_mapspace_seeds (P21: outer K loop + region split + KV state; "
                         "structural search-space seed, no perf claim)").write(CS)

    # --- gaps-resolved note (compare against the P19 mapspace_seed_gaps.md) ---
    rep = [r for r in rows if r["region_role"] in ("repeated_head", "decode_lm")]
    n_K = sum(1 for r in rep if r["K_source"] == "recovered_from_ir")
    workloads = sorted({r["workload"] for r in rows})
    kv_w = sorted({r["workload"] for r in rows if r["kv_state_bytes_workload"]})
    md = f"""# Mapspace seed gaps — resolved by P21 (loop-preserving capture)

Re-derivation of `mapspace_seed_gaps.md` after the P21 `torch.while_loop -> scf.for` capture. The
flat seeds (`mapspace_seed_candidates.yaml`, `timeloop_problem_shapes.yaml`) "covered ONE step".
The loop-aware seeds (`mapspace_seeds_loop.{{csv,yaml}}`) re-derive the same problem shapes WITH the
loop facts the flat capture lacked. Source: `operator_shape_table.csv` x `loop_aware_contract.csv`
(both `recovered_from_ir`). Structural search-space only — no mapping/cycles/perf.

## Now CLOSED (was a gap; present in the loop-aware seed)
- **K denoise/decode loop trip count** — recovered from the `scf.for` upper bound (`loop_aware_
  contract.csv` `K_ir`). The seed now multiplies each repeated-head shape by K:
  `instances_per_replan = layers_in_capture x outer_loop_K`. {n_K} repeated-head shapes across
  {len(workloads)} workloads now carry an IR-recovered K (was config/assumed).
- **Prefix-once vs x K repeated split** — `region_role` per shape (from the `scf.for` boundary),
  so the seed distinguishes the once-per-replan backbone from the K-times head (different reuse
  scope: `once_per_replan` vs `across_K (resident-eligible)`).
- **Loop-carried KV state** — `kv_state_bytes_workload` attached per workload from the recovered
  `iter_args` (`kv_cache_bytes_ir`). Present for: {", ".join(kv_w) or "(none in this corpus)"}.

## Still OPEN (capture-frontier, not analyzer — unchanged from P19)
- **Attention inner dims (heads, seq, head_dim)** — attention contractions still fold batch/heads
  into M; per-head/seq mapspace axes need the SDPA op kept un-decomposed (high-level capture) or a
  sidecar. The named-matmul seed covers linear-GEMM contractions.
- **Conv spatial/channel loops** — conv ops counted, window dims not quantified here.
- **Operand bit-width / packed layout** — f32 in this capture; the qdq recapture exposes per-channel
  int8 (`quant_ext.dequantize`) for a true low-bit mapspace (separate corpus).
- **Fusion/epilogue grouping** — bias-add + activation are separate generics; a fused-epilogue
  mapspace needs the epilogue grouped onto the matmul (`epilogue_pattern_table` has the grouping).

_Generated by `manual_validation/gen_dse_seeds_loop.py` from committed artifacts._
"""
    (CS / "mapspace_seed_gaps_resolved.md").write_text(md)

    print(f"wrote mapspace_seeds_loop.csv ({len(rows)} shapes), mapspace_seeds_loop.yaml "
          f"({len(workloads)} workloads), mapspace_seed_gaps_resolved.md "
          f"({n_K} repeated-head shapes with IR-recovered K)")


if __name__ == "__main__":
    main()
