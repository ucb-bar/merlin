"""Today's grouping, group writer and admission still accept what the sealed Phase 0 corpus contains.

The sealed corpus was generated by the code of its day, and a regeneration found weeks later that
today's code refused every whole-model capsule whose residual-add group the sealed corpus had
admitted. Each fixture under ``merlin/tests/fixtures/phase0_regeneration_canary/`` is a value-free
slice of one sealed model capsule (written by ``build_tools/scripts/extract_regeneration_canary.py``);
replaying it here moves that discovery to the commit that makes the code stricter. Replayed against
archived trees, this canary passes at the sealed generation's commit and first fails at 0e5323b9e,
the commit that added ordered source scales to residual-add groups.
"""

from __future__ import annotations

import gzip
import hashlib
import json
import shutil

import pytest
from merlin_experiments.phase0 import regeneration_canary as RC

from merlin.common.paths import merlin_dir

_ROOT = merlin_dir() / "tests" / "fixtures" / "phase0_regeneration_canary"


def _fixtures():
    for path in sorted(_ROOT.glob("*/canary.json")):
        target = json.loads(path.read_text())["target"]
        yield pytest.param(path.parent, id=path.parent.name, marks=pytest.mark.target(target))


@pytest.mark.parametrize("fixture", list(_fixtures()))
def test_todays_code_still_admits_every_sealed_case(fixture):
    report = RC.run_isolated(fixture)
    assert not report["findings"] and not report["stale_accepted_drift"], (
        "today's code would refuse what the sealed Phase 0 corpus contains -- a regeneration of the "
        "sealed corpus would fail. Fix the regression, or have the change reviewed and record it in the "
        f"fixture's accepted_drift:\n{RC.describe(report)}"
    )
    regenerated = [row for row in report["rows"] if row["replay"] == "generation"]
    assert regenerated and any(row["status"] == "admitted" for row in regenerated)
    # The replay is faithful, not merely permissive: an unchanged group regenerates byte-identical.
    assert any(row.get("program_changed") is False for row in regenerated)


def test_the_canary_reports_a_stricter_admission_by_group(tmp_path):
    """An admission that stops treating the bound software spec as reviewed is caught, per group."""
    source = next(iter(sorted(_ROOT.glob("*/canary.json")))).parent
    fixture = tmp_path / source.name
    shutil.copytree(source, fixture)
    document = json.loads((fixture / "canary.json").read_text())
    views = json.loads(gzip.decompress((fixture / document["views"]["file"]).read_bytes()))
    views["software_spec"]["status"] = "draft"
    raw = json.dumps(views, sort_keys=True).encode()
    (fixture / document["views"]["file"]).write_bytes(gzip.compress(raw, mtime=0))
    document["views"]["sha256"] = hashlib.sha256(raw).hexdigest()
    (fixture / "canary.json").write_text(json.dumps(document))

    report = RC.run_isolated(fixture)
    refused = {(row["replay"], row["group"]) for row in report["findings"]}
    sealed = {row["capsule"].rpartition("/")[2] for row in document["groups"]}
    assert {group for replay, group in refused if replay == "admission"} == sealed
    assert "now unknown" in RC.describe(report)


def test_an_accepted_drift_that_no_longer_reproduces_is_reported(tmp_path):
    source = next(iter(sorted(_ROOT.glob("*/canary.json")))).parent
    fixture = tmp_path / source.name
    shutil.copytree(source, fixture)
    document = json.loads((fixture / "canary.json").read_text())
    document["accepted_drift"] = [
        *document.get("accepted_drift", []),
        {"group": "G_never_formed", "replay": "admission", "reason": "fixture"},
    ]
    (fixture / "canary.json").write_text(json.dumps(document))
    report = RC.run_isolated(fixture)
    assert [row["group"] for row in report["stale_accepted_drift"]] == ["G_never_formed"]
