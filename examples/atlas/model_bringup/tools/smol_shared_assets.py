"""Share exact immutable content-addressed assets without reopening a writer."""
import hashlib
import os
from pathlib import Path
import re

import kernel_library  # noqa: E402,F401
from atlas_path_guard import checked
from bundle import relative_name


class SharedAssets:
    def __init__(self, root, expected, out, read):
        self.root, self.out, self.read = checked(root), checked(out), read
        raw = read(self.root/'SHA256SUMS', expected)
        self.checksums_sha256 = hashlib.sha256(raw).hexdigest()
        self.members, self.shared = {}, []
        names = set()
        for line in raw.decode().splitlines():
            match = re.fullmatch(r'([0-9a-f]{64}) [ *](.+)', line)
            if match is None:
                raise ValueError('Invalid shared asset checksum line')
            digest, name = match.groups()
            relative_name(name)
            if name in names:
                raise ValueError('Duplicate shared asset member')
            names.add(name)
            if Path(name).name == digest+'.bin':
                self.members.setdefault(digest, name)

    def store(self, path, raw):
        path = checked(path)
        if not path.is_relative_to(self.out) or path.exists():
            raise ValueError('Shared asset target must be a fresh owned path')
        digest = hashlib.sha256(raw).hexdigest()
        name = self.members.get(digest)
        if name is None:
            # Exclusive creation also prevents truncation of any existing link.
            with path.open('xb') as stream:
                stream.write(raw)
            return
        source = checked(self.root/name)
        original = self.read(source, digest)
        if original != raw:
            raise ValueError('Shared immutable asset differs from generated bytes')
        # link(2) creates a new entry or fails. It never opens or truncates the
        # target, and neither source nor target may contain a symbolic link.
        os.link(source, path, follow_symlinks=False)
        self.shared.append(dict(source=str(source), target=str(path), sha256=digest, bytes=len(raw)))

    def verify(self):
        for row in self.shared:
            for key in ('source', 'target'):
                if hashlib.sha256(checked(row[key]).read_bytes()).hexdigest() != row['sha256']:
                    raise ValueError('Shared immutable asset bookend changed')

    def receipt(self):
        return dict(root=str(self.root), checksums_sha256=self.checksums_sha256, assets=self.shared,
                    bytes=sum(row['bytes'] for row in self.shared), no_linked_target_reopened_for_writing=True)
