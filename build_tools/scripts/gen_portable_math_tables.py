#!/usr/bin/env python3
"""Generate the coefficient tables of Merlin's portable transcendentals.

``merlin/runtime/abi/portable_math.h`` evaluates ``erff``/``expf``/``tanhf``/``logf`` in double
precision and rounds once to float. Its constants live in ``portable_math_tables.h``, which this
script writes. Every constant is a mathematical quantity computed here at high precision (mpmath,
60 significant digits) and rounded once to the nearest double, then printed as a C99 hexadecimal
literal so that the C compiler reads back exactly that double:

* ``MPM_EXP_TAYLOR``      1/n!, n = 0..13 -- exp(r) on |r| <= ln2/2 (truncation < 5e-18 relative);
* ``MPM_EXPM1_TAYLOR``    1/(n+1)!, n = 0..14 -- expm1(y)/y on |y| <= ln2/2;
* ``MPM_LOG_ATANH``       1/(2n+3), n = 0..10 -- log(m) = 2 atanh(s) on |s| <= 0.1716;
* ``MPM_ERF_SMALL``       (2/sqrt(pi)) (-1)^n / (n! (2n+1)), n = 0..13 -- erf(x)/x on x^2 < 1/4;
* ``MPM_ERFC_SCALED``     per interval [0.5 + i/2, 1 + i/2), i = 0..6, a degree-14 Chebyshev
  interpolant (mpmath ``chebyfit``) of g(c+t) = erfc(c+t) exp((c+t)^2), t in [-1/4, 1/4], c the
  interval's midpoint, converted to the monomial basis in t (fit error < 2e-19 relative);
* the Cody-Waite split of ln 2 (``MPM_LN2_HI`` keeps 31 significant bits so k * LN2_HI is exact for
  every |k| < 2^22) and 1/ln 2.

The tables are data, not tuning: regenerating them must reproduce the checked-in header byte for
byte (``--check``), and any change to them is a change of the numeric policy's implementation,
which ``merlin.llvmlower.portable_math.implementation_digest`` records in every build that uses it.

Needs ``mpmath`` (present in any torch environment). Usage::

    gen_portable_math_tables.py  # (re)write the header
    gen_portable_math_tables.py - -check  # exit 1 if the header is stale
"""

from __future__ import annotations

import argparse
import sys
from fractions import Fraction
from math import factorial
from pathlib import Path

HEADER = Path(__file__).resolve().parents[2] / "merlin" / "runtime" / "abi" / "portable_math_tables.h"

EXP_DEGREE = 13
EXPM1_DEGREE = 14
LOG_TERMS = 11
ERF_SMALL_TERMS = 14
ERFC_INTERVALS = 7
ERFC_DEGREE = 14
ERFC_LO = Fraction(1, 2)
ERFC_WIDTH = Fraction(1, 2)


def _hex(value: float) -> str:
    return float(value).hex()


def _row(name: str, values: list[float], comment: str) -> list[str]:
    lines = [f"/* {comment} */", f"static const double {name}[{len(values)}] = {{"]
    lines += [f"    {_hex(v)}, /* {v!r} */" for v in values]
    lines.append("};")
    return lines


def tables() -> str:
    import mpmath as mp

    mp.mp.dps = 60

    exp_taylor = [float(Fraction(1, factorial(n))) for n in range(EXP_DEGREE + 1)]
    expm1_taylor = [float(Fraction(1, factorial(n + 1))) for n in range(EXPM1_DEGREE + 1)]
    log_atanh = [float(Fraction(1, 2 * n + 3)) for n in range(LOG_TERMS)]
    two_over_sqrt_pi = 2 / mp.sqrt(mp.pi)
    erf_small = [float(two_over_sqrt_pi * (-1) ** n / (factorial(n) * (2 * n + 1))) for n in range(ERF_SMALL_TERMS)]

    ln2 = mp.log(2)
    # LN2_HI: ln 2 truncated to 31 significant bits, so k * LN2_HI is exact for |k| < 2^22.
    scale = mp.mpf(2) ** 31
    ln2_hi = float(mp.floor(ln2 * scale) / scale)
    ln2_lo = float(ln2 - mp.mpf(ln2_hi))
    log2e = float(1 / ln2)

    def scaled(x):
        return mp.erfc(x) * mp.exp(x * x)

    erfc_rows: list[list[float]] = []
    worst = mp.mpf(0)
    for i in range(ERFC_INTERVALS):
        centre = mp.mpf(float(ERFC_LO + ERFC_WIDTH * i + ERFC_WIDTH / 2))  # dyadic: exact
        half = mp.mpf(float(ERFC_WIDTH / 2))
        poly, err = mp.chebyfit(lambda t, c=centre: scaled(c + t), [-half, half], ERFC_DEGREE + 1, error=True)
        worst = max(worst, err / scaled(centre + half))
        # chebyfit returns the highest degree first; the C side wants the constant term first.
        erfc_rows.append([float(c) for c in reversed(poly)])
    if worst > mp.mpf(2) ** -60:
        raise SystemExit(f"erfc fit error {mp.nstr(worst, 3)} exceeds 2^-60; raise ERFC_DEGREE")

    out = [
        "/* GENERATED by build_tools/scripts/gen_portable_math_tables.py -- do not edit by hand.",
        " *",
        " * Coefficients of Merlin's portable transcendentals (portable_math.h). Each value is the",
        " * mathematical constant named beside it rounded once to the nearest double, written as an",
        " * exact hexadecimal literal. */",
        "#ifndef MERLIN_PORTABLE_MATH_TABLES_H",
        "#define MERLIN_PORTABLE_MATH_TABLES_H",
        "",
        f"#define MPM_LN2_HI {_hex(ln2_hi)} /* ln 2, 31 significant bits */",
        f"#define MPM_LN2_LO {_hex(ln2_lo)} /* ln 2 - MPM_LN2_HI */",
        f"#define MPM_LOG2E {_hex(log2e)} /* 1 / ln 2 */",
        f"#define MPM_EXP_DEGREE {EXP_DEGREE}",
        f"#define MPM_EXPM1_DEGREE {EXPM1_DEGREE}",
        f"#define MPM_LOG_TERMS {LOG_TERMS}",
        f"#define MPM_ERF_SMALL_TERMS {ERF_SMALL_TERMS}",
        f"#define MPM_ERFC_INTERVALS {ERFC_INTERVALS}",
        f"#define MPM_ERFC_DEGREE {ERFC_DEGREE}",
        "",
        *_row("MPM_EXP_TAYLOR", exp_taylor, "1/n!: exp(r) = sum r^n / n!"),
        "",
        *_row("MPM_EXPM1_TAYLOR", expm1_taylor, "1/(n+1)!: expm1(y) = y * sum y^n / (n+1)!"),
        "",
        *_row("MPM_LOG_ATANH", log_atanh, "1/(2n+3): log(m) = 2s + 2s * sum s^(2n+2) / (2n+3)"),
        "",
        *_row("MPM_ERF_SMALL", erf_small, "(2/sqrt(pi)) (-1)^n / (n! (2n+1)): erf(x) = x * sum c_n x^(2n)"),
        "",
        "/* erfc(x) exp(x^2) on [0.5 + i/2, 1 + i/2): sum c_k t^k, t = x - (0.75 + i/2). */",
        f"static const double MPM_ERFC_SCALED[{ERFC_INTERVALS}][{ERFC_DEGREE + 1}] = {{",
    ]
    for i, row in enumerate(erfc_rows):
        lo = ERFC_LO + ERFC_WIDTH * i
        out.append(f"    {{ /* [{float(lo)}, {float(lo + ERFC_WIDTH)}) */")
        out += [f"        {_hex(v)}," for v in row]
        out.append("    },")
    out += ["};", "", "#endif /* MERLIN_PORTABLE_MATH_TABLES_H */", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if the checked-in header is stale")
    args = ap.parse_args()
    text = tables()
    if args.check:
        current = HEADER.read_text(encoding="utf-8") if HEADER.is_file() else ""
        if current != text:
            print(f"{HEADER} is stale; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text, encoding="utf-8")
    print(f"wrote {HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
