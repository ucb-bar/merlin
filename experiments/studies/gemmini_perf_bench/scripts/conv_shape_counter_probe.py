#!/usr/bin/env python3
"""One convolution, on the device, with the accelerator's own cycle-attribution counters read out.

``sched_vendor_ab`` answers "is our rendering of this group faster than the library's, and does it
agree bit for bit". It cannot answer WHERE a slow group spends its cycles, and a model of where they
go is not evidence. This runs the same single-group A/B over a convolution named on the command line
and, around each timed region, programs the accelerator's counter file with the SEVEN signals that
partition every cycle in which any unit is busy:

    MAIN_LD / MAIN_ST / MAIN_EX          exactly one unit busy
    MAIN_LD_ST / MAIN_LD_EX / MAIN_ST_EX two busy
    MAIN_LD_ST_EX                        all three

They are mutually exclusive by construction in the RTL (`Controller.scala` builds each as a
conjunction over the three `busy` signals), so `MAIN_LD` is the count of cycles in which the load unit
was the ONLY thing running -- the mesh idle behind it. That single number separates "this group is
bound by how much it moves" from "this group is bound by how it is sequenced", which no amount of
arithmetic over the descriptor can.

The eighth slot takes one further signal, chosen by ``--extra``; ``RDMA_BYTES_REC`` measures what the
read DMA delivered.

READ THAT COUNTER WITH ITS DEFINITION IN HAND. `DMA.scala` accumulates it as

    .elsewhen (tl.d.fire) { total_bytes_read := total_bytes_read + (1.U << tl.d.bits.size) }

-- the whole REQUEST size is added once per response BEAT, so a request counts itself once for every
beat it takes, and the number is (real bytes) x (request size / beat width). It is a faithful measure
of bus occupancy and a 4x overstatement of DRAM bytes for a full-size request. Compare it between two
programs, or divide it out; do not read it as a byte count.

Nothing about the device is written here. The counter codes come from the target's own
``gemmini_counter.h``, the tile from the schedule's own search, and the capacities from the RTL facts.

    conv_shape_counter_probe.py --target <target> --in-dim 56 --in-channels 256 --out-channels 512 \
        --kernel 1 --stride 2 --padding 0 --emulator <gsim emulator> --out <dir>
"""

from __future__ import annotations

import argparse
import importlib
import json
import subprocess
import sys
from pathlib import Path

import sched_vendor_ab as AB

from merlin.common import provenance

#: The pin whose revision every number here is about. A cycle count without it is a claim about an
#: unnamed device: the mesh width, the scratchpad partition and the loader's own iteration all come from
#: this tree, and a different revision can move the answer without moving anything in merlin.
RTL_PIN = "gemmini_rtl"

#: The cycle-attribution partition, in the order the report prints it. Every name is looked up in the
#: target's own counter header -- a code written here would be a claim about an enumeration this repo
#: does not own.
PARTITION = (
    "MAIN_LD_CYCLES",
    "MAIN_ST_CYCLES",
    "MAIN_EX_CYCLES",
    "MAIN_LD_ST_CYCLES",
    "MAIN_LD_EX_CYCLES",
    "MAIN_ST_EX_CYCLES",
    "MAIN_LD_ST_EX_CYCLES",
)


def counter_codes(header: Path, names) -> dict[str, int]:
    """``#define NAME <int>`` for each name, read structurally out of the target's counter header.

    An absent name is UNKNOWN and raises: a probe that silently dropped a counter would report a
    partition with a hole in it and look like a cheap region.
    """
    defines: dict[str, str] = {}
    for line in header.read_text(encoding="utf-8").splitlines():
        text = line.strip()
        if not text.startswith("#define "):
            continue
        rest = text[len("#define ") :].strip()
        name, _, value = rest.partition(" ")
        if name and value:
            defines[name] = value.strip()
    out = {}
    for name in names:
        if name not in defines:
            raise SystemExit(f"UNKNOWN counter {name}: not defined in {header}")
        token = defines[name]
        # Codes past the incremental block are written as an offset from it; resolve that one form
        # rather than pretending every value is a literal.
        if token.startswith("(") and token.endswith(")"):
            body = token[1:-1]
            left, plus, right = body.partition("+")
            if plus and left.strip() in defines and right.strip().isdigit():
                out[name] = int(defines[left.strip()]) + int(right.strip())
                continue
        if not token.isdigit():
            raise SystemExit(f"UNKNOWN counter {name}: value {token!r} is not an integer or a known offset")
        out[name] = int(token)
    return out


PROGRAM = """/* GENERATED by conv_shape_counter_probe.py -- one convolution with the counter file read out. */
#include <stdint.h>
#include <stddef.h>
#include <stdio.h>
#include "include/gemmini_testutils.h"
#include "include/gemmini_counter.h"

#define BLOB(sym, file, type) \\
    __asm__(".section .rodata\\n.balign 64\\n.global " #sym "\\n" #sym ":\\n.incbin \\"" file "\\"\\n.previous\\n"); \\
    extern const type sym[];
{blobs}

static {ctype} OUT_O[{elements}] row_align(1);
static {ctype} OUT_V[{elements}] row_align(1);

#define NSLOTS {nslots}
static const int SLOT_CODE[NSLOTS] = {{{codes}}};
static const char *SLOT_NAME[NSLOTS] = {{{names}}};

static void probe_arm(void) {{
    counter_reset();
    for (int i = 0; i < NSLOTS; i++) counter_configure(i, SLOT_CODE[i]);
}}

static void probe_report(const char *tag, uint64_t cycles) {{
    printf("PROBE_CYCLES %s %llu\\n", tag, (unsigned long long)cycles);
    for (int i = 0; i < NSLOTS; i++)
        printf("PROBE_COUNTER %s %s %u\\n", tag, SLOT_NAME[i], counter_read(i));
}}

{definition}

int main(void) {{
    gemmini_flush(0);
    uint64_t t0, cyc;
    printf("MERLIN_PROFILE warmup begin\\n");
    {ours}
    {vendor}
    printf("MERLIN_PROFILE warmup end rc=0\\n");
    printf("MERLIN_PROFILE measured begin\\n");
    probe_arm();
    t0 = read_cycles(); {ours} cyc = read_cycles() - t0;
    probe_report("ours", cyc);
    probe_arm();
    t0 = read_cycles(); {vendor} cyc = read_cycles() - t0;
    probe_report("vendor", cyc);
    long long diffs = 0; long long first = -1;
    long long sum_o = 0, sum_v = 0;
    for (size_t i = 0; i < {elements}; i++) {{
        sum_o += (long long)OUT_O[i];
        sum_v += (long long)OUT_V[i];
        if (OUT_O[i] != OUT_V[i]) {{ if (first < 0) first = (long long)i; diffs++; }}
    }}
    printf("PROBE_GROUP {name} elements={elements}\\n");
    printf("PROBE_DIFFS %lld first=%lld sum_ours=%lld sum_vendor=%lld\\n", diffs, first, sum_o, sum_v);
    printf("PROBE_VERDICT %s\\n", diffs == 0 ? "BIT_EXACT" : "DIFFERS");
    printf("MERLIN_PROFILE measured end rc=0\\n");
    return 0;
}}
"""


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--target", required=True)
    parser.add_argument("--name", required=True, help="label for the printed rows")
    parser.add_argument("--in-dim", required=True, type=int)
    parser.add_argument("--in-channels", required=True, type=int)
    parser.add_argument("--out-channels", required=True, type=int)
    parser.add_argument("--kernel", required=True, type=int)
    parser.add_argument("--stride", required=True, type=int)
    parser.add_argument("--padding", required=True, type=int)
    parser.add_argument("--scale", default=0.0234375, type=float)
    parser.add_argument("--no-relu", action="store_true")
    parser.add_argument("--seed", default=17, type=int)
    parser.add_argument(
        "--extra",
        default="RDMA_BYTES_REC",
        help="the counter for the eighth slot (a name from the target's counter header)",
    )
    parser.add_argument(
        "--counters",
        default=None,
        help=(
            "comma-separated counter names to program INSTEAD of the cycle partition, for a second "
            "pass over a region the partition has already located (e.g. the execute unit's own stall "
            "signals). The device has a fixed number of slots, so a wider question takes a second run "
            "rather than a wider report."
        ),
    )
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--emulator", type=Path)
    parser.add_argument("--max-cycles", default="400000000")
    parser.add_argument("--build-only", action="store_true")
    args = parser.parse_args(argv)

    backend = AB.base.get_backend(args.target)
    iset = backend.sched_instruction_set()
    sched = importlib.import_module(f"merlin._oot_backends.{args.target}.{args.target}_sched")
    facts = iset.facts
    harness = backend.rocc_tests_dir()
    compiler = backend.gcc_path()

    if args.counters:
        slots = [name.strip() for name in args.counters.split(",") if name.strip()]
    else:
        slots = list(PARTITION) + [args.extra]
    codes = counter_codes(Path(harness) / "include" / "gemmini_counter.h", slots)

    case = AB.conv_case(
        sched,
        facts,
        iset,
        name=args.name,
        in_dim=args.in_dim,
        ci=args.in_channels,
        co=args.out_channels,
        kernel=args.kernel,
        stride=args.stride,
        padding=args.padding,
        pool=(0, 0, 0),
        scale=args.scale,
        relu=not args.no_relu,
        seed=args.seed,
    )

    args.out.mkdir(parents=True, exist_ok=True)
    for symbol, array in case["arrays"].items():
        (args.out / f"{symbol}.bin").write_bytes(AB.np.ascontiguousarray(array).tobytes())
    blobs = "\n".join(f'BLOB({s}, "{s}.bin", {"acc_t" if s == "BS" else "elem_t"})' for s in case["arrays"])
    source = args.out / "probe.c"
    source.write_text(
        PROGRAM.format(
            blobs=blobs,
            ctype=case["ctype"],
            elements=case["elements"],
            definition=case["definition"],
            ours=case["ours"],
            vendor=case["vendor"],
            name=case["name"],
            nslots=len(slots),
            codes=", ".join(str(codes[s]) for s in slots),
            names=", ".join(f'"{s}"' for s in slots),
        ),
        encoding="utf-8",
    )

    common = Path(harness) / "riscv-tests" / "benchmarks" / "common"
    includes = [
        f"-I{Path(harness) / 'riscv-tests'}",
        f"-I{Path(harness) / 'riscv-tests' / 'env'}",
        f"-I{harness}",
        f"-I{common}",
    ]
    objects, log = [], []
    for src in (source, common / "syscalls.c", common / "crt.S"):
        unit = args.out / f"{src.stem}.o"
        done = subprocess.run(
            [str(compiler), *AB.CFLAGS, *includes, f"-Wa,-I{args.out}", "-c", str(src), "-o", str(unit)],
            capture_output=True, text=True, cwd=args.out,
        )  # fmt: skip
        log.append(done.stdout + done.stderr)
        if done.returncode:
            (args.out / "build.log").write_text("".join(log), encoding="utf-8")
            raise SystemExit(f"compile of {src.name} failed:\n{done.stderr[-3000:]}")
        objects.append(str(unit))
    elf = args.out / "probe.elf"
    done = subprocess.run(
        [str(compiler), *AB.CFLAGS, "-T", str(common / "test.ld"), *objects, "-o", str(elf)],
        capture_output=True, text=True, cwd=args.out,
    )  # fmt: skip
    (args.out / "build.log").write_text("".join(log) + done.stdout + done.stderr, encoding="utf-8")
    if done.returncode:
        raise SystemExit(f"link failed:\n{done.stderr[-3000:]}")

    try:
        pins = {RTL_PIN: provenance.verify(RTL_PIN)}
    except Exception as why:  # a pin that cannot be verified is recorded as such, never omitted
        pins = {}
        pin_note = f"UNKNOWN({type(why).__name__}: {why})"
    else:
        pin_note = None
    record = provenance.record(
        pins=pins,
        sources=[str(Path(harness) / "include" / "gemmini.h"), str(Path(harness) / "include" / "gemmini_counter.h")],
        artifacts={"emulator": str(args.emulator)} if args.emulator else None,
        extra={"pin_note": pin_note} if pin_note else None,
    )

    (args.out / "case.json").write_text(
        json.dumps(
            {
                "name": args.name,
                "target": args.target,
                "provenance": record,
                "shape": {
                    "in_dim": args.in_dim,
                    "in_channels": args.in_channels,
                    "out_channels": args.out_channels,
                    "kernel": args.kernel,
                    "stride": args.stride,
                    "padding": args.padding,
                },
                "counter_slots": {s: codes[s] for s in slots},
                "attrs": case["attrs"],
                "elf": str(elf),
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"built {elf}: {case['attrs']}")
    if args.build_only or args.emulator is None:
        return 0
    done = subprocess.run(
        [str(args.emulator), str(elf), f"+max-cycles={args.max_cycles}", f"+loadmem={elf}"],
        capture_output=True, text=True, cwd=args.out,
    )  # fmt: skip
    (args.out / "run.log").write_text(done.stdout + done.stderr, encoding="utf-8")
    for line in (done.stdout + done.stderr).splitlines():
        if line.startswith("PROBE_"):
            print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
