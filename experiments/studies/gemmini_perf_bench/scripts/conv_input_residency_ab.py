#!/usr/bin/env python3
"""One convolution, our own schedule, with the input left in the scratchpad and nothing else changed.

The input is not an axis of the output-channel tile, so a schedule that walks ``ceil(out_channels /
pochs)`` output-channel tiles moves the same input window that many times. The device does not require
it: ``a_ex_spad_id`` pins the input to a named scratchpad half instead of letting it follow the loop
slot, and ``LoopConvLdInput`` gates its whole command queue on ``req.dram_addr =/= 0.U`` -- so the first
output-channel tile stages the window and the rest name the half and pass a NULL input pointer.

This measures what that is worth. Both regions come out of the SAME recipe: the control is
``pin_input=False`` (re-stage per output-channel tile, which is what this repo emitted before) and the
subject is ``pin_input=True``. The tiling, the descriptor count, the pads, the pointers, the readout and
the config commands are identical; what differs is which descriptors carry an input pointer and the one
field that names the half. Bit-exactness is the acceptance criterion, not speed, so both are compared
element for element against the vendor's own ``tiled_conv_auto`` over byte-identical operands.

    conv_input_residency_ab.py --target <target> --name g38 --in-dim 14 --in-channels 256 \\
        --out-channels 256 --kernel 3 --stride 1 --padding 1 --emulator <gsim> --out <dir>
"""

from __future__ import annotations

import argparse
import importlib
import json
import subprocess
import sys
from pathlib import Path

import sched_vendor_ab as AB

from merlin.common import provenance
from merlin.sched.codegen import emit_c_function
from merlin.sched.ir import TensorArg

RTL_PIN = "gemmini_rtl"


PROGRAM = """/* GENERATED by conv_input_residency_ab.py -- one convolution, the input left in the scratchpad. */
#include <stdint.h>
#include <stddef.h>
#include <stdio.h>
#include "include/gemmini_testutils.h"
#include "include/gemmini_counter.h"

#define BLOB(sym, file, type) \\
    __asm__(".section .rodata\\n.balign 64\\n.global " #sym "\\n" #sym ":\\n.incbin \\"" file "\\"\\n.previous\\n"); \\
    extern const type sym[];
{blobs}

static {ctype} OUT_V[{elements}] row_align(1);
static {ctype} OUT_B[{elements}] row_align(1);
static {ctype} OUT_C[{elements}] row_align(1);

#define NSLOTS {nslots}
static const int SLOT_CODE[NSLOTS] = {{{codes}}};
static const char *SLOT_NAME[NSLOTS] = {{{names}}};

static void probe_arm(void) {{
    counter_reset();
    for (int i = 0; i < NSLOTS; i++) counter_configure(i, SLOT_CODE[i]);
}}

static void probe_report(const char *tag, uint64_t cycles) {{
    printf("PROBE_CYCLES %s %llu\\n", tag, (unsigned long long)cycles);
    for (int i = 0; i < NSLOTS; i++)
        printf("PROBE_COUNTER %s %s %u\\n", tag, SLOT_NAME[i], counter_read(i));
}}

static void compare(const char *tag, const {ctype} *got) {{
    long long diffs = 0, first = -1, sum = 0;
    for (size_t i = 0; i < {elements}; i++) {{
        sum += (long long)got[i];
        if (got[i] != OUT_V[i]) {{ if (first < 0) first = (long long)i; diffs++; }}
    }}
    printf("PROBE_DIFFS %s %lld first=%lld sum=%lld verdict=%s\\n",
           tag, diffs, first, sum, diffs == 0 ? "BIT_EXACT" : "DIFFERS");
}}

{definition_off}
{definition_on}

int main(void) {{
    gemmini_flush(0);
    uint64_t t0, cyc;
    printf("MERLIN_PROFILE warmup begin\\n");
    {vendor}
    {call_b}
    {call_c}
    printf("MERLIN_PROFILE warmup end rc=0\\n");
    printf("MERLIN_PROFILE measured begin\\n");
    probe_arm(); t0 = read_cycles(); {vendor} cyc = read_cycles() - t0; probe_report("vendor", cyc);
    probe_arm(); t0 = read_cycles(); {call_b} cyc = read_cycles() - t0; probe_report("restaged", cyc);
    probe_arm(); t0 = read_cycles(); {call_c} cyc = read_cycles() - t0; probe_report("pinned", cyc);
    compare("restaged", OUT_B);
    compare("pinned", OUT_C);
    printf("PROBE_GROUP {name} elements={elements}\\n");
    printf("MERLIN_PROFILE measured end rc=0\\n");
    return 0;
}}
"""


def _definition(sched, facts, iset, *, symbol, pin, **shape) -> tuple[str, dict]:
    """The recipe's C for one convolution, with the input pinning forced on or off."""
    in_dim, ci, co = shape["in_dim"], shape["ci"], shape["co"]
    kernel, stride, padding = shape["kernel"], shape["stride"], shape["padding"]
    ps, pst, ppad = shape["pool"]
    out_dim = (in_dim + 2 * padding - kernel) // stride + 1
    final = (out_dim + 2 * ppad - ps) // pst + 1 if pst else out_dim
    ops = {
        "input": TensorArg("p_in", (1, in_dim, in_dim, ci), "i8", "read"),
        "weights": TensorArg("p_w", (kernel, kernel, ci, co), "i8", "read"),
        "bias": TensorArg("p_bias", (co,), "i32", "read"),
        "output": TensorArg("p_out", (1, final, final, co), "i8", "write"),
    }
    kern = sched.conv_reference(
        name=symbol,
        batch=1,
        in_dim=in_dim,
        in_channels=ci,
        out_channels=co,
        kernel=kernel,
        stride=stride,
        padding=padding,
        operands=ops,
        relu=shape["relu"],
        scale=shape["scale"],
        facts=facts,
        pool_size=ps,
        pool_stride=pst,
        pool_padding=ppad,
        pin_input=pin,
    )
    return emit_c_function(kern, iset, symbol=symbol), dict(kern.attrs)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--target", required=True)
    parser.add_argument("--name", required=True)
    parser.add_argument("--in-dim", required=True, type=int)
    parser.add_argument("--in-channels", required=True, type=int)
    parser.add_argument("--out-channels", required=True, type=int)
    parser.add_argument("--kernel", required=True, type=int)
    parser.add_argument("--stride", required=True, type=int)
    parser.add_argument("--padding", required=True, type=int)
    parser.add_argument("--pool", default="0,0,0", help="size,stride,padding of a pooled readout")
    parser.add_argument("--scale", default=0.0234375, type=float)
    parser.add_argument("--seed", default=17, type=int)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--emulator", type=Path)
    parser.add_argument("--max-cycles", default="400000000")
    parser.add_argument("--build-only", action="store_true")
    args = parser.parse_args(argv)

    probe = importlib.import_module("conv_shape_counter_probe")

    backend = AB.base.get_backend(args.target)
    iset = backend.sched_instruction_set()
    sched = importlib.import_module(f"merlin._oot_backends.{args.target}.{args.target}_sched")
    harness = Path(backend.rocc_tests_dir())
    compiler = backend.gcc_path()

    pool = tuple(int(p) for p in args.pool.split(","))
    if len(pool) != 3:
        raise SystemExit(f"--pool wants size,stride,padding, got {args.pool!r}")
    shape = dict(
        in_dim=args.in_dim,
        ci=args.in_channels,
        co=args.out_channels,
        kernel=args.kernel,
        stride=args.stride,
        padding=args.padding,
        pool=pool,
        scale=args.scale,
        relu=True,
    )

    case = AB.conv_case(sched, iset.facts, iset, name=args.name, seed=args.seed, **shape)
    off, attrs_off = _definition(sched, iset.facts, iset, symbol=f"{args.name}_off", pin=False, **shape)
    on, attrs_on = _definition(sched, iset.facts, iset, symbol=f"{args.name}_on", pin=True, **shape)
    # The two must differ in the staging and in NOTHING else the attributes record, or the A/B is not
    # of one mode: same tiling, same descriptor count, same reduction, same readout.
    for key in ("tile", "descriptors", "reduction_steps", "readout", "shape"):
        if attrs_off[key] != attrs_on[key]:
            raise SystemExit(f"the two schedules differ in {key}: {attrs_off[key]!r} vs {attrs_on[key]!r}")
    if attrs_off["input_staging"] == attrs_on["input_staging"]:
        raise SystemExit(f"both schedules stage the input the same way ({attrs_on['input_staging']})")

    slots = list(probe.PARTITION) + ["RDMA_BYTES_REC"]
    codes = probe.counter_codes(harness / "include" / "gemmini_counter.h", slots)

    args.out.mkdir(parents=True, exist_ok=True)
    for name, array in case["arrays"].items():
        (args.out / f"{name}.bin").write_bytes(AB.np.ascontiguousarray(array).tobytes())
    blobs = "\n".join(f'BLOB({s}, "{s}.bin", {"acc_t" if s == "BS" else "elem_t"})' for s in case["arrays"])
    actuals = "(elem_t *)IN, (elem_t *)WT, (acc_t *)BS"
    source = args.out / "probe.c"
    source.write_text(
        PROGRAM.format(
            blobs=blobs,
            ctype=case["ctype"],
            elements=case["elements"],
            definition_off=off,
            definition_on=on,
            vendor=case["vendor"],
            call_b=f"{args.name}_off({actuals}, OUT_B);",
            call_c=f"{args.name}_on({actuals}, OUT_C);",
            name=args.name,
            nslots=len(slots),
            codes=", ".join(str(codes[s]) for s in slots),
            names=", ".join(f'"{s}"' for s in slots),
        ),
        encoding="utf-8",
    )

    common = harness / "riscv-tests" / "benchmarks" / "common"
    includes = [
        f"-I{harness / 'riscv-tests'}",
        f"-I{harness / 'riscv-tests' / 'env'}",
        f"-I{harness}",
        f"-I{common}",
    ]
    objects, log = [], []
    for src in (source, common / "syscalls.c", common / "crt.S"):
        unit = args.out / f"{src.stem}.o"
        done = subprocess.run(
            [str(compiler), *AB.CFLAGS, *includes, f"-Wa,-I{args.out}", "-c", str(src), "-o", str(unit)],
            capture_output=True, text=True, cwd=args.out,
        )  # fmt: skip
        log.append(done.stdout + done.stderr)
        if done.returncode:
            (args.out / "build.log").write_text("".join(log), encoding="utf-8")
            raise SystemExit(f"compile of {src.name} failed:\n{done.stderr[-3000:]}")
        objects.append(str(unit))
    elf = args.out / "probe.elf"
    done = subprocess.run(
        [str(compiler), *AB.CFLAGS, "-T", str(common / "test.ld"), *objects, "-o", str(elf)],
        capture_output=True, text=True, cwd=args.out,
    )  # fmt: skip
    (args.out / "build.log").write_text("".join(log) + done.stdout + done.stderr, encoding="utf-8")
    if done.returncode:
        raise SystemExit(f"link failed:\n{done.stderr[-3000:]}")

    try:
        pins = {RTL_PIN: provenance.verify(RTL_PIN)}
        note = None
    except Exception as why:
        pins, note = {}, f"UNKNOWN({type(why).__name__}: {why})"
    (args.out / "case.json").write_text(
        json.dumps(
            {
                "name": args.name,
                "target": args.target,
                "restaged": attrs_off,
                "pinned": attrs_on,
                "provenance": provenance.record(
                    pins=pins,
                    sources=[str(harness / "include" / "gemmini.h")],
                    artifacts={"emulator": str(args.emulator)} if args.emulator else None,
                    extra={"pin_note": note} if note else None,
                ),
                "elf": str(elf),
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"built {elf}")
    print(f"  restaged: {attrs_off['input_staging']}")
    print(f"  pinned:   {attrs_on['input_staging']}")
    if args.build_only or args.emulator is None:
        return 0
    done = subprocess.run(
        [str(args.emulator), str(elf), f"+max-cycles={args.max_cycles}", f"+loadmem={elf}"],
        capture_output=True, text=True, cwd=args.out,
    )  # fmt: skip
    (args.out / "run.log").write_text(done.stdout + done.stderr, encoding="utf-8")
    for line in (done.stdout + done.stderr).splitlines():
        if line.startswith("PROBE_"):
            print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
