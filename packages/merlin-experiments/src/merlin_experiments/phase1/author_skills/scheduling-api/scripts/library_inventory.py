"""Write the library inventory and a per-family pass table you keep current.

    python library_inventory.py                     # writes submission/docs/library_inventory.md
    python library_inventory.py --print             # also prints the inventory
    python library_inventory.py --workspace W --library L --output FILE

Seconds, once at the start and again whenever you like. It lists what the editable compiler library
offers: the scheduling capabilities of the selected release (``scheduling_capabilities(N)`` imported
from ``submission/compiler_library``, else the copy in ``shared-library.json``), the composition
capabilities, and the catalogue mechanisms ``OPTIMIZATION_SUGGESTIONS.json`` finds available for this
target. For each it says whether your own compiler files under ``submission/`` (``compiler_library/``
excluded) import it, read with ``ast``. Then it adds a table with one column per operation family of
the staged public cases (``operation.op`` of their ``capsule.yaml``) where you mark each pass
``used``, ``tried-rejected (evidence path)`` or ``n/a``. Re-running rewrites only the generated part
between its markers and keeps your table. An aid, not a gate. Read-only except ``--output``.
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import sys
from pathlib import Path

DEFAULT_OUTPUT = Path("submission") / "docs" / "library_inventory.md"
SHARED = "shared-library.json"
SUGGESTIONS = "OPTIMIZATION_SUGGESTIONS.json"
DECLARATION = "capsule.yaml"
BEGIN = "<!-- library-inventory:begin (regenerated by library_inventory.py) -->"
END = "<!-- library-inventory:end -->"
TABLE_HEADING = "## Per-family library passes"
#: Author trees and outputs never scanned for imports or declarations.
SKIP_DIRS = frozenset({"compiler_library", "__pycache__", "build", ".git", "selfcheck_out"})
_WORKSPACE_SKIP = frozenset(
    {"submission", "variants", "selfcheck_out", "qa", ".qa_channel", "build", "__pycache__", "evidence", "discovery"}
)
MAX_FILES = 4000
MAX_FILE_BYTES = 2 << 20
MAX_TREE_BYTES = 64 << 20
MAX_FAMILIES = 8


def _load(path: Path):
    try:
        if not path.is_file() or path.stat().st_size > (32 << 20):
            return None
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


# -- what the author's own files import ----------------------------------------------------------------
def imports_of(text, *, direct: bool = False) -> set[str]:
    """Absolute ``merlin`` names one source imports: modules, and ``module.name`` for each imported name
    (a submodule or a symbol; matching against the library decides which). ``direct`` keeps only the
    modules an import statement names itself."""
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return set()
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module and not node.level:
            names.add(node.module)
            if not direct:
                names.update(f"{node.module}.{alias.name}" for alias in node.names)
        elif isinstance(node, ast.Import):
            names.update(alias.name for alias in node.names)
    return {name for name in names if name == "merlin" or name.startswith("merlin.")}


def python_files(tree: Path, *, skip=SKIP_DIRS) -> list[Path]:
    """The ``.py`` files of one author tree, bounded, without the library copy or build outputs."""
    found, total = [], 0
    if not tree.is_dir():
        return found
    for root, dirs, files in os.walk(tree):
        dirs[:] = sorted(d for d in dirs if d not in skip and not os.path.islink(os.path.join(root, d)))
        for name in sorted(files):
            path = Path(root) / name
            if not name.endswith(".py") or path.is_symlink():
                continue
            try:
                size = path.stat().st_size
            except OSError:
                continue
            total += size
            if size > MAX_FILE_BYTES or total > MAX_TREE_BYTES or len(found) >= MAX_FILES:
                return found
            found.append(path)
    return found


def imported_modules(tree: Path, *, skip=SKIP_DIRS, direct: bool = False) -> dict[str, list[str]]:
    """``{imported name: [relative file, ...]}`` over the author's files under ``tree`` (see
    :func:`imports_of` for ``direct``)."""
    tree = Path(tree)
    out: dict[str, list[str]] = {}
    for path in python_files(tree, skip=skip):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        rel = path.relative_to(tree).as_posix()
        for name in imports_of(text, direct=direct):
            out.setdefault(name, []).append(rel)
    return out


def users(modules, symbols, imports: dict[str, list[str]]) -> list[str]:
    """Files importing any of ``modules`` (or one of ``symbols`` from them)."""
    files: set[str] = set()
    for module in modules:
        files.update(imports.get(module) or ())
        for symbol in symbols:
            files.update(imports.get(f"{module}.{symbol}") or ())
    return sorted(files)


# -- what the library offers -----------------------------------------------------------------------------
def manifest(workspace: Path) -> dict:
    """The selected release's ``shared-library.json``: in the workspace, else on ``sys.path`` (the SDK root)."""
    for root in (Path(workspace), *(Path(entry or ".") for entry in sys.path)):
        found = _load(root / SHARED)
        if isinstance(found, dict):
            return found
    return {}


def selected_inventory(workspace: Path) -> int | None:
    value = manifest(workspace).get("inventory_version")
    return value if type(value) is int else None


#: Inventories probed, newest first, when no release manifest names one.
_PROBED = range(64, 15, -1)


def capabilities(workspace: Path, library: Path, version: int | None) -> tuple[dict | None, str]:
    """``scheduling_capabilities(N)`` from the author-visible library (N from the release manifest, else the
    newest the library accepts), else the manifest's own copy."""
    reason = "no library"
    if Path(library).is_dir():
        root = str(Path(library).resolve())
        if root not in sys.path:
            sys.path.insert(0, root)
        try:
            from merlin.compile.scheduling.api_catalog import scheduling_capabilities

            if version is not None:
                return scheduling_capabilities(version), f"scheduling_capabilities({version}) from {library}"
            for probe in _PROBED:
                try:
                    found = scheduling_capabilities(probe)
                except ValueError:
                    continue
                return found, f"scheduling_capabilities({probe}) from {library} (newest it accepts; no {SHARED})"
            reason = "the library accepts no inventory"
        except Exception as exc:  # noqa: BLE001 -- fall back to the manifest and say why
            reason = f"{type(exc).__name__}: {exc}"[:160]
    embedded = manifest(workspace).get("scheduling_capabilities")
    if isinstance(embedded, dict):
        return embedded, f"{SHARED} scheduling_capabilities (import unavailable: {reason})"
    return None, f"unavailable ({reason})"


def _symbol_parts(symbol: str) -> tuple[str, str]:
    module, _, name = str(symbol).replace(":", ".").rpartition(".")
    return module, name


def available(row: dict) -> bool:
    """A catalogue mechanism whose capability requirements are all supported (workload checks aside)."""
    requirements = row.get("requirements")
    if not isinstance(requirements, dict) or row.get("status") == "unsupported":
        return False
    return all(state == "supported" for key, state in requirements.items() if not key.startswith("workload."))


def passes(catalog: dict | None, suggestions: dict | None) -> list[dict]:
    """One row per scheduling capability, composition capability and available catalogue mechanism."""
    rows = []
    for kind, block in (("capability", catalog or {}), ("composition", (catalog or {}).get("composition") or {})):
        for entry in block.get("capabilities") or ():
            if not isinstance(entry, dict) or not entry.get("name"):
                continue
            parts = [_symbol_parts(s) for s in entry.get("symbols") or () if isinstance(s, str)]
            rows.append(
                {
                    "kind": kind,
                    "name": entry["name"],
                    "modules": sorted({m for m, _ in parts if m}),
                    "symbols": sorted({n for _, n in parts if n}),
                    "facet": None,
                    "status": (entry.get("source_availability") or {}).get("status") if kind == "composition" else None,
                    "requires": [str(r) for r in entry.get("requires") or ()],
                }
            )
    for entry in (suggestions or {}).get("all_mechanisms") or ():
        if not isinstance(entry, dict) or not entry.get("id") or not isinstance(entry.get("api"), str):
            continue
        if not available(entry):
            continue
        workload = sorted(
            k for k, v in (entry.get("requirements") or {}).items() if k.startswith("workload.") and v != "supported"
        )
        rows.append(
            {
                "kind": "mechanism",
                "name": entry["id"],
                "modules": [entry["api"]],
                "symbols": [entry["symbol"]] if isinstance(entry.get("symbol"), str) else [],
                "facet": entry.get("family"),
                "status": entry.get("status"),
                "requires": [f"check {w}" for w in workload],
            }
        )
    return rows


# -- the families of the staged public cases ----------------------------------------------------------
def declared_op(text: str) -> str | None:
    """``operation.op`` of one ``capsule.yaml``, read line by line (block style, two-space indent)."""
    inside = False
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line.startswith(" "):
            inside = line.rstrip() == "operation:"
            continue
        if inside and line.startswith("  ") and not line.startswith("   "):
            key, _, value = line.strip().partition(":")
            if key == "op":
                value = value.strip().strip("'\"")
                return value or None
    return None


def families(workspace: Path) -> dict[str, int]:
    """``{op: number of staged public cases}`` from ``<ws>/<group>/<case>/capsule.yaml``."""
    counts: dict[str, int] = {}
    seen = 0
    workspace = Path(workspace)
    try:
        groups = sorted(
            p
            for p in workspace.iterdir()
            if p.is_dir() and not p.is_symlink() and p.name not in _WORKSPACE_SKIP and not p.name.startswith(".")
        )
    except OSError:
        return counts
    for group in groups:
        try:
            cases = sorted(group.iterdir())
        except OSError:
            continue
        for case in cases:
            declaration = case / DECLARATION
            if seen >= MAX_FILES or not declaration.is_file():
                continue
            seen += 1
            try:
                op = declared_op(declaration.read_text(encoding="utf-8", errors="replace")[: 1 << 20])
            except OSError:
                continue
            if op:
                counts[op] = counts.get(op, 0) + 1
    return counts


# -- the document -----------------------------------------------------------------------------------------
def _cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "/")


def _short(module: str) -> str:
    return module[len("merlin.") :] if module.startswith("merlin.") else module


def inventory(
    rows: list[dict], imports: dict[str, list[str]], *, source: str, version, suggestions_found: bool, modules=()
):
    """The generated block (between the markers)."""
    used = [r for r in rows if users(r["modules"], r["symbols"], imports)]
    lines = [
        BEGIN,
        "## Library inventory",
        "",
        f"Inventory {version if version is not None else '?'}; capabilities: {source}; mechanisms: "
        f"{SUGGESTIONS if suggestions_found else SUGGESTIONS + ' not found'}. "
        f"{len(used)} of {len(rows)} passes are imported by your files under submission/ "
        "(compiler_library/ excluded). An import is not use: consume the pass's actual result in emitted code.",
        "",
        "| kind | pass | facet | module | imported by submission/ | requires / status |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        files = users(row["modules"], row["symbols"], imports)
        lines.append(
            "| "
            + " | ".join(
                _cell(v)
                for v in (
                    row["kind"],
                    row["name"],
                    row["facet"] or "-",
                    ", ".join(_short(m) for m in row["modules"]) or "-",
                    (", ".join(files[:3]) + (f" +{len(files) - 3}" if len(files) > 3 else "")) if files else "no",
                    "; ".join(row["requires"][:2]) or row["status"] or "-",
                )
            )
            + " |"
        )
    covered = {m for row in rows for m in row["modules"]}
    other = sorted(name for name in modules if name not in covered)
    if other:
        lines += [
            "",
            "Other library modules your files import (no capability or mechanism row): "
            + ", ".join(f"`{_short(m)}`" for m in other)
            + ".",
        ]
    lines += ["", END]
    return "\n".join(lines) + "\n"


def family_table(rows: list[dict], imports: dict[str, list[str]], counts: dict[str, int]) -> str:
    """The table the author keeps current (written once; re-runs keep it)."""
    ordered = sorted(counts, key=lambda f: (-counts[f], f))
    shown = ordered[:MAX_FAMILIES]
    if len(ordered) > MAX_FAMILIES:
        shown.append("other")
    if not shown:
        shown = ["family"]
    header = ["pass", "in submission/"] + [f"{f} ({counts[f]})" if f in counts else f for f in shown]
    lines = [
        TABLE_HEADING,
        "",
        "Yours to keep current: per family, mark each pass `used`, `tried-rejected (evidence path)` or "
        "`n/a`. Measure before keeping or rejecting a pass (`ab-library-pass`); a pass you never tried "
        "stays `?`.",
        "",
        "| " + " | ".join(header) + " |",
        "|" + "---|" * len(header),
    ]
    listed: set[str] = set()
    for row in rows:
        if row["kind"] == "composition" or row["name"] in listed:
            continue
        listed.add(row["name"])
        imported = "yes" if users(row["modules"], row["symbols"], imports) else "no"
        lines.append("| " + " | ".join([_cell(row["name"]), imported] + ["?"] * len(shown)) + " |")
    return "\n".join(lines) + "\n"


def merge(existing: str | None, block: str, table: str) -> str:
    """Replace the generated block in ``existing`` and keep everything else, the family table included."""
    if not existing:
        return "# Library inventory and pass status\n\n" + block + "\n" + table
    start, end = existing.find(BEGIN), existing.find(END)
    if start >= 0 and end > start:
        text = existing[:start] + block.rstrip("\n") + existing[end + len(END) :]
    else:
        text = existing.rstrip("\n") + "\n\n" + block
    if TABLE_HEADING not in text:
        text = text.rstrip("\n") + "\n\n" + table
    return text


def build(workspace: Path, library: Path) -> dict:
    workspace = Path(workspace)
    version = selected_inventory(workspace)
    catalog, source = capabilities(workspace, library, version)
    suggestions = _load(workspace / SUGGESTIONS)
    rows = passes(catalog, suggestions)
    imports = imported_modules(workspace / "submission")
    return {
        "rows": rows,
        "imports": imports,
        "version": version,
        "block": inventory(
            rows,
            imports,
            source=source,
            version=version,
            suggestions_found=suggestions is not None,
            modules=imported_modules(workspace / "submission", direct=True),
        ),
        "table": family_table(rows, imports, families(workspace)),
        "source": source,
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--workspace", default=".")
    parser.add_argument("--library", default="", help="compiler library root (default: submission/compiler_library)")
    parser.add_argument("--output", default="", help=f"markdown file to write (default: {DEFAULT_OUTPUT})")
    parser.add_argument("--print", action="store_true", help="also print the generated inventory")
    args = parser.parse_args(argv)
    workspace = Path(args.workspace)
    library = Path(args.library) if args.library else workspace / "submission" / "compiler_library"
    result = build(workspace, library)
    output = Path(args.output) if args.output else workspace / DEFAULT_OUTPUT
    try:
        existing = output.read_text(encoding="utf-8") if output.is_file() else None
    except OSError:
        existing = None
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(merge(existing, result["block"], result["table"]), encoding="utf-8")
    rows = result["rows"]
    imported = [r for r in rows if users(r["modules"], r["symbols"], result["imports"])]
    if args.print:
        print(result["block"])
    print(
        json.dumps(
            {
                "output": output.as_posix(),
                "capabilities_source": result["source"],
                "passes": len(rows),
                "imported_by_submission": len(imported),
                "not_imported": [r["name"] for r in rows if r["kind"] != "composition" and r not in imported],
                "kept_family_table": bool(existing and TABLE_HEADING in existing),
            },
            indent=2,
        )
    )
    return 0 if rows else 2


if __name__ == "__main__":
    sys.exit(main())
