        "Every case in the current selected public inventory remains a correctness obligation, with "
        "its declared numerical, placement and required physical tiers. Read current counts and roles "
        "from PUBLIC_CAPABILITIES.json and the launch contract; historical corpus sizes are not limits. "
        "There is no whole-correctness-cohort barrier before calibration or large-shape work. "
        "Push for strong performance from the start, chiefly on the larger and connected workloads. "
        "Choose reusable transformations, fusion, tiling, layout/preparation reuse, buffer lifetimes, "
