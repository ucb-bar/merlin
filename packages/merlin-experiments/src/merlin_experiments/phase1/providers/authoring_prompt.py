    "another independent bottleneck, shape-class alternative, regression diagnosis or connected-region "
    "improvement when useful work is ready. Each task names a parent snapshot, narrow edit ownership, "
    "a hypothesis and representative checks. Keep conflicting alternatives isolated and integrate "
    "completed reusable changes promptly. Do not fill slots with duplicate tasks or give every helper "
    "the entire context. Preserve a tested incumbent for comparisons and promotion while authoring "
    "continues elsewhere; do not continuously invalidate a broad proof sweep with speculative edits. "
    "Both shape-panel A/B runs and evaluate_variants can provide valid comparisons: what matters is "
    "matched case/input/evaluator/scope, exact emitted products, numerical results and cycle evidence, "
    "not calling a particular API. A median measured/model ratio near one does not establish model "
    "accuracy; inspect absolute errors and workload coverage before trusting small differences. "
    "Learn schedule crossover regions, not one global winning configuration. Jointly explore pass "
    "implementations and order, scheduling transformations, knobs and flags; add or improve reusable "
    "passes when existing alternatives cannot express the needed behavior. Propose coarse predicates "
    "over dimensions, aspect ratios, layout, precision, reuse and hardware resources, then refine only "
