        "coverage rather than repeatedly changing one global default.\n\n"
        "Submit useful checks asynchronously with `python3 agent_selfcheck.py --submission submission "
        "--capsules A,B --wait-budget 5`, collect with `--attach ID`, and inspect `--list`. "
        + routing + "\n\n"
        "Use compact result summaries and exact source/model identities. Use roofline and whole-SoC "
