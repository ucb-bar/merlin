"""Standing author instructions shared by the native Codex and OpenCode transports."""


def authoring_prompt() -> str:
    """Required startup discovery precedes authoring; a submitted manifest then enables grading."""
    from .. import joint_control

    if joint_control.selected() is not None:
        return (
            "Build one general compiler in submission/ from the empty backend. TASK.md is the "
            "authoritative launch contract; read it, applicable workspace instructions and the concise "
            "qa/round_brief.md if present. Complete the selected mandatory discovery calls once before "
            "editing or delegating edits. Batch them in one direct attributable script outside submission/, "
            "retain outputs under discovery/, and check qa/workflow_conformance.json. Repeat only failed "
            "calls or calls whose inputs changed. Do not read whole libraries or historical logs for orientation.\n\n"
            "Write a valid manifest and executable entrypoints promptly. First run one tiny applicable "
            "capsule through emission, linking, Spike and all-output comparison. Fix the first shared "
            "contract failure before fanning out affected cases; successful tool startup alone is not "
            "successful target execution. Follow the boundary checklist in TASK.md.\n\n"
            "All selected 250 capsules remain required: 153 original, 20 calibration, 77 scalability. "
            "Prioritize original numerical correctness and reviewed calibration prerequisites while "
            "developing scalable, performant implementations from the start. Required original gSIM "
            "checks follow matching Spike evidence automatically; extra calibration runs require the "
            "declared question/budget. Expected refusals remain refusals. Large cases use Spike, not gSIM. "
            + joint_control.selfcheck_routing_guidance() + "\n\n"
            "Use independent helpers for frontend/graph transforms, scheduling/codegen, and numerical "
            "or performance diagnosis when useful. Give each bounded file ownership, integrate completed "
            "work frequently into the same compiler, and retain reusable passes and semantic/shape/resource "
            "heuristics. Use or adapt the supplied pass library, scheduling abstractions and host codegen "
            "where useful; consume their actual results. Explore aggressively: fusion, preparation reuse, "
            "tiling, resident buffers, compact loops, pipelining, overlap and command/configuration overhead. "
            "The capability-based optimization menu is non-exhaustive guidance, not a prescribed solution.\n\n"
            "Keep authoring while immutable snapshots execute. Submit affected named cases with "
            "`python3 agent_selfcheck.py --submission submission --capsules A,B --wait-budget 5`; "
            "use `--attach ID` for results and `--list` for requests. Concurrent requests share resources; "
            "do not duplicate automatic work or repeat whole-corpus sweeps. Check scalability members with "
            "`--suite scalability --sim spike`. Keep alternative sources small under variants/, merge "
            "winners into submission/, and record changes, hypotheses and evidence in iteration notes.\n\n"
            "Read feedback_brief and source/model identities first. Distinguish numerical failures, "
            "pending required gSIM, model UNKNOWN, provisional estimates and qualified timing. Use "
            "roofline/resource/whole-SoC feedback to attack the largest supported performance gaps, "
            "including host work and synchronization. Prefer the selected tuned model where qualified; "
            "never silently replace it with untuned timing. Continue independent work while calibration "
            "is pending. Do not alter evaluator coefficients, contracts, goldens or private boundaries. "
            "Do not hardcode capsule identities or reference answers. Report only demonstrated results. "
            "Begin now."
        )

    routing = (
        joint_control.selfcheck_routing_guidance()
        if joint_control.selected()
        else "Without `--sim` it runs every tier each capsule declares mandatory, with the grade's own "
        "simulators, and reports a certified pass/fail per capsule; `--sim spike` is only a faster "
        "screen that cannot certify."
    )
    return (
        "Before changing submission/ or delegating compiler edits, read qa/round_brief.md (if present) FIRST, "
        "including its operator errata, then TASK.md, applicable workspace instructions and qa/verdict.json "
        "(if present). Complete every mandatory pre-edit discovery/tool invocation required by those "
        "instructions in the main author transcript before any submission mutation. Reading facts or scaffold "
        "source does not substitute for required tool execution. Keep discovery/scaffold outputs outside "
        "submission/. For reproducible execution evidence, use inline Python or save a discovery script with "
        "a literal quoted heredoc (`cat > /absolute/path/startup.py <<'PY'`) in a separate successful write "
        "command, then execute it in a separate successful Python command without trailing commands or "
        "pipelines that could mask its exit status. Use an absolute script path, or explicitly `cd` to the same "
        "absolute directory with `&&` in both commands. If the source uses any relative path, including a facts "
        "path, use that explicit `cd /absolute/workspace &&` in the writer and executor, or make every path absolute. "
        "Use literal dictionaries/lists for the startup plan. Keep startup Python as direct top-level imports, "
        "assignments and API calls; opaque helper/control-flow "
        "forms cannot provide reproducible discovery evidence. After discovery, read qa/workflow_conformance.json "
        "when present and resolve missing pre-edit discovery evidence before the first submission mutation. "
        "Keep startup bounded: batch the mandatory calls into one attributable script, save full outputs "
        "under discovery/, and print only success/status and artifact paths. Run each required call once "
        "per epoch; repeat only a failed call or one whose inputs changed. Reuse retained discovery notes "
        "for orientation instead of rereading whole libraries. This does not waive any current-epoch "
        "mandatory invocation. Broker request IDs from an earlier epoch are historical: read their "
        "retained results, do not repeatedly attach them to the new broker. "
        "A missing or pending feedback file is not a pass. Keep outputs outside "
        "submission/ until all required pre-edit tool invocations have completed successfully. Then build or "
        "repair the target backend under submission/ per those instructions. During iteration, check the "
        "capsules an edit affects "
        "with `python3 agent_selfcheck.py --submission submission --capsules <names>`. "
        + routing
        + " KEEP WORKING WHILE "
        "CHECKS RUN: add `--wait-budget 5` to get a request id back within seconds, keep editing (each check "
        "grades a snapshot taken when it starts), and collect the verdict later with `python3 agent_selfcheck.py "
        "--attach <id>`; `--list` shows your requests. Several requests may be in flight at once. Put every "
        "capsule an edit affects into ONE comma-separated request rather than one per capsule: they run in "
        "parallel across the CPU pool and per-request overhead dominates small checks. Iterate on named "
        "capsules; `--capsules changed` is a slow sweep that rebuilds every capsule (use it rarely); "
        "`--capsules failing` re-checks what did not pass in your most recent check. To try alternatives side by "
        "side, copy submission/ to variants/<name>/, change the copy, and check it with `--submission "
        "variants/<name>`; variant results are labelled self-check results only, never graded officially, so "
        "copy the winner into submission/. Do not repeatedly grade the whole corpus. Run `--capsules all` only "
        "after the focused checks improve and the candidate is ready for a regression sweep. You may edit "
        "submission/ while a self-check runs; compare the verdict's source digest with your current bytes. "
        "For a promotion sweep, keep the tested candidate frozen and explore in separate variants; "
        "integrate afterwards and recheck only affected cases before another justified milestone sweep. "
        "Goldens are withheld; "
        "iterate until the complete corpus passes. THE FIRST GRADE NEEDS A SUBMISSION AFTER REQUIRED STARTUP "
        "DISCOVERY: the harness "
        "grades submission/, so while submission/manifest.yaml does not exist there is NOTHING to grade and no "
        "verdict can ever arrive -- an absent qa/verdict.json is not a queue you wait in, it means you have not "
        "submitted yet. "
        "After completing the required pre-edit discovery, promptly build something minimal and write "
        "submission/manifest.yaml before waiting for a grade; only once a verdict exists does "
        "waiting for the next one make sense (then use await_verdict.py rather than a poll loop, and do not "
        "launch `--capsules all` merely to refresh it). Use exact capsule directory names for focused checks. "
        "Begin now."
    )
