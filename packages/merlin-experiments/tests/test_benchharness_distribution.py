"""The research harness delegates shared storage/content identities to core."""

import ast
import hashlib
from pathlib import Path

from merlin.common.paths import python_source_dir
from merlin.common.tree_hash import hash_tree


def test_source_digest_is_nonvacuous_under_a_build_ancestor_and_relocatable(tmp_path):
    direct = tmp_path / "source"
    relocated = tmp_path / "out/build/workspaces/source"
    for source in (direct, relocated):
        source.mkdir(parents=True)
        (source / "tool.py").write_bytes(b"original\n")
        (source / "build").mkdir()
        (source / "build" / "generated.py").write_bytes(b"ignored generated bytes\n")
    expected = {
        "present": True,
        "sha256": hashlib.sha256(b"tool.py\0original\n\0").hexdigest(),
        "n_files": 1,
    }
    assert hash_tree(direct) == hash_tree(relocated) == expected
    (relocated / "tool.py").write_bytes(b"changed\n")
    assert hash_tree(relocated)["sha256"] != expected["sha256"]
    assert hash_tree(direct) == expected


def test_harness_reexports_shared_functions_by_identity():
    from merlin import benchharness
    from merlin.common import paths, tree_hash

    assert benchharness.hash_tree is tree_hash.hash_tree
    assert benchharness._SKIP is tree_hash._SKIP
    assert benchharness.runs_root is paths.runs_root
    assert "merlin-experiments" in Path(benchharness.__file__).parts


def test_core_source_does_not_import_the_optional_benchmark_harness():
    failures = []
    for path in (python_source_dir() / "merlin").rglob("*.py"):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.ImportFrom) and "benchharness" in (node.module or "").split("."):
                failures.append(str(path.relative_to(python_source_dir())))
    assert failures == []


def test_target_specific_conformance_is_not_shipped_by_merlin():
    from importlib.util import find_spec

    for module in (
        "merlin.targetgen.eval.gemmini_conformance",
        "merlin.targetgen.eval.gemmini_suite",
        "merlin.targetgen.eval.gemmini_dispatcher",
        "merlin.targetgen.agent.gemmini_kernel_slot",
    ):
        assert find_spec(module) is None
    assert not (python_source_dir() / "merlin/targetgen/eval").exists()
