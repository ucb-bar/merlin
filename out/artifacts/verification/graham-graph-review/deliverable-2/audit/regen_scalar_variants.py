"""Regenerate the retained scalar chain variants locally and bind them to the seal.

Graham independent review (agent), 2026-10-26. The sealed zero-chain and
nested-chain buffers are absent locally (D1-G03). This script rebuilds the
source text from the frozen test generator, runs the implementation's own
capture CLI as the SUBJECT (pinned producer checkout, local xDSL), emits the
implementation's chain query, and compares every regenerated byte string with
the hash recorded in graph-state-scalar/review/sealed-v1/MANIFEST.json. A hash
match binds the regenerated bytes to the sealed ones; it is not a replay of the
original qualification and grants no proof authority. Lean is run without `-o`
against the pre-existing local development build (read-only).
"""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path("/home/grammy/blast/merlin-pass-verification")
PRODUCER = REPO / "out/build/upstreams/merlin-graph-proof-intake"
OUT = REPO / "out/artifacts/verification/graham-graph-review/deliverable-2/probes/scalar-variants"
MANIFEST = REPO / "out/artifacts/verification/graph-state-scalar/review/sealed-v1/MANIFEST.json"
CAPTURE = REPO / "src/merlin/verify/lean_graph_state_scalar_capture.py"
TESTS = REPO / "merlin/tests/ir/test_lean_graph_state_scalar.py"
LEAN = Path("/home/grammy/.elan/toolchains/leanprover--lean4---v4.35.0/bin/lean")
LEAN_LIB = REPO / "out/build/verification-setup/20261025/graph-smoke-MJ63mO/lib/lean"
PYTHON = REPO / ".venv/bin/python"


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def generator_cases():
    text = TESTS.read_text()
    start, stop = text.index("def redundant("), text.index("\ndef produce(")
    namespace = {}
    exec(compile(text[start:stop], str(TESTS), "exec"), namespace)  # test data only
    return namespace["CASES"]


def capture(source, destination, target=None, middle=None, mode="chain"):
    command = [str(PYTHON), str(CAPTURE), "--reference", str(PRODUCER), "--source", str(source),
               "--destination", str(destination), "--mode", mode]
    if target is not None:
        command += ["--target", str(target)]
    if middle is not None:
        command += ["--middle", str(middle)]
    env = {**os.environ, "PYTHONPATH": str(PRODUCER / "src"), "PYTHONDONTWRITEBYTECODE": "1"}
    done = subprocess.run(command, cwd=PRODUCER, env=env, capture_output=True, text=True, timeout=120)
    return {"command": command[1:], "returncode": done.returncode, "stdout": done.stdout, "stderr": done.stderr}


def main():
    sealed = {row["path"]: row["sha256"] for row in json.loads(MANIFEST.read_text())["files"]}
    prefix = "out/artifacts/verification/graph-state-scalar/qualification-v1/originals/"
    cases = generator_cases()
    sys.path.insert(0, str(REPO / "src"))
    from merlin.verify.lean_graph_state_scalar_chain import emit_chain_query  # subject, not oracle

    report = {"reviewer": "Graham independent review (agent)", "date": "2026-10-26",
              "producer_head": subprocess.run(["git", "-C", str(PRODUCER), "rev-parse", "HEAD"], capture_output=True,
                                              text=True).stdout.strip(),
              "capture_source_sha256": sha(CAPTURE), "test_generator_sha256": sha(TESTS),
              "lean_sha256": sha(LEAN), "lean_library": str(LEAN_LIB),
              "note": "local re-execution under local xDSL 0.68.0/Python 3.12; not the original qualification",
              "cases": {}}
    OUT.mkdir(parents=True, exist_ok=False)
    for name in ("chain", "zero-chain", "nested-chain"):
        mode, text = cases[name]
        root = OUT / name
        root.mkdir()
        (root / "source.mlir").write_text(text)
        first = capture(root / "source.mlir", root / "actual", mode=mode)
        second = capture(root / "source.mlir", root / "checked-projection", target=root / "actual/after.mlir",
                         middle=root / "actual/middle.mlir", mode="chain")
        row = {"captures": [first, second]}
        projection = json.loads((root / "checked-projection/projection.json").read_text())
        if projection.get("projection_checked"):
            query, roots = emit_chain_query(projection)
            (root / "GraphStateScalarInstance.lean").write_text(query)
            env = {**os.environ, "LEAN_PATH": str(LEAN_LIB)}
            done = subprocess.run([str(LEAN), "GraphStateScalarInstance.lean"], cwd=root, env=env,
                                  capture_output=True, text=True, timeout=600)
            (root / "lean.stdout").write_text(done.stdout)
            (root / "lean.stderr").write_text(done.stderr)
            row["lean_returncode_no_output_object"] = done.returncode
            row["roots"] = roots
        comparisons = {}
        for local, sealed_rel in (
            ("source.mlir", "source.mlir"),
            ("actual/before.mlir", "actual/before.mlir"),
            ("actual/middle.mlir", "actual/middle.mlir"),
            ("actual/after.mlir", "actual/after.mlir"),
            ("actual/stage-000.mlir", "actual/stage-000.mlir"),
            ("actual/stage-001.mlir", "actual/stage-001.mlir"),
            ("actual/projection.json", "actual/projection.json"),
            ("checked-projection/projection.json", "checked/projection/projection.json"),
            ("GraphStateScalarInstance.lean", "checked/kernel/GraphStateScalarInstance.lean"),
        ):
            key = prefix + name + "/" + sealed_rel
            path = root / local
            comparisons[local] = {
                "sealed_sha256": sealed.get(key),
                "local_sha256": sha(path) if path.exists() else None,
                "match": path.exists() and sealed.get(key) == sha(path),
            }
        row["comparisons"] = comparisons
        report["cases"][name] = row
    (OUT / "REGENERATION.json").write_text(json.dumps(report, indent=2) + "\n")
    for name, row in report["cases"].items():
        print(name, row.get("lean_returncode_no_output_object"),
              {k: v["match"] for k, v in row["comparisons"].items()})


if __name__ == "__main__":
    main()
