class Trap(Exception):
    pass


def interpret(module, seeds, caller_value):
    functions = {dict(fn.props)["sym_name"].strip('"'): fn for fn in module.ops}
    heap = {"caller": {"shape": [1], "cells": {0: caller_value}, "live": True}}
    trace, fresh = [], itertools.count()

    def width(ty):
        return int(ty[1:]) if ty.startswith("i") and ty[1:].isdigit() else None

    def call(fn, args):
        block = fn.regions[0][0]
        env = {name: value for (name, _), value in zip(block.args, args)}
        return run(block, env)

    def cell(buffer, indices):
        state = heap[buffer]
        if not state["live"]:
            raise Trap("access after free")
        flat = 0
        for index, size in zip(indices, state["shape"]):
            if not 0 <= index < size:
                raise Trap("out of bounds")
            flat = flat * size + index
        return state, flat

    def run(block, env):
        for op in block.ops:
            ins = [env[v] for v in op.operands]
            name = op.name
            if name in ("func.return", "scf.yield"):
                return ins
            if name == "arith.constant":
                value = int(dict(op.props)["value"].rpartition(":")[0])
                outs = [value]
            elif name in ("arith.addi", "arith.subi", "arith.muli"):
                a, b = ins
                raw = {"arith.addi": a + b, "arith.subi": a - b, "arith.muli": a * b}[name]
                w = width(op.result_types[0])
                outs = [raw % (1 << w) if w else raw]
            elif name == "arith.minui":
                outs = [min(ins)]
            elif name == "memref.alloc":
                ident = f"heap{next(fresh)}"
                shape = [int(x) for x in op.result_types[0][7:-1].split("x")[:-1]]
                heap[ident] = {"shape": shape, "cells": {}, "live": True}
                outs = [ident]
            elif name == "memref.dealloc":
                if not heap[ins[0]]["live"]:
                    raise Trap("double free")
                heap[ins[0]]["live"] = False
                outs = []
            elif name == "memref.store":
                state, flat = cell(ins[1], ins[2:])
                state["cells"][flat] = ins[0]
                outs = []
            elif name == "memref.load":
                state, flat = cell(ins[0], ins[1:])
                if flat not in state["cells"]:
                    raise Trap("read of uninitialized (poisoned) cell")
                outs = [state["cells"][flat]]
            elif name == "memref.dim":
                outs = [heap[ins[0]]["shape"][ins[1]]]
            elif name == "func.call":
                callee = dict(op.props)["callee"].lstrip("@")
                trace.append((callee, tuple(v if isinstance(v, int) else "buffer" for v in ins)))
                outs = call(functions[callee], ins)
            elif name == "scf.for":
                lb, ub, st = ins[:3]
                carried = ins[3:]
                inner = op.regions[0][0]
                iv = lb
                while iv < ub:
                    local = dict(env)
                    local[inner.args[0][0]] = iv
                    for (arg, _), v in zip(inner.args[1:], carried):
                        local[arg] = v
                    carried = run(inner, local)
                    env.update({k: v for k, v in local.items() if k not in env})
                    iv += st
                outs = carried
            else:
                raise Trap(f"uninterpreted operation {name}")
            for result, value in zip(op.results, outs):
                env[result] = value
        raise Trap("missing terminator")

    try:
        returned = call(functions["kernel"], [*seeds, "caller"])
        outcome = ("ok", tuple(returned))
    except Trap as error:
        outcome = ("trap", str(error))
    return outcome, heap["caller"]["cells"].get(0), tuple(trace)


