def canonical(module):
    """Functions as nested tuples with SSA names replaced by definition order."""
    out = []
    for fn in module.ops:
        names = {}

        def define(name):
            names[name] = f"v{len(names)}"
            return names[name]

        def op_form(op):
            operands = tuple(names.get(v, "UNBOUND:" + v) for v in op.operands)
            for name in op.results:
                define(name)
            regions = []
            for region in op.regions:
                blocks = []
                for block in region:
                    args = tuple((define(n), t) for n, t in block.args)
                    blocks.append((args, tuple(op_form(child) for child in block.ops)))
                regions.append(tuple(blocks))
            props = tuple((k, v) for k, v in M.canonical_props(op))
            return (op.name, props, operands, tuple(op.operand_types), tuple(op.result_types), tuple(regions))

        out.append(op_form(fn))
    return out


def first_difference(a, b, path="root"):
    if type(a) is not type(b):
        return f"{path}: {a!r:.120} != {b!r:.120}"
    if isinstance(a, tuple | list):
        if len(a) != len(b):
            return f"{path}: length {len(a)} != {len(b)}: {a!r:.200} / {b!r:.200}"
        for k, (x, y) in enumerate(zip(a, b)):
            found = first_difference(x, y, f"{path}[{k}]")
            if found:
                return found
        return None
    return None if a == b else f"{path}: {a!r:.120} != {b!r:.120}"


def rename(ops, mapping):
    for op in M.walk(ops):
        op.operands = [mapping.get(v, v) for v in op.operands]


def owner(module):
    return next(fn for fn in module.ops if any(op.name == "memref.alloc" for op in fn.regions[0][0].ops))


def expected_middle(before):
    """Reviewer specification of the two-epoch reuse: one physical slot, both epochs."""
    module = copy.deepcopy(before)
    body = owner(module).regions[0][0]
    allocs = [op for op in body.ops if op.name == "memref.alloc"]
    frees = [op for op in body.ops if op.name == "memref.dealloc"]
    assert len(allocs) == 2 and len(frees) == 2
    first, second = allocs
    if first.result_types != second.result_types or M.canonical_props(first) != M.canonical_props(second):
        raise ValueError("reviewer spec: epochs are not slot-compatible")
    if frees[0].operands != first.results:
        raise ValueError("reviewer spec: first free is not the first epoch")
    if body.ops.index(frees[0]) > body.ops.index(second):
        raise ValueError("reviewer spec: epochs overlap")
    body.ops = [op for op in body.ops if op is not frees[0] and op is not second]
    rename(body.ops, {second.results[0]: first.results[0]})
    return module


def expected_after(middle, tile):
    """Reviewer specification of segmentation of every owner-level initializer nest."""
    module = copy.deepcopy(middle)
    body = owner(module).regions[0][0]
    new_ops, counter = [], itertools.count()
    for op in body.ops:
        if op.name != "scf.for" or op.result_types:
            new_ops.append(op)
            continue
        lower, upper, step = op.operands
        k = next(counter)
        stride, base, total, end = (f"%seg{k}_{n}" for n in ("stride", "base", "sum", "end"))
        new_ops.append(M.Op("arith.constant", [stride], ["index"], [], [], {"value": f"{tile}:index"}, {}, []))
        inner = M.Op("scf.for", [], [], [base, end, step], ["index"] * 3, {}, {}, op.regions)
        add = M.Op("arith.addi", [total], ["index"], [base, stride], ["index", "index"],
                   {"overflowFlags": "#arith.overflow<none>"}, {}, [])
        minimum = M.Op("arith.minui", [end], ["index"], [total, upper], ["index", "index"], {}, {}, [])
        terminator = M.Op("scf.yield", [], [], [], [], {}, {}, [])
        outer_block = M.Block([(base, "index")], [add, minimum, inner, terminator])
        new_ops.append(M.Op("scf.for", [], [], [lower, upper, stride], ["index"] * 3, {}, {}, [[outer_block]]))
    body.ops = new_ops
    return module


