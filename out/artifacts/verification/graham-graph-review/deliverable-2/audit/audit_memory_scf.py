def query_facts():
    model = json.loads((REGEN / "model.json").read_text())
    query = (REGEN / "Obligation.lean").read_text()
    facts = {"model_sha256": sha(REGEN / "model.json"), "query_sha256": sha(REGEN / "Obligation.lean")}
    rows = []
    for config in model["configurations"]:
        seg = config["segment"]
        rows.append({
            "object": config["object"],
            "sourceBody==targetBody(identical python strings)": seg["sourceBody"] == seg["targetBody"],
            "sourceContext==targetContext(identical python strings)": seg["sourceContext"] == seg["targetContext"],
            "middleInitializer==key-derived": config["middleInitializer"] == config["middleInitializer"],
            "after-derived naturals": {k: seg[k] for k in ("targetLower", "targetUpper", "targetStride",
                                                           "targetInnerStep", "outerIV", "strideValue", "upperValue",
                                                           "addResult", "minResult")},
            "after-derived lists": {k: seg[k] for k in ("addOperands", "minOperands", "innerOperands", "outerYield")},
            "lean_occurrences_of_sourceContext_string": query.count(json.dumps(seg["sourceContext"])[1:-1][:200]),
        })
    facts["segments"] = rows
    reuse = model["reuse"]
    facts["reuse_contexts_identical"] = reuse["sourceContext"] == reuse["targetContext"]
    facts["reuse_context_in_query"] = reuse["sourceContext"][:200] in query
    facts["instructions"] = [{k: v for k, v in row.items() if k != "key"} | {"key_prefix": row.get("key", "")[:60]}
                             for row in reuse["instructions"]]
    facts["reuseMiddle_emitted_twice_from_one_value"] = query.count("reuseMiddle := ") == 1 and query.count(
        "segmentationMiddle := ") == 1
    return facts


def main():
    modules = {k: M.read(p.read_text()) for k, p in BUFFERS.items()}
    report = {"reviewer": "Graham independent review (agent)", "date": "2026-10-26",
              "script_sha256": sha(__file__), "reader_sha256": sha(M.__file__), "imports_implementation": False,
              "buffers": {k: {"path": str(p), "sha256": sha(p)} for k, p in BUFFERS.items()},
              "operation_counts": {k: sum(1 for _ in M.walk(m.ops)) for k, m in modules.items()},
              "functions": {k: [dict(fn.props)["sym_name"] for fn in m.ops] for k, m in modules.items()}}
    spec_middle = expected_middle(modules["before"])
    spec_after = expected_after(modules["middle"], 2)
    report["reuse_spec_vs_retained_middle"] = first_difference(canonical(spec_middle), canonical(modules["middle"])) or "equal"
    report["segment_spec_vs_retained_after"] = first_difference(canonical(spec_after), canonical(modules["after"])) or "equal"
    report["untouched_functions_equal_across_stages"] = all(
        canonical(modules["before"])[k] == canonical(modules["middle"])[k] == canonical(modules["after"])[k]
        for k, fn in enumerate(modules["before"].ops) if fn is not owner(modules["before"]))
    grid = [(-7, 5), (0, 0), (1, 2), (17, 34), (2147483647, -2147483648), (123456, -98765)]
    runs, mismatches = [], []
    for seeds in grid:
        for caller in (0, 3, -11):
            results = {k: interpret(m, [s % (1 << 32) for s in seeds], caller % (1 << 32)) for k, m in modules.items()}
            runs.append({"seeds": seeds, "caller": caller, "before": repr(results["before"])})
            if not results["before"] == results["middle"] == results["after"]:
                mismatches.append({"seeds": seeds, "caller": caller, **{k: repr(v) for k, v in results.items()}})
    report["differential"] = {"runs": len(runs), "mismatches": mismatches, "sample": runs[:3],
                              "model": "i32 wrapping; index unbounded nonnegative; fresh allocation cells poisoned "
                                       "(read traps); freed buffer access traps; func.call executes the local callee"}
    if REGEN.exists():
        report["implementation_query"] = query_facts()
    out = D2 / "audit/audit_memory_scf.out.json"
    out.write_text(json.dumps(report, indent=2, default=str) + "\n")
    print(json.dumps({k: report[k] for k in ("operation_counts", "reuse_spec_vs_retained_middle",
                                             "segment_spec_vs_retained_after",
                                             "untouched_functions_equal_across_stages")}, indent=1))
    print("differential mismatches:", len(mismatches), "runs:", len(runs), report["differential"]["sample"][0])


if __name__ == "__main__":
    main()
