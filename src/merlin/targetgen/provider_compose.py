"""Layered support providers: materialize a provider's effective contract from its base + overlay.

A support provider declared with ``schema: merlin.provider.v2`` and ``extends: {target: <base>, ...}``
authors only the DELTA to its base, in ``contracts/overlay.yaml``. Everything downstream (target
resolution, plugin loading, capability readers, the whole-model routes) reads one flat
``contracts/target_contract.yaml``, so the composition is MATERIALIZED rather than performed at every
read: this module writes that file, marked generated, plus ``contracts/composed.lock.yaml`` naming the
exact base revision and the digests it was composed from. ``--check`` recomputes and fails on drift,
which is how a layer notices its base moved.

Merge rules (base ⊕ overlay, overlay wins):

* mappings merge recursively;
* lists of mappings that all carry ``name`` merge item-by-name (same name merges, new names append);
* lists of scalars are a set union in first-seen order;
* anything else is replaced by the overlay's value;
* the overlay may list dotted paths under ``replace:`` (take the overlay's value wholesale) and
  ``remove:`` (drop that path from the base before merging);
* the base's ``plugin`` block is NEVER inherited: a plugin reference must resolve inside the package
  that declares it, and a layer that wants a base's executable support declares its own plugin;
* ``name`` is always the layer's own target.

Resolution of the base never fetches: it looks first at the layer's own submodules (a chip package
carries its base as one, e.g. at ``base/<base>-mlir``), then the ``MERLIN_TARGET_PATH`` selection (unset:
the vendored ``examples/*/support`` and the pinned packages fetched at their pins), the generated home
(``out/build/generated/``), then the checkout's vendored ``examples/*/support``. Use
``merlin-target-fetch`` (which follows ``extends`` chains) to bring an absent base in first.

Single base: when the checkout pins a base (:mod:`merlin.targetgen.support_pins`), a layer over that
target must declare ``extends.commit`` equal to the pin, and the base it is composed from must be at that
revision; anything else is refused with the command that fixes it.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import subprocess
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from merlin.common.yaml import safe_load_text

from .providers import Provider, ProviderError, ProviderRole, read_provider

LOCK_FILE = "contracts/composed.lock.yaml"
LOCK_SCHEMA = "merlin.provider_compose.v1"
_DIRECTIVES = ("replace", "remove")
_NOT_INHERITED = ("plugin",)
_HEADER = (
    "# GENERATED by merlin-target-compose: the effective contract of a layered support provider.\n"
    "# Do not edit. Edit {overlay} (this layer's delta) and re-run `merlin-target-compose <provider root>`.\n"
    "# Base: {base_target} @ {base_revision} -- see {lock}.\n"
)


class ComposeError(ProviderError):
    """A layered provider cannot be composed (absent base, revision mismatch, cycle, bad overlay)."""


# ── merge ────────────────────────────────────────────────────────────────────────────────────────


def _is_named_list(value: Any) -> bool:
    return isinstance(value, list) and all(isinstance(i, dict) and "name" in i for i in value)


def _is_scalar_list(value: Any) -> bool:
    return isinstance(value, list) and all(not isinstance(i, (dict, list)) for i in value)


def merge(base: Any, overlay: Any) -> Any:
    """Deep-merge ``overlay`` onto ``base`` (neither is mutated)."""
    if isinstance(base, dict) and isinstance(overlay, dict):
        out = copy.deepcopy(base)
        for key, value in overlay.items():
            out[key] = merge(out[key], value) if key in out else copy.deepcopy(value)
        return out
    if _is_named_list(base) and _is_named_list(overlay) and base and overlay:
        out = [copy.deepcopy(i) for i in base]
        index = {item["name"]: n for n, item in enumerate(out)}
        for item in overlay:
            if item["name"] in index:
                out[index[item["name"]]] = merge(out[index[item["name"]]], item)
            else:
                index[item["name"]] = len(out)
                out.append(copy.deepcopy(item))
        return out
    if _is_scalar_list(base) and _is_scalar_list(overlay):
        out = list(base)
        for item in overlay:
            if item not in out:
                out.append(item)
        return out
    return copy.deepcopy(overlay)


def _split(path: str, *, where: str) -> list[str]:
    parts = path.split(".")
    if not path or any(not p for p in parts):
        raise ComposeError(f"{where}: invalid dotted path {path!r}")
    return parts


def _pop_path(doc: dict[str, Any], parts: list[str], *, where: str) -> Any:
    node: Any = doc
    for part in parts[:-1]:
        if not isinstance(node, dict) or part not in node:
            raise ComposeError(f"{where}: path {'.'.join(parts)!r} does not exist in the base")
        node = node[part]
    if not isinstance(node, dict) or parts[-1] not in node:
        raise ComposeError(f"{where}: path {'.'.join(parts)!r} does not exist in the base")
    return node.pop(parts[-1])


def _get_path(doc: dict[str, Any], parts: list[str]) -> tuple[bool, Any]:
    node: Any = doc
    for part in parts:
        if not isinstance(node, dict) or part not in node:
            return False, None
        node = node[part]
    return True, node


def _set_path(doc: dict[str, Any], parts: list[str], value: Any) -> None:
    node = doc
    for part in parts[:-1]:
        node = node.setdefault(part, {})
    node[parts[-1]] = copy.deepcopy(value)


def compose(base: dict[str, Any], overlay: dict[str, Any], *, target: str, where: str = "overlay") -> dict[str, Any]:
    """The effective contract of a layer named ``target`` over ``base``."""
    if not isinstance(base, dict) or not isinstance(overlay, dict):
        raise ComposeError(f"{where}: base contract and overlay must both be mappings")
    if "name" in overlay and overlay["name"] != target:
        raise ComposeError(f"{where}: overlay names {overlay['name']!r} but the provider declares {target!r}")
    directives = {key: overlay.get(key) or [] for key in _DIRECTIVES}
    for key, paths in directives.items():
        if not isinstance(paths, list) or not all(isinstance(p, str) for p in paths):
            raise ComposeError(f"{where}: {key} must be a list of dotted paths")
    body = {k: v for k, v in overlay.items() if k not in _DIRECTIVES}
    effective = {k: copy.deepcopy(v) for k, v in base.items() if k not in _NOT_INHERITED}
    for path in directives["remove"]:
        _pop_path(effective, _split(path, where=where), where=where)
    replaced: dict[str, Any] = {}
    for path in directives["replace"]:
        parts = _split(path, where=where)
        present, value = _get_path(body, parts)
        if not present:
            raise ComposeError(f"{where}: replace names {path!r} but the overlay does not set it")
        replaced[path] = value
    effective = merge(effective, body)
    for path, value in replaced.items():
        _set_path(effective, _split(path, where=where), value)
    effective["name"] = target
    return effective


# ── base resolution ──────────────────────────────────────────────────────────────────────────────


def provider_revision(root: Path) -> str | None:
    """The source revision a provider root's bytes come from, or None when nothing records one.

    A vendored provider (``examples/<x>/support``) is described by its sibling ``SOURCE.yaml``; a
    fetched clone is its own git top level. A directory inside some OTHER repository's tree is not
    attributed that repository's HEAD -- that would name the wrong bytes.
    """
    root = Path(root).resolve()
    source = root.parent / "SOURCE.yaml"
    if source.is_file():
        try:
            doc = safe_load_text(source.read_text(encoding="utf-8")) or {}
        except (OSError, yaml.YAMLError):
            doc = {}
        if isinstance(doc, dict) and str(doc.get("path") or "") == root.name:
            commit = (doc.get("source") or {}).get("commit")
            return str(commit) if commit else None
    try:
        top = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--show-toplevel", "HEAD"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout.split()
    except (OSError, subprocess.CalledProcessError):
        return None
    if len(top) == 2 and Path(top[0]).resolve() == root:
        return top[1]
    return None


def _candidate_roots() -> list[Path]:
    from . import target_registry as registry

    roots = [*registry._env_target_roots(), registry.generated_target_home()]
    roots.extend(p for p in registry.in_repo_support().values() if p not in roots)
    return roots


def layer_bases(root: str | Path) -> list[Path]:
    """The checked-out submodules a layer carries (its own copy of its base), as base candidates.

    A submodule that is not checked out contributes nothing; whichever copy is found, its revision is
    still checked against ``extends.commit`` and the checkout's base pin.
    """
    root = Path(root).resolve()
    if not (root / ".gitmodules").is_file():
        return []
    from .oot_fetch import FetchError, submodules

    try:
        paths = submodules(root)
    except FetchError:
        return []
    return [root / path for path in sorted(paths) if (root / path / "provider.yaml").is_file()]


def _check_single_base(provider: Provider) -> None:
    from .support_pins import PinError, check_single_base

    try:
        check_single_base(provider)
    except PinError as exc:
        raise ComposeError(f"{provider.root}: {exc}") from exc


def resolve_base(provider: Provider, *, search: Sequence[Path] | None = None) -> Provider:
    """The support provider ``provider`` extends, found without fetching."""
    if provider.extends is None:
        raise ComposeError(f"{provider.root}: provider does not extend another")
    want = provider.extends.target
    entries = list(search) if search is not None else [*layer_bases(provider.root), *_candidate_roots()]
    me = provider.root.resolve()
    for entry in entries:
        entry = Path(entry)
        if entry.resolve() == me:
            continue  # the layer itself may be selected and, mid-composition, not yet materialized
        if (entry / "provider.yaml").is_file() or (entry / "contracts" / "target_contract.yaml").is_file():
            candidates = [entry]
        elif entry.is_dir():
            candidates = [c for c in sorted(entry.iterdir()) if c.resolve() != me]
        else:
            candidates = []
        for root in candidates:
            root = root.resolve()
            if not ((root / "provider.yaml").is_file() or (root / "contracts" / "target_contract.yaml").is_file()):
                continue
            # Identify by declaration first: an unrelated, not-yet-materialized layer on the same path
            # must not block this one. The base itself, once matched, must be materialized.
            found = read_provider(root, materialized=False)
            if found is None or found.role != ProviderRole.SUPPORT or found.target != want:
                continue
            return read_provider(root)
    hint = (
        f" (fetch it with `merlin-target-fetch {want}`"
        + (f" from {provider.extends.repo}" if provider.extends.repo else "")
        + ")"
    )
    raise ComposeError(f"{provider.root}: base support provider {want!r} is not selected, generated or vendored{hint}")


def chain(provider: Provider, *, search: Sequence[Path] | None = None) -> list[Provider]:
    """``[root-most base, ..., provider]``; refuses cycles."""
    seen = [provider]
    while seen[0].extends is not None:
        base = resolve_base(seen[0], search=search)
        if any(p.root.resolve() == base.root.resolve() or p.target == base.target for p in seen):
            names = " -> ".join(p.target for p in reversed([base, *seen]))
            raise ComposeError(f"{provider.root}: extends cycle: {names}")
        seen.insert(0, base)
    return seen


# ── materialization ──────────────────────────────────────────────────────────────────────────────


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _load(path: Path) -> dict[str, Any]:
    try:
        doc = safe_load_text(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        raise ComposeError(f"{path}: cannot read: {exc}") from exc
    if not isinstance(doc, dict):
        raise ComposeError(f"{path}: expected a mapping")
    return doc


def _strip_header(text: str) -> str:
    lines = text.splitlines(keepends=True)
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    return "".join(lines)


@dataclass(frozen=True)
class Composition:
    provider: Provider
    base: Provider
    base_revision: str | None
    text: str
    lock: dict[str, Any]


def composition(root: str | Path, *, search: Sequence[Path] | None = None) -> Composition:
    """Compute (without writing) the effective contract of the layered provider at ``root``."""
    provider = _layered(root)
    _check_single_base(provider)
    base = resolve_base(provider, search=search)
    if base.contract_path is None:
        raise ComposeError(f"{base.root}: base provider has no contract")
    chain(provider, search=search)  # refuse cycles before trusting the base
    revision = provider_revision(base.root)
    pinned = provider.extends.commit
    if pinned is not None and revision != pinned:
        raise ComposeError(
            f"{provider.root}: extends {base.target!r} pinned at {pinned} but the resolved base "
            f"{base.root} is at {revision or 'an unrecorded revision'}"
        )
    base_bytes = base.contract_path.read_bytes()
    overlay_path = provider.overlay_path
    overlay_bytes = overlay_path.read_bytes()
    effective = compose(_load(base.contract_path), _load(overlay_path), target=provider.target, where=str(overlay_path))
    body = yaml.safe_dump(effective, sort_keys=False, default_flow_style=False, width=100, allow_unicode=True)
    header = _HEADER.format(
        overlay=provider.extends.overlay,
        base_target=base.target,
        base_revision=revision or "unrecorded",
        lock=LOCK_FILE,
    )
    lock = {
        "schema": LOCK_SCHEMA,
        "target": provider.target,
        "provider_id": provider.id,
        "base": {
            "target": base.target,
            "provider_id": base.id,
            "revision": revision,
            "pinned": pinned,
            "repo": provider.extends.repo,
            "contract_sha256": _sha256(base_bytes),
            "not_inherited": list(_NOT_INHERITED),
        },
        "overlay": {"path": provider.extends.overlay, "sha256": _sha256(overlay_bytes)},
        "effective": {"path": _relative(provider.contract_path, provider.root), "sha256": _sha256(body.encode())},
    }
    return Composition(provider, base, revision, header + body, lock)


def _relative(path: Path | None, root: Path) -> str:
    assert path is not None
    return path.resolve().relative_to(root.resolve()).as_posix()


def _layered(root: str | Path) -> Provider:
    root = Path(root).resolve()
    provider = read_provider(root, materialized=False)
    if provider is None or provider.role != ProviderRole.SUPPORT:
        raise ComposeError(f"{root}: not a support provider")
    if provider.extends is None:
        raise ComposeError(f"{root}: provider does not declare extends")
    return provider


def materialize(
    root: str | Path, *, check: bool = False, search: Sequence[Path] | None = None
) -> tuple[bool, Composition]:
    """Write (or, with ``check``, only compare) the effective contract and lock. Returns ``(fresh, c)``:
    ``fresh`` is whether the files on disk already matched before this call."""
    comp = composition(root, search=search)
    contract = comp.provider.contract_path
    assert contract is not None
    lock_path = comp.provider.root / LOCK_FILE
    lock_text = yaml.safe_dump(comp.lock, sort_keys=False, default_flow_style=False, width=100)
    current = contract.read_text(encoding="utf-8") if contract.is_file() else ""
    current_lock = lock_path.read_text(encoding="utf-8") if lock_path.is_file() else ""
    fresh = _strip_header(current) == _strip_header(comp.text) and current_lock == lock_text
    if not check and not fresh:
        contract.parent.mkdir(parents=True, exist_ok=True)
        contract.write_text(comp.text, encoding="utf-8")
        lock_path.parent.mkdir(parents=True, exist_ok=True)
        lock_path.write_text(lock_text, encoding="utf-8")
    return fresh, comp


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="merlin-target-compose",
        description="Materialize a layered support provider's effective contract from its base + overlay.",
    )
    ap.add_argument(
        "roots", nargs="+", type=Path, help="layered provider root(s) (each has provider.yaml with extends)"
    )
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if any effective contract is stale")
    ap.add_argument(
        "--base",
        type=Path,
        action="append",
        default=None,
        help="search this provider root (or shelf) for the base first; repeatable",
    )
    args = ap.parse_args(argv)
    stale = 0
    for root in args.roots:
        search = [*args.base, *layer_bases(root), *_candidate_roots()] if args.base else None
        try:
            fresh, comp = materialize(root, check=args.check, search=search)
        except ProviderError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2
        state = "fresh" if fresh else ("STALE" if args.check else "written")
        stale += 0 if fresh else 1
        revision = comp.base_revision or "unrecorded"
        print(f"{comp.provider.target}: {state} (base {comp.base.target} @ {revision} from {comp.base.root})")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
