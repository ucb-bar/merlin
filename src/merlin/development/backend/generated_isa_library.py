"""Operator-only, explicit generated ISA extension of a reviewed library.

This prepares a future selection, never changes a running campaign or grants a
companion checkout. The existing library snapshot/seal/transport owns admission.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from merlin.targetgen.compiler_library import CompilerLibrarySelection, freeze_compiler_library

MODULE = "reviewed_isa.instruction_dialect"
RECEIPT = "reviewed_isa/selection.json"
PRODUCTS = ("instruction_dialect.py", "isa-resolved.json", "manifest.json")


def _digest(payload):
    return hashlib.sha256(payload).hexdigest()


def _json(record):
    return (json.dumps(record, sort_keys=True, indent=2) + "\n").encode()


def _ordinary(path):
    path = Path(path)
    if not path.is_absolute() or path.resolve() != path or any(p.is_symlink() for p in (path, *path.parents)):
        raise ValueError("generated ISA selection requires canonical unlinked paths")
    return path


def prepare_library(base, package, destination, *, review_id, manifest_sha256, facts_sha256, declaration_sha256):
    """Extend an explicitly reviewed release with exactly three generated files.

    Expected identities come from the operator's public source review. Hashes and
    regenerated bytes prove custody, not agreement with hardware. The caller must
    explicitly select the returned contract using the ordinary library flags.
    """
    from merlin.targetgen.isa_dialect_gen import render_dialect_module
    from merlin.targetgen.isa_spec import resolved_isa_from_record

    if type(base) is not CompilerLibrarySelection:
        raise ValueError("generated ISA staging requires an explicit reviewed base library")
    before = base.record()
    package, destination = _ordinary(package), _ordinary(destination)
    if destination.exists() or destination.is_relative_to(package) or package.is_relative_to(destination):
        raise ValueError("generated ISA library needs a fresh separate destination")
    if destination.is_relative_to(base.root) or base.root.is_relative_to(destination):
        raise ValueError("generated ISA library must not overlap its base")
    if any(member.path.startswith("reviewed_isa/") for member in base.contract.members):
        raise ValueError("base already contains a generated ISA selection")
    payloads = {}
    for name in PRODUCTS:
        path = _ordinary(package / name)
        if not path.is_file() or path.stat().st_size > 8 << 20:
            raise ValueError("generated ISA product is absent or oversized")
        payloads[name] = path.read_bytes()
    if _digest(payloads["manifest.json"]) != manifest_sha256:
        raise ValueError("generated ISA manifest differs from the reviewed identity")
    manifest = json.loads(payloads["manifest.json"])
    model = resolved_isa_from_record(json.loads(payloads["isa-resolved.json"]))
    if (
        manifest.get("schema") != "merlin.isa_generation.v1"
        or manifest.get("assurance") != "declarations_and_encodings_only"
        or manifest.get("model_sha256") != model.identity()
        or manifest.get("target") != model.target
        or manifest.get("facts_sha256") != facts_sha256
        or model.facts_sha256 != facts_sha256
        or manifest.get("declaration_sha256") != declaration_sha256
        or model.declaration_sha256 != declaration_sha256
    ):
        raise ValueError("generated ISA public source identities differ from the reviewed selection")
    expected_files = {name: _digest(payloads[name]) for name in PRODUCTS if name != "manifest.json"}
    if manifest.get("files") != expected_files:
        raise ValueError("generated ISA product membership or bytes changed")
    registry = {**model.record(), "identity": model.identity()}
    if payloads["instruction_dialect.py"] != render_dialect_module(model).encode() or payloads[
        "isa-resolved.json"
    ] != _json(registry):
        raise ValueError("generated ISA products are not the declared generator output")
    selected_modules = {member.module: member.sha256 for member in base.contract.members}
    generator = manifest.get("generator", {}).get("modules", {})
    required = {"merlin.targetgen.isa_spec", "merlin.targetgen.isa_dialect_gen"}
    if set(generator) != required or any(selected_modules.get(name) != digest for name, digest in generator.items()):
        raise ValueError("generated ISA requires the same reviewed generator implementation in its library")
    receipt = {
        "schema": "merlin.generated_isa_library.v1",
        "experiment_origin": "fresh optimized backend atop generated scaffolding",
        "base_contract_sha256": base.contract.sha256,
        "manifest_sha256": manifest_sha256,
        "facts_sha256": facts_sha256,
        "declaration_sha256": declaration_sha256,
        "model_sha256": model.identity(),
        "module": MODULE,
        "assurance": "declarations_and_encodings_only",
        "independent_encoding_validation": "pending",
        "numerical_runtime_and_performance_qualification": "pending",
    }
    contents = {member.path: (base.root / member.path).read_bytes() for member in base.contract.members}
    contents.update({"reviewed_isa/" + name: raw for name, raw in payloads.items()})
    contents.update({"reviewed_isa/__init__.py": b"", RECEIPT: _json(receipt)})
    if base.record() != before or any((package / name).read_bytes() != raw for name, raw in payloads.items()):
        raise ValueError("generated ISA inputs changed during preparation")
    destination.mkdir(parents=True)
    for name, raw in contents.items():
        path = destination / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)
    sources = tuple((member.path, member.module) for member in base.contract.members) + (
        ("reviewed_isa/__init__.py", "reviewed_isa"),
        ("reviewed_isa/instruction_dialect.py", MODULE),
        ("reviewed_isa/isa-resolved.json", None),
        ("reviewed_isa/manifest.json", None),
        (RECEIPT, None),
    )
    contract = freeze_compiler_library(
        destination, review_id=review_id, public_modules=(*base.contract.public_modules, MODULE), sources=sources
    )
    return CompilerLibrarySelection(contract, destination)


def prompt(selection):
    """Describe only an already explicitly selected and verified scaffold."""
    if not selection.contract.permits(MODULE):
        return ""
    selection.record()
    members = {member.path for member in selection.contract.members}
    if RECEIPT not in members:
        raise ValueError("generated ISA library lacks its reviewed source provenance")
    receipt = json.loads((selection.root / RECEIPT).read_bytes())
    if receipt.get("schema") != "merlin.generated_isa_library.v1" or receipt.get("module") != MODULE:
        raise ValueError("generated ISA selection provenance is invalid")
    return (
        "\n## Selected generated instruction scaffold\n\n"
        "Experiment origin: **fresh optimized backend atop generated scaffolding**. "
        f"The explicitly reviewed readonly module `{MODULE}` supplies instruction declarations, "
        "effects, verifiers and encodings from the pinned public software/RTL inputs. "
        "It supplies no tensor lowering, fusion, allocation, scheduling or optimized backend. "
        "Build those in your editable backend and compiler pass library. Encoding agreement with "
        "an independent assembler/RTL remains pending; numerical, execution and timing checks "
        "are still required. No reference backend or reference kernel is granted. "
        "Source identities are in `reviewed_isa/selection.json` beside the selected module.\n"
    )
