"""Whole-model observability: every output in full, and a cycle bracket around every device group.

Two opt-in additions to the bare-metal whole-model image, both generated from the build's own
artifacts and both printed on the console the image already uses.

FULL READBACK. The default console protocol prints the first output's leading 4096 words, which
cannot grade a program with several outputs (a prefix and its cache, logits and a key/value cache) or
one large output. With full readback the image prints every forward result, complete, as an
``OUT_BIN v1`` frame (:mod:`merlin.runtime.harness.output_decoding`): a text header naming the output, its row/column
shape, element width and signedness, the raw little-endian bytes, and an FNV-1a checksum footer. The
output table is generated from the module's own forward signature.

GROUP PROFILE. Each call the compiled model makes to a routed device group goes through one external
symbol per kernel signature. The build wraps every such symbol the model object references
(``ld --wrap``) with a C function of the identical prototype that reads the cycle counter before and
after the call. The image then prints, after the outputs::

    GROUP_ID <i> <name>     the i-th group call, named after the routed group in program order
    GROUP <i> <cycles>      cycles inside that call
    GAP <i> <cycles>        cycles between the previous call's return (or the forward's start) and it
    GAP <n> <cycles>        cycles from the last call's return to the forward's end

The lines are target-neutral and printed in that order (all GROUP_IDs, then GROUP/GAP interleaved),
so a consumer joins per-group cycles to the model's groups and rooflines. Nothing here names a target,
an instruction or a counter: the cycle counter is the standard RISC-V ``rdcycle``.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from merlin.compiler.lower.model.profile import resolve_category

# ---- whole_model_readback ----------------------------------------------------------------------

#: Trace capacity: calls beyond it are counted as dropped, never silently lost.
TRACE_CAPACITY = 8192

#: (element bytes, signed) per forward-result dtype, the OUT_BIN container format.
_FORMAT = {
    "f32": (4, False),
    "f64": (8, False),
    "f16": (2, False),
    "bf16": (2, False),
    "i64": (8, True),
    "i32": (4, True),
    "i16": (2, True),
    "i8": (1, True),
    "i1": (1, False),
}

#: Floating-point dtypes travel as raw bits (unsigned words) and are reinterpreted on the host.
FLOAT_BITS = {"f32": "<u4", "f64": "<u8", "f16": "<u2", "bf16": "<u2"}


class ReadbackError(ValueError):
    """The image cannot state its outputs or its group calls in full."""


def output_name(index: int) -> str:
    return f"out{int(index)}"


def render_outputs_header(out_specs: Sequence[tuple[Sequence[int], str]]) -> str:
    """``model_outputs.h``: name, rows, cols, element width, signedness and byte count per result."""
    names, rows, cols, widths, signs, sizes = [], [], [], [], [], []
    for index, (shape, dtype) in enumerate(out_specs):
        if dtype not in _FORMAT:
            raise ReadbackError(f"result {index} has dtype {dtype!r}, which full readback cannot carry")
        width, signed = _FORMAT[dtype]
        row, col = _output_geometry(shape)
        count = row * col
        names.append(f'"{output_name(index)}"')
        rows.append(str(row))
        cols.append(str(col))
        widths.append(str(width))
        signs.append("'s'" if signed else "'u'")
        sizes.append(f"{count * width}ULL")
    return "\n".join(
        [
            "/* Generated by merlin.runtime.harness.output_observation. Do not edit. */",
            "#ifndef MERLIN_MODEL_OUTPUTS_H",
            "#define MERLIN_MODEL_OUTPUTS_H",
            f"static const char *const MERLIN_OUTPUT_NAMES[{len(names)}] = {{{', '.join(names)}}};",
            f"static const unsigned long long MERLIN_OUTPUT_ROWS[{len(names)}] = {{{', '.join(rows)}}};",
            f"static const unsigned long long MERLIN_OUTPUT_COLS[{len(names)}] = {{{', '.join(cols)}}};",
            f"static const unsigned MERLIN_OUTPUT_WIDTH[{len(names)}] = {{{', '.join(widths)}}};",
            f"static const char MERLIN_OUTPUT_SIGN[{len(names)}] = {{{', '.join(signs)}}};",
            f"static const unsigned long long MERLIN_OUTPUT_BYTES[{len(names)}] = {{{', '.join(sizes)}}};",
            "#endif",
            "",
        ]
    )


@dataclass(frozen=True)
class GroupCallee:
    """One external group symbol the model object calls, with the prototype it is called through."""

    symbol: str
    #: ``expanded`` (three rank-r memrefs passed field by field, a rank-r memref returned) or
    #: ``c_interface`` (result pointer, then one descriptor per call buffer).
    abi: str
    #: None for a C-interface call with mixed operand ranks. Its ABI carries
    #: descriptor pointers, so the wrapper does not inspect their pointees.
    rank: int | None
    #: Number of descriptor arguments, including the destination. Expanded
    #: calls have the fixed three-buffer ABI; C interfaces may also pass bias.
    buffers: int = 3
    #: Original source route, when a checked writer rewrite changed its ABI.
    routed_symbol: str | None = None


def callees(
    routed: Sequence[Mapping[str, Any]],
    signatures: Mapping[str, Sequence[int]],
    undefined: set[str],
    call_buffers: Mapping[str, Sequence[Mapping[str, Any]]] | None = None,
    writer_bindings: Mapping[str, Mapping[str, Any]] | None = None,
):
    """The group callees the model object actually references, in a stable order.

    ``undefined`` is the model object's undefined-symbol list; only a referenced name can be wrapped.
    A routed symbol referenced under neither name is refused: its calls would go unbracketed."""
    out: list[GroupCallee] = []
    for symbol in sorted({str(row.get("symbol")) for row in routed if row.get("symbol")}):
        if symbol in (writer_bindings or {}) and (symbol in undefined or f"_mlir_ciface_{symbol}" in undefined):
            raise ReadbackError("profile writer and original ABI both remain referenced")
        key = signatures.get(symbol)
        if key is None:
            raise ReadbackError(f"routed symbol {symbol} has no device signature")
        if symbol in undefined:
            if len(key) not in (3, 4):
                raise ReadbackError(f"routed symbol {symbol} has no 3- or 4-extent signature")
            if call_buffers is not None and symbol in call_buffers and len(call_buffers[symbol]) != 3:
                raise ReadbackError(f"expanded routed symbol {symbol} has a non-three-buffer call ABI")
            out.append(GroupCallee(symbol, "expanded", len(key) - 1))
        elif f"_mlir_ciface_{symbol}" in undefined:
            buffers = (call_buffers or {}).get(symbol)
            if buffers is not None:
                roles = [buf.get("role") if isinstance(buf, Mapping) else None for buf in buffers]
                if (
                    not isinstance(buffers, (list, tuple))
                    or roles
                    not in (
                        ["input_0", "weight_0", "out_0"],
                        ["input_0", "input_1", "out_0"],
                        ["input_0", "weight_0", "bias_0", "out_0"],
                    )
                    or any(
                        not isinstance(buf, Mapping)
                        or not isinstance(buf.get("shape"), (list, tuple))
                        or not buf["shape"]
                        or any(not isinstance(dim, int) or dim < 1 for dim in buf["shape"])
                        for buf in buffers
                    )
                ):
                    raise ReadbackError(f"routed symbol {symbol} has no complete call-buffer ABI")
                rank = None
                arity = len(buffers)
            elif len(key) in (3, 4):
                rank, arity = len(key) - 1, 3
            else:
                raise ReadbackError(f"routed symbol {symbol} has no complete call-buffer ABI")
            out.append(GroupCallee(f"_mlir_ciface_{symbol}", "c_interface", rank, arity))
        else:
            binding = (writer_bindings or {}).get(symbol)
            borrowed = None if binding is None else binding.get("borrowed_symbol")
            buffers = None if binding is None else binding.get("buffers")
            ranks = None if binding is None else binding.get("argument_ranks")
            actual = f"_mlir_ciface_{borrowed}"
            if (
                not isinstance(borrowed, str)
                or not borrowed.isascii()
                or not borrowed.isidentifier()
                or type(buffers) is not int
                or not 0 < buffers <= 64
                or not isinstance(ranks, list)
                or len(ranks) != buffers
                or any(type(rank) is not int or rank < 0 for rank in ranks)
                or actual not in undefined
            ):
                raise ReadbackError(f"the model object references routed symbol {symbol} under no known name")
            if any(c.symbol == actual for c in out):
                raise ReadbackError("the profiled borrowed entry has ambiguous source routes")
            out.append(GroupCallee(actual, "borrowed_c_interface", None, buffers, symbol))
    return out


def group_names(routed: Sequence[Mapping[str, Any]]) -> list[tuple[str, str]]:
    """``(g<group index>_<symbol>, symbol)`` per routed group, in program order (the order calls are issued)."""
    names = []
    for row in routed:
        group, symbol = row.get("group"), str(row.get("symbol"))
        names.append((f"g{int(group)}_{symbol}" if group is not None else symbol, symbol))
    return names


def _memref(rank: int) -> str:
    return f"merlin_profile_memref_{rank}d"


def _expanded_params(rank: int) -> tuple[str, str]:
    params, args = [], []
    for letter in "abc":
        fields = [("void *", "alloc"), ("void *", "aligned"), ("intptr_t ", "off")]
        fields += [("intptr_t ", f"s{i}") for i in range(rank)]
        fields += [("intptr_t ", f"st{i}") for i in range(rank)]
        for ctype, field in fields:
            params.append(f"{ctype}{letter}_{field}")
            args.append(f"{letter}_{field}")
    return ", ".join(params), ", ".join(args)


def render_group_profile(callees_: Sequence[GroupCallee], names: Sequence[tuple[str, str]]) -> str:
    """``merlin_group_profile.c``: the wrappers, the trace and the print routine ``model_main`` calls.

    A call is named after the routed group in the same program-order position only when that group
    calls the same symbol; otherwise (a loop, a branch) it is named by its callee, never mislabelled."""
    symbols = [c.routed_symbol or c.symbol for c in callees_]
    base = {c.routed_symbol or c.symbol.removeprefix("_mlir_ciface_"): i for i, c in enumerate(callees_)}
    name_callee = [base.get(symbol, -1) for _name, symbol in names]
    names = [name for name, _symbol in names]
    lines = [
        "/* Generated by merlin.runtime.harness.output_observation. Do not edit. */",
        "#include <stdint.h>",
        "void htif_puts(const char *);",
        "void htif_putc(char);",
        f"#define MERLIN_GROUP_TRACE_CAP {TRACE_CAPACITY}",
        "static uint64_t merlin_group_start[MERLIN_GROUP_TRACE_CAP];",
        "static uint64_t merlin_group_end[MERLIN_GROUP_TRACE_CAP];",
        "static uint16_t merlin_group_callee[MERLIN_GROUP_TRACE_CAP];",
        "static uint64_t merlin_group_count, merlin_group_dropped;",
        "static inline uint64_t merlin_rdcycle(void) {",
        "  uint64_t c;",
        '  __asm__ volatile("rdcycle %0" : "=r"(c));',
        "  return c;",
        "}",
        "static void merlin_group_record(unsigned callee, uint64_t start, uint64_t end) {",
        "  if (merlin_group_count < MERLIN_GROUP_TRACE_CAP) {",
        "    merlin_group_start[merlin_group_count] = start;",
        "    merlin_group_end[merlin_group_count] = end;",
        "    merlin_group_callee[merlin_group_count] = (uint16_t)callee;",
        "    merlin_group_count++;",
        "  } else {",
        "    merlin_group_dropped++;",
        "  }",
        "}",
    ]
    for rank in sorted({c.rank for c in callees_ if c.rank is not None}):
        lines += [
            "typedef struct {",
            "  void *allocated;",
            "  void *aligned;",
            "  intptr_t offset;",
            f"  intptr_t sizes[{rank}];",
            f"  intptr_t strides[{rank}];",
            f"}} {_memref(rank)};",
        ]
    for index, callee in enumerate(callees_):
        memref = _memref(callee.rank) if callee.rank is not None else None
        if callee.abi == "expanded":
            params, args = _expanded_params(callee.rank)
            lines += [
                f"{memref} __real_{callee.symbol}({params});",
                f"{memref} __wrap_{callee.symbol}({params}) {{",
                "  uint64_t start = merlin_rdcycle();",
                f"  {memref} result = __real_{callee.symbol}({args});",
                f"  merlin_group_record({index}u, start, merlin_rdcycle());",
                "  return result;",
                "}",
            ]
        elif callee.abi == "borrowed_c_interface":
            args = [f"arg_{i}" for i in range(callee.buffers)]
            proto = ", ".join(f"void *{arg}" for arg in args)
            lines += [
                f"void __real_{callee.symbol}({proto});",
                f"void __wrap_{callee.symbol}({proto}) {{",
                "  uint64_t start = merlin_rdcycle();",
                f"  __real_{callee.symbol}({', '.join(args)});",
                f"  merlin_group_record({index}u, start, merlin_rdcycle());",
                "}",
            ]
        elif callee.abi == "c_interface":
            pointer = f"const {memref} *" if memref is not None else "const void *"
            args = [chr(ord("a") + i) for i in range(callee.buffers)]
            proto = f"{memref} *result" if memref is not None else "void *result"
            proto += ", " + ", ".join(f"{pointer}{arg}" for arg in args)
            lines += [
                f"void __real_{callee.symbol}({proto});",
                f"void __wrap_{callee.symbol}({proto}) {{",
                "  uint64_t start = merlin_rdcycle();",
                f"  __real_{callee.symbol}(result, {', '.join(args)});",
                f"  merlin_group_record({index}u, start, merlin_rdcycle());",
                "}",
            ]
        else:
            raise ReadbackError("unknown group profiling ABI")
    callee_names = ", ".join(f'"{s}"' for s in symbols) or '""'
    group_list = ", ".join(f'"{n}"' for n in names) or '""'
    lines += [
        f"static const char *const merlin_callee_names[] = {{{callee_names}}};",
        f"static const char *const merlin_group_names[] = {{{group_list}}};",
        f"static const unsigned long long merlin_group_name_count = {len(names)}ULL;",
        "static const int merlin_group_name_callee[] = {" + (", ".join(str(i) for i in name_callee) or "-1") + "};",
        "static void merlin_put_u64(uint64_t v) {",
        "  char buf[24];",
        "  int i = 0;",
        "  do { buf[i++] = (char)('0' + (v % 10)); v /= 10; } while (v);",
        "  while (i) htif_putc(buf[--i]);",
        "}",
        "static void merlin_line(const char *tag, uint64_t index, uint64_t value) {",
        "  htif_puts(tag); htif_putc(' '); merlin_put_u64(index); htif_putc(' '); merlin_put_u64(value);",
        "  htif_putc('\\n');",
        "}",
        "uint64_t merlin_group_profile_now(void) { return merlin_rdcycle(); }",
        "void merlin_group_profile_reset(void) {",
        "  merlin_group_count = 0;",
        "  merlin_group_dropped = 0;",
        "}",
        "void merlin_group_profile_dump(uint64_t forward_start, uint64_t forward_end) {",
        "  for (uint64_t i = 0; i < merlin_group_count; i++) {",
        "    htif_puts(\"GROUP_ID \"); merlin_put_u64(i); htif_putc(' ');",
        "    int named = i < merlin_group_name_count && merlin_group_name_callee[i] == (int)merlin_group_callee[i];",
        "    htif_puts(named ? merlin_group_names[i] : merlin_callee_names[merlin_group_callee[i]]);",
        "    htif_putc('\\n');",
        "  }",
        "  uint64_t previous = forward_start;",
        "  for (uint64_t i = 0; i < merlin_group_count; i++) {",
        '    merlin_line("GAP", i, merlin_group_start[i] - previous);',
        '    merlin_line("GROUP", i, merlin_group_end[i] - merlin_group_start[i]);',
        "    previous = merlin_group_end[i];",
        "  }",
        '  merlin_line("GAP", merlin_group_count, forward_end - previous);',
        "  htif_puts(\"METRIC group_calls \"); merlin_put_u64(merlin_group_count); htif_putc('\\n');",
        "  htif_puts(\"METRIC group_calls_dropped \"); merlin_put_u64(merlin_group_dropped); htif_putc('\\n');",
        "}",
    ]
    return "\n".join(lines) + "\n"


def wrap_flags(callees_: Sequence[GroupCallee]) -> list[str]:
    return [f"-Wl,--wrap={c.symbol}" for c in callees_]


def parse_group_profile(text: str) -> dict[str, Any] | None:
    """``{groups: [{index, name, cycles, gap_before}], tail_gap, calls, dropped}`` or ``None`` when absent.

    Refuses an inconsistent record: every GROUP needs its GROUP_ID and its preceding GAP, indices run
    from zero without holes, and the tail GAP closes the list."""
    names: dict[int, str] = {}
    cycles: dict[int, int] = {}
    gaps: dict[int, int] = {}
    metrics: dict[str, int] = {}
    seen = False
    for line in text.splitlines():
        parts = line.split()
        if not parts:
            continue
        tag = parts[0]
        if tag in ("GROUP_ID", "GROUP", "GAP") and len(parts) != 3:
            raise ReadbackError("malformed group profile record")
        if tag == "GROUP_ID" and len(parts) == 3:
            seen = True
            index = int(parts[1])
            if index < 0 or index in names:
                raise ReadbackError("negative or duplicate group profile index")
            names[index] = parts[2]
        elif tag in ("GROUP", "GAP") and len(parts) == 3:
            seen = True
            index, value = int(parts[1]), int(parts[2])
            records = cycles if tag == "GROUP" else gaps
            if index < 0 or value < 0 or index in records:
                raise ReadbackError("negative or duplicate group profile counter")
            records[index] = value
        elif tag == "METRIC" and len(parts) == 3 and parts[1] in ("group_calls", "group_calls_dropped"):
            seen = True
            value = int(parts[2])
            if value < 0 or parts[1] in metrics:
                raise ReadbackError("negative or duplicate group profile metric")
            metrics[parts[1]] = value
    if not seen:
        return None
    count = len(cycles)
    if set(cycles) != set(range(count)) or set(names) != set(range(count)) or set(gaps) != set(range(count + 1)):
        raise ReadbackError("the group profile is incomplete: GROUP, GROUP_ID and GAP indices disagree")
    if metrics.get("group_calls", count) != count:
        raise ReadbackError("the group profile's call count disagrees with its records")
    return {
        "groups": [{"index": i, "name": names[i], "cycles": cycles[i], "gap_before": gaps[i]} for i in range(count)],
        "tail_gap": gaps[count],
        "calls": count,
        "dropped": metrics.get("group_calls_dropped", 0),
    }


def decode_outputs(
    outputs: Mapping[str, list], frames: Mapping[str, Any], out_specs: Sequence[tuple[Sequence[int], str]]
):
    """The decoded OUT_BIN frames as ``[numpy array]`` in forward-result order, in their own dtypes."""
    import numpy as np

    arrays = []
    for index, (shape, dtype) in enumerate(out_specs):
        name = output_name(index)
        if name not in outputs or name not in frames:
            raise ReadbackError(f"the console carries no complete frame for result {index}")
        width, signed = _FORMAT[dtype]
        frame = frames[name]
        if frame.word_bytes != width or bool(frame.signed) != signed:
            raise ReadbackError(f"result {index}'s frame format differs from its declared dtype {dtype}")
        rows, cols = _output_geometry(shape)
        if (frame.rows, frame.cols) != (rows, cols):
            raise ReadbackError(f"result {index}'s frame geometry differs from its declared shape")
        words = np.asarray(outputs[name], dtype=np.int64 if signed else np.uint64).reshape(-1)
        if dtype in FLOAT_BITS:
            raw = words.astype(np.dtype(FLOAT_BITS[dtype]))
            if dtype == "bf16":
                value = (raw.astype(np.uint32) << 16).view(np.float32)
            else:
                value = raw.view({"f32": np.float32, "f64": np.float64, "f16": np.float16}[dtype])
        elif dtype == "i1":
            value = words.astype(np.uint8)
        else:
            value = words.astype({"i64": np.int64, "i32": np.int32, "i16": np.int16, "i8": np.int8}[dtype])
        expected = 1
        for d in shape:
            expected *= int(d)
        if value.size != expected:
            raise ReadbackError(f"result {index} printed {value.size} of {expected} elements")
        arrays.append(value.reshape([int(d) for d in shape]) if shape else value.reshape(()))
    if set(outputs) - {output_name(i) for i in range(len(out_specs))}:
        raise ReadbackError("the console carries frames for results the forward does not have")
    return arrays


# ---- input_observation -------------------------------------------------------------------------
# Opt-in complete byte observations of caller-declared readonly arguments.
#
# The driver reads original argument addresses after forward returns and before
# state commit. This checks end-of-call bytes, not intermediate writes, fences,
# guard regions, numerical correctness or a target's unspecified effects.

SCHEMA = "merlin.readonly_input_observation.v1"
STAGE = "after_forward_before_state_commit"


def validate_selection(indices, max_bytes):
    if type(indices) is not tuple or len(indices) > 4096 or any(type(i) is not int or i < 0 for i in indices):
        raise ValueError("readonly input indices must be a bounded tuple of nonnegative integers")
    if len(set(indices)) != len(indices):
        raise ValueError("readonly input indices must not repeat")
    if type(max_bytes) is not int or not 0 < max_bytes <= 64 << 20:
        raise ValueError("readonly input observation byte budget must be in 1..64 MiB")


def _pin(path):
    path = Path(path).resolve(strict=True)
    if not path.is_file():
        raise ValueError("readonly input observation requires regular pinned files")
    with path.open("rb") as stream:
        digest = hashlib.file_digest(stream, "sha256").hexdigest()
    return {"path": str(path), "sha256": digest, "bytes": path.stat().st_size}


def _checked(pin):
    if type(pin) is not dict or set(pin) != {"path", "sha256", "bytes"}:
        raise ValueError("readonly input observation has a malformed artifact pin")
    if type(pin["path"]) is not str or type(pin["sha256"]) is not str or type(pin["bytes"]) is not int:
        raise ValueError("readonly input observation has invalid artifact fields")
    path = Path(pin["path"])
    if not path.is_absolute() or path.is_symlink() or _pin(path) != pin:
        raise ValueError("readonly input observation artifact changed")
    return path


def _read(pin):
    if type(pin) is not dict or type(pin.get("bytes")) is not int or not 0 <= pin["bytes"] <= 64 << 20:
        raise ValueError("readonly input observation artifact exceeds its bounded read budget")
    path = _checked(pin)
    return path.read_bytes()


def snapshot_sources(paths):
    """Pin original derivation inputs before the code generator consumes them."""
    return [_pin(path) for path in paths]


def _header(arguments):
    # No tensor semantics or expected answers enter this generated observer.
    lines = [
        "/* Original-caller readonly argument observations, OUT_BIN v1 byte frames. */",
        f"static const volatile unsigned char *merlin_readonly_ptrs[{len(arguments)}];",
        f"static unsigned char merlin_readonly_bytes[{sum(arg['bytes'] for arg in arguments)}];",
        "static void merlin_snapshot_readonly_inputs(const void *weights) {",
    ]
    for j, arg in enumerate(arguments):
        address = (
            f"((const unsigned char *)weights + {arg['weight_offset']}ULL)"
            if arg["kind"] == "MERLIN_WEIGHT"
            else f"MERLIN_INPUT_PTR[{arg['runtime_index']}]"
        )
        lines.append(f"  merlin_readonly_ptrs[{j}] = (const volatile unsigned char *){address};")
    lines.extend(["  (void)weights;", "}", "static void merlin_capture_readonly_inputs(void) {"])
    for j, arg in enumerate(arguments):
        lines.extend(
            [
                f"  for (unsigned long long i = 0; i < {arg['bytes']}ULL; i++)",
                f"    merlin_readonly_bytes[{arg['expected_offset']}ULL + i] = merlin_readonly_ptrs[{j}][i];",
            ]
        )
    lines.extend(["}", "static void merlin_emit_readonly_inputs(void) {"])
    for j, arg in enumerate(arguments):
        name, size = arg["frame"], arg["bytes"]
        lines.extend(
            [
                "  { uint64_t hash = 0xcbf29ce484222325ULL;",
                f'    htif_puts("OUT_BIN_BEGIN v1 {name} 1 {size} 1 u {size}\\n");',
                "    htif_line_flush(0);",
                f"    for (unsigned long long i = 0; i < {size}ULL; i++) {{",
                f"      unsigned char byte = merlin_readonly_bytes[{arg['expected_offset']}ULL + i];",
                "      htif_putc((char)byte); hash = (hash ^ byte) * 0x100000001b3ULL;",
                "    }",
                '    htif_line_flush(1); htif_puts("OUT_BIN_END v1 ");',
                "    for (int shift = 60; shift >= 0; shift -= 4)",
                '      htif_putc("0123456789abcdef"[(hash >> shift) & 15]);',
                "    htif_putc('\\n');",
                "  }",
            ]
        )
    return "\n".join([*lines, "}", ""])


def write_observation(directory, *, arguments, sources, max_bytes):
    """Retain source-derived expected bytes and an independent runtime observer."""
    indices = tuple(arg["original_index"] for arg in arguments)
    validate_selection(indices, max_bytes)
    if not arguments:
        raise ValueError("an enabled readonly input observation requires arguments")
    directory = Path(directory).resolve(strict=True)
    roster, data = [], bytearray()
    for arg in arguments:
        payload = arg["data"]
        if type(payload) is not bytes or len(data) + len(payload) > max_bytes:
            raise ValueError("readonly input observation exceeds its complete byte budget")
        row = {k: v for k, v in arg.items() if k != "data"}
        row.update(
            frame=f"readonly_arg_{arg['original_index']}",
            bytes=len(payload),
            expected_offset=len(data),
            expected_sha256=hashlib.sha256(payload).hexdigest(),
            access="readonly_during_forward",
        )
        roster.append(row)
        data.extend(payload)
    expected = directory / "readonly_inputs.expected.bin"
    expected.write_bytes(data)
    header = directory / "readonly_inputs.h"
    header.write_text(_header(roster))
    for source in sources:
        _checked(source)
    manifest = {
        "schema": SCHEMA,
        "stage": STAGE,
        "max_bytes": max_bytes,
        "arguments": roster,
        "sources": sources,
        "expected": _pin(expected),
    }
    path = directory / "readonly_inputs.json"
    path.write_text(json.dumps(manifest, sort_keys=True, indent=2) + "\n")
    return {"manifest": _pin(path), "header": _pin(header), "owner": _pin(__file__)}


def revalidate_observation(record):
    if type(record) is not dict or set(record) != {"manifest", "header", "owner"}:
        raise ValueError("readonly input observation has no exact original artifact roster")
    if record["owner"] != _pin(__file__):
        raise ValueError("readonly input observation implementation changed")
    raw = _read(record["manifest"])
    _read(record["header"])
    manifest = json.loads(raw)
    if (
        set(manifest) != {"schema", "stage", "max_bytes", "arguments", "sources", "expected"}
        or manifest["schema"] != SCHEMA
        or manifest["stage"] != STAGE
    ):
        raise ValueError("readonly input observation manifest is unsupported")
    args = manifest["arguments"]
    validate_selection(tuple(a["original_index"] for a in args), manifest["max_bytes"])
    data = _read(manifest["expected"])
    cursor = 0
    for arg in args:
        fields = {
            "original_index",
            "runtime_index",
            "kind",
            "weight_offset",
            "shape",
            "dtype",
            "frame",
            "bytes",
            "expected_offset",
            "expected_sha256",
            "access",
        }
        if (
            set(arg) != fields
            or arg["frame"] != f"readonly_arg_{arg['original_index']}"
            or arg["access"] != "readonly_during_forward"
            or type(arg["bytes"]) is not int
            or arg["bytes"] < 0
            or arg["expected_offset"] != cursor
        ):
            raise ValueError("readonly input observation argument roster changed")
        payload = data[cursor : cursor + arg["bytes"]]
        if len(payload) != arg["bytes"] or hashlib.sha256(payload).hexdigest() != arg["expected_sha256"]:
            raise ValueError("readonly input observation expected source bytes changed")
        cursor += arg["bytes"]
    if not args or cursor != len(data) or cursor > manifest["max_bytes"]:
        raise ValueError("readonly input observation has incomplete or excessive expected bytes")
    for source in manifest["sources"]:
        _checked(source)
    if _read(record["manifest"]) != raw:
        raise ValueError("readonly input observation changed while reopening")
    return manifest


def verify_observed_inputs(record, outputs, frames):
    """Remove only the exact selected argument frames, checking every raw byte."""
    manifest = revalidate_observation(record)
    expected = _read(manifest["expected"])
    remaining, remaining_frames, observed = dict(outputs), dict(frames), []
    for arg in manifest["arguments"]:
        name, count = arg["frame"], arg["bytes"]
        frame = remaining_frames.pop(name, None)
        if frame is None or (frame.rows, frame.cols, frame.word_bytes, frame.signed) != (1, count, 1, False):
            raise ValueError("readonly input observation lacks an exact complete byte frame")
        words = remaining.pop(name, None)
        if count == 0:
            if words != []:
                raise ValueError("empty readonly input observation has unexpected payload")
            actual = b""
        elif words is None or len(words) != 1 or len(words[0]) != count:
            raise ValueError("readonly input observation has incomplete argument values")
        else:
            actual = bytes(words[0])
        start = arg["expected_offset"]
        if actual != expected[start : start + count]:
            raise ValueError(f"readonly input argument {arg['original_index']} changed during forward")
        observed.append(
            {
                "original_index": arg["original_index"],
                "frame": name,
                "bytes": count,
                "sha256": hashlib.sha256(actual).hexdigest(),
                "passed": True,
            }
        )
    revalidate_observation(record)
    return remaining, remaining_frames, {"schema": SCHEMA, "stage": STAGE, "arguments": observed, "artifacts": record}


def require_observation_selection(record, *, indices, max_bytes):
    """Join the produced roster to the unchanged original caller request."""
    validate_selection(indices, max_bytes)
    manifest = revalidate_observation(record)
    if tuple(arg["original_index"] for arg in manifest["arguments"]) != indices or manifest["max_bytes"] != max_bytes:
        raise ValueError("readonly input observation does not match the original selection")
    return manifest


def setup_readback(cgen, model_dir, info, compilation, full, indices, max_bytes):
    """Prepare the existing full-output transport and optional argument observer."""
    if full:
        from merlin.compiler.lower.c.runtime import _out_specs

        (cgen / "model_outputs.h").write_text(
            render_outputs_header(
                info["outputs"] if "runtime_invocation_abi" in info else _out_specs(model_dir / "model.mlir")
            ),
            encoding="utf-8",
        )
    if indices:
        require_observation_selection(info.get("readonly_input_observation"), indices=indices, max_bytes=max_bytes)
        compilation.bind_preparation(
            "readonly_input_observation", Path(info["readonly_input_observation"]["manifest"]["path"])
        )


# ---- operation_profile -------------------------------------------------------------------------
# Closed single-function operation observations, without assigning counter units.
#
# The existing marker runtime credits each interval to the previous marker. A
# sentinel closes the last operation and accumulates gaps BETWEEN invocations.
# Those gaps are recorded separately and never assigned to an operation category.
# This reader establishes trace consistency, not timing or placement authority.


class OperationProfileError(ValueError):
    """An operation trace is incomplete, inconsistent or outside the selected scope."""


def summarize(table: Sequence[Mapping], console: str) -> dict:
    """Join one typed, single-function table to a complete marker-runtime dump.

    All operations must execute equally often. The runtime must print each
    observation exactly once, with matching total/mark counters and terminal
    DONE. Nested multi-function tables, overflow and partial traces refuse.
    Hit consistency does not establish nonrecursive ownership. ``counter_ticks``
    are raw observations: there is no Hz, time or
    accelerator-cycle conversion. Semantic categories retain their derivation;
    neither category nor callee name establishes CPU/device ownership.
    """
    if not table or any(
        not isinstance(row, Mapping)
        or type(row.get("id")) is not int
        or row["id"] != i
        or not isinstance(row.get("mlir_op"), str)
        or not row["mlir_op"]
        or "function" in row
        for i, row in enumerate(table)
    ):
        raise OperationProfileError("expected a nonempty contiguous single-function operation table")
    observations: dict[int, tuple[int, int]] = {}
    metrics: dict[str, int] = {}
    done = False
    for line in console.splitlines():
        parts = line.split()
        if not parts:
            continue
        selected = parts[0] == "PROF" or (
            len(parts) > 1
            and parts[:2]
            in (
                ["METRIC", "prof_total_ticks"],
                ["METRIC", "prof_marks"],
            )
        )
        if done and (selected or parts[0] == "DONE"):
            raise OperationProfileError("operation observations after terminal DONE")
        if parts[0] == "DONE":
            if len(parts) != 1:
                raise OperationProfileError("malformed terminal DONE")
            done = True
        elif parts[0] == "PROF":
            if len(parts) != 4:
                raise OperationProfileError("malformed PROF observation")
            try:
                index, ticks, hits = map(int, parts[1:])
            except ValueError as exc:
                raise OperationProfileError("noninteger PROF observation") from exc
            if index in observations:
                raise OperationProfileError("duplicate PROF observation")
            if not 0 <= index <= len(table) or not 0 <= ticks < 2**64 or not 0 < hits < 2**32:
                raise OperationProfileError("overflow, foreign id or invalid PROF counter")
            observations[index] = ticks, hits
        elif selected:
            if len(parts) != 3 or parts[1] in metrics:
                raise OperationProfileError("malformed or duplicate profiler metric")
            try:
                value = int(parts[2])
            except ValueError as exc:
                raise OperationProfileError("noninteger profiler metric") from exc
            if not 0 <= value < 2**64:
                raise OperationProfileError("invalid profiler metric")
            metrics[parts[1]] = value
    if not done or set(metrics) != {"prof_marks", "prof_total_ticks"}:
        raise OperationProfileError("missing terminal DONE or profiler metrics")
    if not set(range(len(table))) <= observations.keys():
        raise OperationProfileError("missing operation observations")
    executions = observations[0][1]
    if any(observations[i][1] != executions for i in range(len(table))):
        raise OperationProfileError("inconsistent operation execution counts")
    gap_ticks, gap_hits = observations.get(len(table), (0, 0))
    if gap_hits != executions - 1:
        raise OperationProfileError("inconsistent sentinel inter-invocation gaps")
    total = sum(ticks for ticks, _hits in observations.values())
    if metrics["prof_marks"] != executions * (len(table) + 1) or metrics["prof_total_ticks"] != total:
        raise OperationProfileError("profiler total or marker count mismatch")
    operations, categories = [], {}
    for record in table:
        ticks, hits = observations[record["id"]]
        category, source = resolve_category(record)
        operations.append(
            {
                **record,
                "counter_ticks": ticks,
                "hits": hits,
                "category": category,
                "category_source": source,
                "execution_owner": "unknown",
            }
        )
        categories[category] = categories.get(category, 0) + ticks
    return {
        "schema": "merlin.operation_profile.v1",
        "unit": "raw_counter_ticks",
        "timing_qualified": False,
        "executions": executions,
        "operations": operations,
        "category_counter_ticks": dict(sorted(categories.items())),
        "operation_counter_ticks": total - gap_ticks,
        "inter_invocation_counter_ticks": gap_ticks,
        "total_counter_ticks": total,
        "marks": metrics["prof_marks"],
        "limitations": [
            "Markers may change optimization, allocation and scheduling; pair an uninstrumented control.",
            "Categories describe source semantics, not CPU/device placement or instruction effects.",
            "Nested packing, copies, dispatch, allocator and accelerator work are not separately resolved.",
            "Marker bookkeeping, entry/return, startup, output and final dump are outside operation intervals.",
            "Raw ticks establish no counter calibration, hardware latency or numerical agreement.",
        ],
    }


