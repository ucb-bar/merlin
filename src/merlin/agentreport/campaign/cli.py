"""Regenerate the campaign figure at any point of a run.

    python -m merlin.agentreport.campaign --manifest <campaign.yaml> [--out-dir DIR]
    python -m merlin.agentreport.campaign --run-dir RUN [--workspace WS] [--agent-home HOME]
                                          [--launch-log LOG] [--accounting-log LOG] [--target T]

Without ``--out-dir`` the output is a versioned product under the ``campaign-figure`` product root
(``out/artifacts/agentic-report/campaign-figures/<target>/v<N>/...``, ``latest`` repointed). Each
product holds ``campaign_figure.{pdf,svg,png}``, ``notes.json`` (every number on the figure),
``records.json`` (the extracted dataset), ``campaign_manifest.yaml`` (the inputs) and ``README.md``.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

import yaml

from . import FIGURE_VERSION, PRODUCT
from .figure import build_series, draw, fmt_tok
from .manifest import Manifest, load, single_run
from .records import read_campaign


def _min(v) -> str:
    return f"{v:.1f} min" if isinstance(v, (int, float)) else "not recorded"


def _readme(m: Manifest, notes: dict) -> str:
    perf = notes["performance"]
    fin = notes["final"]
    tok = notes["tokens"]
    lab = {"l2": "L2 sim", "l3": "L3 sim", **m.labels}
    sp = (f"×{perf['speedup_geomean']:.2f} (IQR {perf['speedup_iqr'][0]:.2f}–{perf['speedup_iqr'][1]:.2f}), "
          f"n = {perf['speedup_test_cases']} test cases") if perf["speedup_geomean"] else "not available (no test case measured twice)"
    ut = (f"{perf['utilization_median_pct']:.1f} % (IQR {perf['utilization_iqr_pct'][0]:.1f}–{perf['utilization_iqr_pct'][1]:.1f} %), "
          f"n = {perf['utilization_test_cases']} test cases") if perf["utilization_median_pct"] is not None else "not available"
    coh = "\n".join(f"| {c['label']} | {c['l3']} | {c['l2']} | {c['test_cases']} | {'yes' if c['l3_required'] else 'no'} |"
                    for c in notes["cohorts"].values())
    return f"""# Campaign figure: {m.campaign}

Generated by `python -m merlin.agentreport.campaign` (figure version {FIGURE_VERSION}) from the inputs in
`campaign_manifest.yaml`. Every number below is also in `notes.json`; the extracted dataset is `records.json`.

**One stitched run.** The attempts are drawn as one run whose x axis is minutes of active time: each
attempt's window from its lead agent's start to its last record, cut where a finished attempt's
background grader recorded nothing for 45 min; gaps, failed startups and grader-down spans are left out.
Pass status is carried across the whole timeline and never reset.

## Panels

- **Agent trajectory.** Smoothed share of agent time (all agent threads, per minute) by activity, with
  input/output token rates (right log axis). Rollout evidence: reading = reader commands (`sed`, `cat`,
  `rg`, `grep`, `ls`, …) or print-only Python; writing code = `apply_patch` calls and file-writing
  commands; shell = other commands; wait: helpers = sub-agent spawn/message/wait calls; wait: checks =
  self-check, model-check, RTL-job, ISA/CCA/capability commands and sleeps; thinking = the rest of each
  turn (model generation between tool calls). Strip: agent threads inside a turn (lead + helpers).
  Callouts: milestones (test cases passing · L3 · cumulative tokens) and the final state.
- **Test cases passed over time.** A test case counts from its first L2 ({lab['l2']}) pass and is
  promoted at its first L3 ({lab['l3']}) certificate; a later failing L2 grade drops it, a later failing
  L3 certificate demotes it. "regression" marks the largest drop.
- **Performance on {lab['l3']} RTL.** Only certifying rows with engine `{m.rtl_engine}`, positive cycles,
  a compiler source digest and a matching test-case digest count. Speedup: geomean of first ÷ latest
  cycles per test case measured twice on the same digest (band IQR). PE-array utilization: useful MACs
  ÷ (cycles × peak MACs/cycle) from the same row's structural roofline (equal to floor ÷ cycles).
- **Compute on the reserved cores.** Recorded job intervals (grader stages, RTL jobs, agent process
  tree), scaled per launch by one factor ≤ 1 and capped at the reservation so the integral equals the
  CPU time systemd measured; CPU not attributable to a record is "other". Launches without accounting
  use the median factor.
- **Final status by cohort.** Share of each cohort holding an L3 certificate, L2 only, or not passing.

## Numbers at this render

- Active time {notes['active_minutes']:.0f} min; tokens {fmt_tok(tok['total'])} ({fmt_tok(tok['fresh'])} fresh,
  {fmt_tok(tok['cached'])} cached input, {fmt_tok(tok['output'])} output).
- Final: {fin['l2']}/{fin['test_cases']} test cases pass L2, {fin['l3']} hold an L3 certificate.
- Speedup: {sp}. Utilization: {ut}. RTL rows used: {perf['rtl_rows_used']}; exclusions per attempt in
  `notes.json → performance.excluded`.
- Self-check latency (request → verdict): median {_min(notes['selfcheck_latency_min']['median'])}
  (n = {notes['selfcheck_latency_min']['n']}); grade duration: median {_min(notes['grade_duration_min']['median'])}
  (n = {notes['grade_duration_min']['n']}).

| cohort | L3 | L2 or better | test cases | L3 required |
|---|---|---|---|---|
{coh}
"""


def _output_dir(m: Manifest, out_dir: str | None) -> tuple[Path, object | None]:
    if out_dir:
        p = Path(out_dir)
        p.mkdir(parents=True, exist_ok=True)
        return p, None
    from merlin.common.artifacts import new_product

    prod = new_product(PRODUCT, version=FIGURE_VERSION, target=m.target,
                       notes=f"campaign figure for {m.campaign}")
    return prod.path, prod


def run(m: Manifest, out_dir: str | None = None, *, formats=("pdf", "svg", "png")) -> Path:
    data = read_campaign(m)
    ser = build_series(data)
    dest, prod = _output_dir(m, out_dir)
    notes = draw(data, ser, str(dest / "campaign_figure"), formats=formats)
    (dest / "notes.json").write_text(json.dumps(notes, indent=1, default=str))
    (dest / "records.json").write_text(json.dumps(data, separators=(",", ":"), default=str))
    if m.source and m.source.is_file():
        shutil.copyfile(m.source, dest / "campaign_manifest.yaml")
    else:
        (dest / "campaign_manifest.yaml").write_text(yaml.safe_dump(m.raw, sort_keys=False))
    (dest / "README.md").write_text(_readme(m, notes))
    if prod is not None:
        for name in [f"campaign_figure.{f}" for f in formats] + ["notes.json", "records.json", "campaign_manifest.yaml", "README.md"]:
            prod.add_artifact(name)
        prod.write_manifest()
    return dest


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m merlin.agentreport.campaign", description=__doc__.split("\n\n")[0])
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--manifest", help="campaign manifest YAML (schema merlin.agentreport.campaign_manifest.v1)")
    src.add_argument("--run-dir", help="a single run directory (shorthand for a one-attempt manifest)")
    ap.add_argument("--workspace")
    ap.add_argument("--agent-home")
    ap.add_argument("--launch-log")
    ap.add_argument("--accounting-log")
    ap.add_argument("--target")
    ap.add_argument("--live", action="store_true", help="the single run is still running")
    ap.add_argument("--out-dir", help="write here instead of a versioned product")
    ap.add_argument("--formats", default="pdf,svg,png")
    a = ap.parse_args(argv)
    if a.manifest:
        m = load(a.manifest)
    else:
        m = single_run(a.run_dir, workspace=a.workspace, agent_home=a.agent_home, launch_log=a.launch_log,
                       accounting_log=a.accounting_log, target=a.target, live=a.live)
    dest = run(m, a.out_dir, formats=tuple(f for f in a.formats.split(",") if f))
    print(dest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
