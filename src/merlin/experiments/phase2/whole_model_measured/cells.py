SCHEMA = "merlin_cell_machine_v1"
DEVICE_MACHINE = "merlin.phase2.whole_model_measured.cells:cell_sum"
ARM_PACKAGE, ARM_REFERENCE = "package", "reference"
#: How a program record states who answers its group (the measurer's own field).
LINKED_SUBMISSION = "submission"
DEFAULT_MAX_CYCLES = 60_000_000
#: The member label of a cell's collateral representatives (never a held-out label).
COLLATERAL = "collateral"
#: A representative's emulator bound: its baseline times this, plus the setup a program needs
#: whatever its group; both overridable in the cell's ``collateral`` block.
DEFAULT_COLLATERAL_BOUND_FACTOR = 3.0
DEFAULT_COLLATERAL_BOUND_SETUP_CYCLES = 2_000_000
#: The cell's own groups measured on the baseline package (``{"groups": [{"group", "cycles", "on"}]}``);
#: it bounds a candidate's objective programs by the same rule as the collateral's.
BASELINE = "baseline"
#: ``{"functional_model": spec, "rooflines": {group: roofline}}``: what the objective's own programs'
#: efficiency rows are taken against (:func:`.group_capsules.efficiency_row`). Diagnostic only.
DIAGNOSTICS = "diagnostics"
BASIS_NOTE = (
    "the sum of the cell's groups, each timed alone in a program of its own on the elaborated-RTL emulator; "
    "compared only with the same cell's reference arm on the same emulator, never with a whole-program "
    "count or a board number"
)


class CellError(RuntimeError):
    """The cell is underdetermined, or its measurer cannot answer."""


class CellMeasurer(Protocol):
    """The target's per-group program builder and timer, as the cell machine calls it.

    ``programs`` builds one program per group of one member and returns ``{label: record}``; a record
    carries ``group``, ``linked`` (``submission`` when the package answers it), ``cause``, ``elf`` and,
    when it could not be built, ``refusal``.  ``scan`` checks one program's WHOLE ELF for the roles and
    returns ``{clean, summary, prohibited}`` (``prohibited``: the ``{selector: name}`` it held the
    program to).  ``time`` runs the given programs and returns ``{label: {status,
    cycles, correct, ...}}``; it is only ever handed programs that may be timed."""

    def programs(
        self, arm: str, groups: Sequence[int], *, package_dir: Path | None, member: Mapping[str, Any], out: Path
    ) -> Mapping[str, Mapping[str, Any]]: ...

    def scan(self, record: Mapping[str, Any], *, roles: Sequence[str]) -> Mapping[str, Any]: ...

    def time(
        self, records: Mapping[str, Mapping[str, Any]], *, member: Mapping[str, Any], max_cycles: int, out: Path
    ) -> Mapping[str, Mapping[str, Any]]: ...


def members(cell: Mapping[str, Any]) -> list[dict[str, Any]]:
    """The objective member first (``label`` None), then each held-out member."""
    if not cell.get("groups") or not (cell.get("model_capsule") or cell.get("capsules")):
        raise CellError("a cell names its groups and its model capsule (or form-perf capsules)")
    rows = [
        {
            # The cell's baseline block is the bound's, not the member's: a member's ``baseline`` is the
            # collateral's per-group bar (:func:`collateral_member`).
            **{k: v for k, v in cell.items() if k not in ("held_out", BASELINE)},
            "label": None,
            "groups": [int(g) for g in cell["groups"]],
        }
    ]
    for held in cell.get("held_out") or ():
        if not held.get("label") or not held.get("groups"):
            raise CellError(f"a held-out row needs a label and groups: {dict(held)}")
        if held["label"] == COLLATERAL:
            raise CellError(f"a held-out row may not be labelled {COLLATERAL!r}: that label is the collateral's")
        rows.append({**dict(held), "groups": [int(g) for g in held["groups"]]})
    return rows


def measure_member(
    measurer: CellMeasurer,
    arm: str,
    member: Mapping[str, Any],
    *,
    package_dir: Path | None,
    roles: Sequence[str],
    out: Path,
    max_cycles: int,
    sealed: Mapping[str, Any] | None = None,
) -> list[dict[str, Any]]:
    """One member's rows: built, refused where the rule or coverage refuses, and only the rest timed.

    For the PACKAGE arm of the OBJECTIVE member, a group the package does not answer is refused
    before any emulator time.  Every package program's whole ELF is scanned for the roles; a scan that
    cannot run refuses (it never passes), and so does one that prohibits less than the ``sealed``
    Phase 0 policy (:func:`.gates.scan_weaker_than_sealed`).

    A FUSED REGION is one program: the internal members' records name the boundary they are timed with
    (``timed_with``), are never timed alone, and take the boundary's grade with no cycles of their own --
    the region's cycles are counted once, at its boundary, and every member is still the package's."""
    records = dict(measurer.programs(arm, member["groups"], package_dir=package_dir, member=member, out=out))
    refused: dict[str, str] = {}
    census: dict[str, Any] = {}
    required = _required_groups(arm, member)
    with_boundary = {label: record for label, record in records.items() if record.get("timed_with") is not None}
    for label, record in records.items():
        if label in with_boundary:
            # A REGION MEMBER IS THE PACKAGE'S ONLY WHILE THE PACKAGE ANSWERS IT: claiming a region and
            # handing a member back is a decline like any other, refused by the same rule.
            if int(record.get("group", -1)) in required and record.get("linked") != LINKED_SUBMISSION:
                refused[label] = (
                    f"coverage: the package does not answer this cell group inside its claimed region "
                    f"({record.get('cause') or record.get('linked')}); not timed"
                )
            continue
        if record.get("refusal"):
            refused[label] = str(record["refusal"])
            continue
        if int(record.get("group", -1)) in required and record.get("linked") != LINKED_SUBMISSION:
            answered_by = record.get("cause") or record.get("linked")
            # The package's own words (its decline reason, an exception it raised), never a paraphrase.
            why = f": {str(record['why'])[:300]}" if record.get("why") else ""
            refused[label] = f"coverage: the package does not answer this cell group ({answered_by}{why}); not timed"
            continue
        if arm == ARM_PACKAGE and roles:
            try:
                scan = dict(measurer.scan(record, roles=roles))
            except Exception as exc:  # noqa: BLE001 -- a scan that cannot run refuses
                scan = {"clean": False, "summary": {}, "error": f"{type(exc).__name__}: {exc}"}
            weaker = G.scan_weaker_than_sealed(scan, sealed, roles) if sealed is not None else ""
            if weaker:
                scan = {**scan, "clean": False, "error": scan.get("error") or weaker}
            if scan.get("clean") is not True:
                refused[label] = "isa_prohibited: " + (
                    ", ".join(sorted(scan.get("summary") or {}))
                    or f"the program could not be checked ({scan.get('error')})"
                )
                continue
            if scan.get("census") is not None:
                census[label] = scan["census"]
    runnable = {
        label: record for label, record in records.items() if label not in refused and label not in with_boundary
    }
    timed = dict(measurer.time(runnable, member=member, max_cycles=max_cycles, out=out)) if runnable else {}
    boundary_label = {int(r.get("group", -1)): label for label, r in records.items() if label not in with_boundary}
    for label, record in with_boundary.items():
        boundary = boundary_label.get(int(record["timed_with"]))
        if label in refused:
            continue
        if boundary is None:
            refused[label] = f"its fused region's boundary g{record['timed_with']} is not among this cell's programs"
        elif boundary in refused:
            refused[label] = (
                f"its fused region's boundary g{record['timed_with']} was refused: {refused[boundary][:200]}"
            )
        else:
            shared = dict(timed.get(boundary) or {"status": "refused", "refusal": "the boundary was not timed"})
            timed[label] = {
                **{k: shared.get(k) for k in ("status", "correct", "refusal", "exactness", "carried")},
                "cycles": 0 if shared.get("status") == "graded" else None,
                "timed_with": int(record["timed_with"]),
            }
    rows = []
    for label, record in sorted(records.items()):
        row = {
            "label": label,
            "group": record.get("group"),
            "model": member.get("label"),
            "linked": record.get("linked"),
            "cause": record.get("cause"),
            "why": record.get("why"),
            "kind": record.get("kind") or record.get("op"),
            "elf_sha256": record.get("elf_sha256"),
        }
        if record.get("region"):
            row["region"] = record["region"]
        if label in refused:
            row.update(status="refused", refusal=refused[label])
        else:
            row.update(dict(timed.get(label) or {"status": "refused", "refusal": "the measurer returned no timing"}))
        if label in census:
            row["census"] = census[label]
        rows.append(row)
    return rows


def _required_groups(arm: str, member: Mapping[str, Any]) -> set[int]:
    """The groups the PACKAGE arm must answer itself: every objective group, and each collateral
    representative its baseline package answered.  Held-out groups are reported, never required."""
    if arm != ARM_PACKAGE:
        return set()
    if member.get("label") is None:
        return {int(g) for g in member["groups"]}
    if member.get("label") == COLLATERAL:
        return {int(g) for g, row in (member.get("baseline") or {}).items() if row.get("on") == "package"}
    return set()


def _on(row: Mapping[str, Any]) -> Any:
    return "package" if row.get("linked") == LINKED_SUBMISSION else row.get("linked")


def collateral_problem(row: Mapping[str, Any], baseline: Mapping[str, Any], tolerance: float) -> str | None:
    """Why one collateral representative refuses the candidate, or None when it is no worse than its
    baseline: no longer answered by the package (with the package's own reason), not timed, wrong, or
    slower than the baseline by more than ``tolerance``."""
    group = str(row["group"])
    if row.get("linked") != LINKED_SUBMISSION and baseline.get("on") == "package":
        why = f": {str(row['why'])[:300]}" if row.get("why") else ""
        return f"collateral g{group}: the package no longer answers it ({row.get('cause') or row.get('linked')}{why})"
    if row.get("status") != "graded":
        return f"collateral g{group}: {str(row.get('refusal') or 'not timed')[:160]}"
    if not row.get("correct"):
        return f"collateral g{group}: output is wrong"
    cycles, base = row.get("cycles"), baseline.get("cycles")
    if isinstance(cycles, int) and isinstance(base, int) and cycles > base * (1.0 + tolerance):
        change = 100 * (cycles / base - 1)
        return f"collateral g{group}: {cycles:,} cycles against the baseline's {base:,} ({change:+.1f}%)"
    return None


def _state(row: Mapping[str, Any]) -> str:
    if row.get("status") != "graded":
        return "refused"
    return "correct" if row.get("correct") else "failed"


def compose_cell(
    rows: Sequence[Mapping[str, Any]],
    *,
    machine: str,
    collateral: Mapping[str, Mapping[str, Any]] | None = None,
    tolerance: float = 0.0,
) -> dict[str, Any]:
    """The service verdict for one cell measurement from its per-program rows (pure).  ``collateral``
    maps each representative group to its baseline (``{"cycles", "on", "form"}``); rows of the
    :data:`COLLATERAL` member are held to it and never summed into the objective."""
    groups, held_out, refused, failed = [], [], [], []
    collateral_rows, regressions = [], []
    for row in rows:
        if row.get("model") == COLLATERAL:
            baseline = dict((collateral or {}).get(str(row["group"])) or {})
            members = [int(g) for g in (row.get("region") or {}).get("members") or ()]
            if members and row.get("timed_with") is None:
                # A REGION'S BOUNDARY times every member: it is held to the sum of their baselines.
                baselines = [(collateral or {}).get(str(m)) or {} for m in members]
                if all(isinstance(b.get("cycles"), int) for b in baselines):
                    baseline["cycles"] = sum(int(b["cycles"]) for b in baselines)
            elif row.get("timed_with") is not None:
                baseline.pop("cycles", None)  # timed inside its boundary's program, whose sum is checked
            problem = collateral_problem(row, baseline, tolerance)
            collateral_rows.append(
                {
                    "group": str(row["group"]),
                    "cycles": row.get("cycles"),
                    "baseline_cycles": baseline.get("cycles"),
                    "form": baseline.get("form"),
                    "on": _on(row),
                    "carried": row.get("carried"),
                    "state": "regressed" if problem else "ok",
                    **({"problem": problem} if problem else {}),
                }
            )
            if problem:
                regressions.append(problem)
            continue
        entry = {
            "group": str(row["group"]),
            "kind": row.get("kind") or row.get("linked"),
            "cycles": row.get("cycles"),
            "state": _state(row),
            "correct": row.get("status") == "graded" and bool(row.get("correct")),
            "on": "package" if row.get("linked") == LINKED_SUBMISSION else row.get("linked"),
        }
        if row.get("refusal"):
            entry["refusal"] = str(row["refusal"])[:300]
        if row.get("region"):
            entry["region"] = row["region"]
        if row.get("timed_with") is not None:
            entry["timed_with"] = row["timed_with"]  # its cycles are its region boundary's
        where = f"{row['model']}:g{row['group']}" if row.get("model") else f"g{row['group']}"
        (held_out.append({**entry, "model": row["model"]}) if row.get("model") else groups.append(entry))
        if entry["state"] == "refused":
            refused.append(where)
        elif entry["state"] == "failed":
            failed.append(where)
    total = sum(int(g["cycles"]) for g in groups if isinstance(g.get("cycles"), int))
    status = V.TIMING_REFUSED if refused or regressions else V.TIMING_MEASURED_INVALID if failed else V.TIMING_MEASURED
    verdict: dict[str, Any] = {
        "schema": V.SCHEMA,
        "timing_status": status,
        "timing_basis": "cell_sum",
        "basis_note": BASIS_NOTE,
        "machine": machine,
        "whole_window_cycles": total if not refused else None,
        "objective_cycles": total if status == V.TIMING_MEASURED else None,
        "correctness": {
            "status": "pass" if not (refused or failed) else "fail",
            "groups_failed": failed,
            "evidence": "each cell and held-out group's own exact grade on the emulator",
        },
        "groups": groups,
        "held_out": held_out,
        "collateral": collateral_rows,
    }
    if refused:
        verdict["refusal"] = f"{len(refused)} cell program(s) refused: " + ", ".join(refused[:12])
    if regressions:
        verdict["collateral_regression"] = regressions
        lead = "COLLATERAL REGRESSION (other forms of the model got worse): " + "; ".join(regressions[:6])
        verdict["refusal"] = lead + ("; " + verdict["refusal"] if verdict.get("refusal") else "")
    return verdict


def collateral_representatives(
    objective_forms: Sequence[Mapping[str, Any]], groups: Sequence[int], share: Mapping[str, Any]
) -> list[dict[str, Any]]:
    """One representative group per OTHER form of the objective model: the member holding the largest
    ``share`` (a group -> cycles mapping, e.g. the reference arm's per-group counts on the cell's
    machine).  ``objective_forms`` rows carry ``group`` and ``form_text``.  The cell's own forms are
    excluded -- they are the objective.  A form none of whose members has a count is represented by its
    first member, never skipped."""
    mine = {int(g) for g in groups}
    own = {r["form_text"] for r in objective_forms if int(r["group"]) in mine}
    by_form: dict[str, list[str]] = {}
    for row in objective_forms:
        if row["form_text"] not in own:
            by_form.setdefault(row["form_text"], []).append(str(row["group"]))
    picked = []
    for text, member_groups in by_form.items():
        counted = [g for g in member_groups if isinstance(share.get(g), (int, float))]
        group = max(counted, key=lambda g: share[g]) if counted else member_groups[0]
        picked.append({"group": int(group), "form": text, "members": len(member_groups)})
    return sorted(picked, key=lambda r: r["group"])


def collateral_baseline(
    representatives: Sequence[Mapping[str, Any]], baseline_rows: Sequence[Mapping[str, Any]], *, tolerance: float
) -> dict[str, Any]:
    """The cell's ``collateral`` block: each representative with the BASELINE package's own standalone
    measurement (``baseline_rows``: :func:`measure_member` rows).  A representative the baseline could
    not time correctly is refused here, never carried as a bar.  A representative the baseline's PACKAGE
    does not answer (the library or host code runs it) measures no code a candidate can change: it is
    left out and listed under ``not_package`` with the baseline's own reason."""
    rows = {str(r["group"]): r for r in baseline_rows}
    out, excluded = [], []
    for rep in representatives:
        row = rows.get(str(rep["group"]))
        if row is not None and row.get("linked") != LINKED_SUBMISSION:
            excluded.append({**dict(rep), "cause": row.get("cause") or row.get("refusal"), "why": row.get("why")})
            continue
        if not row or row.get("status") != "graded" or not row.get("correct") or not isinstance(row.get("cycles"), int):
            raise CellError(f"the baseline has no correct standalone measurement of collateral g{rep['group']}: {row}")
        out.append({**dict(rep), "cycles": int(row["cycles"]), "on": _on(row)})
    return {"tolerance": float(tolerance), "groups": out, "not_package": excluded}


def measure_collateral_baseline(
    spec: Mapping[str, Any],
    representatives: Sequence[Mapping[str, Any]],
    *,
    baseline_package: Path,
    target: str,
    out: Path,
    tolerance: float,
) -> dict[str, Any]:
    """Measure ``baseline_package`` (the seed, or the run's best) on each representative by the cell's
    own path and return the ``collateral`` block a cell machine carries.  Nothing is required of the
    baseline's coverage: what it answers is what a candidate must keep answering."""
    cell = dict(spec.get("cell") or {})
    timing = dict(spec.get("timing") or {})
    member = {
        **{k: v for k, v in cell.items() if k not in ("held_out", COLLATERAL)},
        "label": COLLATERAL,
        "groups": [int(r["group"]) for r in representatives],
        "target": target,
    }
    rows = measure_member(
        _measurer(spec),
        ARM_PACKAGE,
        member,
        package_dir=Path(baseline_package),
        roles=(),
        out=Path(out),
        max_cycles=int(timing.get("max_cycles") or DEFAULT_MAX_CYCLES),
    )
    block = collateral_baseline(representatives, rows, tolerance=tolerance)
    from merlin.common.tree_hash import hash_tree

    block["baseline_package_sha256"] = hash_tree(Path(baseline_package))["sha256"]
    return block


def cell_baseline(groups: Sequence[int], baseline_rows: Sequence[Mapping[str, Any]]) -> dict[str, Any] | None:
    """The cell's ``baseline`` block: its own groups' cycles on the baseline package, which bound a
    candidate's objective programs (:func:`objective_bound`).  None -- and the flat bound -- unless the
    baseline timed EVERY cell group correctly: a bound read off a subset would understate the group it
    is missing."""
    rows = {str(r["group"]): r for r in baseline_rows}
    out = []
    for group in groups:
        row = rows.get(str(group))
        if not row or row.get("status") != "graded" or not row.get("correct") or not isinstance(row.get("cycles"), int):
            return None
        out.append({"group": int(group), "cycles": int(row["cycles"]), "on": _on(row)})
    return {"groups": out}


def measure_cell_baseline(
    spec: Mapping[str, Any], *, baseline_package: Path, target: str, out: Path
) -> dict[str, Any] | None:
    """Measure ``baseline_package`` on the cell's own groups by the cell's own path and return the
    ``baseline`` block a cell machine carries, or None when the baseline did not time every group."""
    cell = dict(spec.get("cell") or {})
    timing = dict(spec.get("timing") or {})
    member = {**members(cell)[0], "target": target}
    rows = measure_member(
        _measurer(spec),
        ARM_PACKAGE,
        member,
        package_dir=Path(baseline_package),
        roles=(),
        out=Path(out),
        max_cycles=int(timing.get("max_cycles") or DEFAULT_MAX_CYCLES),
    )
    block = cell_baseline(member["groups"], rows)
    if block is not None:
        from merlin.common.tree_hash import hash_tree

        block["baseline_package_sha256"] = hash_tree(Path(baseline_package))["sha256"]
    return block


def baseline_bound(block: Mapping[str, Any] | None) -> int | None:
    """The emulator cycle bound a baseline block implies (worst group x factor + setup), or None when
    it states no cycles.  The factor and setup are the block's own when it states them."""
    rows = [r for r in (block or {}).get("groups") or () if isinstance(r.get("cycles"), int)]
    if not rows:
        return None
    factor = float((block or {}).get("bound_factor") or DEFAULT_COLLATERAL_BOUND_FACTOR)
    setup = int((block or {}).get("bound_setup_cycles") or DEFAULT_COLLATERAL_BOUND_SETUP_CYCLES)
    return int(max(int(r["cycles"]) for r in rows) * factor + setup)


def flat_bound(timing: Mapping[str, Any]) -> int:
    return int(timing.get("max_cycles") or DEFAULT_MAX_CYCLES)


def objective_bound(cell: Mapping[str, Any], timing: Mapping[str, Any]) -> tuple[int, str]:
    """``(max_cycles, basis)`` for a candidate's objective programs: derived from ``cell.baseline``
    when the cell carries one, the flat bound otherwise (an older cell spec)."""
    derived = baseline_bound(cell.get(BASELINE))
    if derived is None:
        return flat_bound(timing), "flat: the cell carries no baseline of its own groups"
    return derived, "derived from cell.baseline: worst group x factor + setup"


def collateral_member(cell: Mapping[str, Any], target: str) -> tuple[dict[str, Any], int] | None:
    """The collateral member of a candidate's measurement and its emulator bound, or None.  The bound is
    derived from the worst baseline: a representative never needs more to show it is no worse."""
    block = dict(cell.get(COLLATERAL) or {})
    reps = list(block.get("groups") or ())
    if not reps:
        return None
    member = {
        **{k: v for k, v in cell.items() if k not in ("held_out", COLLATERAL, DIAGNOSTICS)},
        "label": COLLATERAL,
        "groups": [int(r["group"]) for r in reps],
        "baseline": {int(r["group"]): dict(r) for r in reps},
        "target": target,
    }
    return member, int(baseline_bound({**block, "groups": reps}) or 0)


def _measurer(spec: Mapping[str, Any]) -> CellMeasurer:
    factory = load_builder(str(spec.get("measurer") or ""))
    return factory(spec)


def measure_cell(job: Mapping[str, Any], job_dir: Path, package: Path, *, target: str) -> dict[str, Any]:
    """One candidate's cell measurement, as the result fields the service writes."""
    spec = dict(job.get("machine") or {})
    cell = dict(spec.get("cell") or {})
    timing = dict(spec.get("timing") or {})
    roles = list((job.get("build_options") or {}).get("prohibited_roles") or ())
    sealed = job.get("instruction_policy")
    unsealed = G.sealed_policy_problems(sealed, roles)
    if unsealed:
        # Before any program is built: a cell under a rule nobody sealed spends emulator time on
        # programs whose instruction scan could not have refused them.
        raise J.ServiceError(f"the cell carries no enforceable sealed instruction policy ({'; '.join(unsealed)})")
    # THE EXACTNESS CONTRACT the run carries (the cell machine's own when the job carries none): every
    # program's group is graded under it, and the result records which contract that was.
    from merlin.perf import exactness as EX

    carried = (job.get("exactness") or {}).get("contract") or spec.get("exactness")
    contract = EX.Contract.from_value(carried, target=target)
    # The package arm is built by the job's own recipe (its build options), as its whole model would be.
    measurer = _measurer(
        {**spec, "build_options": dict(job.get("build_options") or {}), "exactness": contract.to_document()}
    )
    rows: list[dict[str, Any]] = []
    # A member never needs more than its own baseline (two invocations and setup) to show it is no
    # worse; a regression or a deadlock is refused at that bound instead of run to a flat one.
    plan = []
    for member in members(cell):
        if member["label"] is None:
            bound, basis = objective_bound(cell, timing)
        else:
            bound, basis = flat_bound(timing), "flat: a held-out group has no baseline"
        plan.append(({**member, "target": target}, bound, basis))
    collateral = collateral_member(cell, target)
    if collateral is not None:
        plan.append((*collateral, "derived from cell.collateral: worst group x factor + setup"))
    for member, bound, basis in plan:
        rows += [
            {**row, "max_cycles": bound, "max_cycles_basis": basis}
            for row in measure_member(
                measurer,
                ARM_PACKAGE,
                member,
                package_dir=package,
                roles=roles,
                out=Path(job_dir) / "cell" / (member["label"] or "objective"),
                max_cycles=bound,
                sealed=sealed if roles else None,
            )
        ]
    machine = str(timing.get("registry_machine") or spec.get("registry_name") or "cell")
    block = dict(cell.get(COLLATERAL) or {})
    verdict = compose_cell(
        rows,
        machine=machine,
        collateral={str(r["group"]): r for r in block.get("groups") or ()},
        tolerance=float(block.get("tolerance") or 0.0),
    )
    (Path(job_dir) / "cell_rows.json").write_text(json.dumps(rows, indent=1, default=str) + "\n", encoding="utf-8")
    fields: dict[str, Any] = {
        "timing_status": verdict["timing_status"],
        "objective_cycles": V.objective_cycles(verdict),
        "verdict": verdict,
        "build": {
            "groups": [
                {
                    "group": str(r["group"]),
                    "op": r.get("kind"),
                    "on": "package" if r.get("linked") == LINKED_SUBMISSION else r.get("linked"),
                    "cause": r.get("cause"),
                }
                for r in rows
                if not r.get("model")
            ],
            "collateral": verdict.get("collateral") or [],
            "isa_census": {
                "per_group": {str(r["group"]): r["census"] for r in rows if r.get("census") and not r.get("model")}
            },
            "cell": {
                "id": cell.get("id"),
                "groups": list(cell.get("groups") or ()),
                "held_out": cell.get("held_out") or [],
            },
            "programs": [{k: r.get(k) for k in ("label", "elf_sha256")} for r in rows],
        },
        "device": {
            "machine": DEVICE_MACHINE,
            "artifact": machine,
            "binary_sha256": machine,
            "rung": "gsim",
            "timing_basis": "cell_sum",
        },
    }
    prohibited = [r for r in rows if str(r.get("refusal") or "").startswith("isa_prohibited")]
    if prohibited:
        summary = {f"{r['model'] + ':' if r.get('model') else ''}g{r['group']}": 1 for r in prohibited}
        fields["isa_prohibited"] = {
            "clean": False,
            "roles": roles,
            "summary": summary,
            "scope": "whole_elf",
            "checked_build": "cell programs",
        }
        fields["refusal"] = "isa_prohibited: " + ", ".join(sorted(summary))
    elif verdict.get("refusal"):
        fields["refusal"] = verdict["refusal"]
    diagnostics = diagnostics_of(rows, cell)
    if diagnostics:
        fields["diagnostics"] = diagnostics
    per_group = {
        f"{r['model'] + ':' if r.get('model') else ''}g{r['group']}": r.get("exactness")
        for r in rows
        if r.get("exactness")
    }
    summary: dict[str, int] = {}
    for label in per_group.values():
        summary[str(label)] = summary.get(str(label), 0) + 1
    fields["exactness"] = {
        "contract": contract.record(),
        "per_group": per_group,
        "summary": summary,
        "label": EX.label_summary({"summary": summary}),
    }
    return fields


def diagnostics_of(rows: Sequence[Mapping[str, Any]], cell: Mapping[str, Any]) -> dict[str, Any] | None:
    """``{"per_group": {group: {"roofline", "efficiency"}}}`` for the objective's groups: each group's
    derived roofline beside what its program issued -- numbers, never a fix. None without a roofline."""
    rooflines = dict((cell.get(DIAGNOSTICS) or {}).get("rooflines") or {})
    if not rooflines:
        return None
    per_group = {
        str(row["group"]): {"roofline": rooflines.get(str(row["group"])), "efficiency": row.get("efficiency")}
        for row in rows
        if not row.get("model")
    }
    return {"schema": "merlin_cell_diagnostics_v1", "per_group": per_group}


def reference_cell(spec: Mapping[str, Any], *, target: str, out: Path) -> dict[str, Any]:
    """The cell's REFERENCE arm -- the vendor reference answering every cell group, unrestricted (it is
    the bar) -- measured by the same path, as a result document the objective reads as its reference."""
    cell = dict(spec.get("cell") or {})
    timing = dict(spec.get("timing") or {})
    measurer = _measurer(spec)
    rows: list[dict[str, Any]] = []
    bound = flat_bound(timing)
    for member in members(cell):
        rows += [
            # The library can be far slower than the package: the reference arm keeps the flat bound.
            {**row, "max_cycles": bound, "max_cycles_basis": "flat: the reference arm has no baseline"}
            for row in measure_member(
                measurer,
                ARM_REFERENCE,
                {**member, "target": target},
                package_dir=None,
                roles=(),
                out=Path(out) / "cell" / (member["label"] or "objective"),
                max_cycles=bound,
            )
        ]
    machine = str(timing.get("registry_machine") or spec.get("registry_name") or "cell")
    verdict = compose_cell(rows, machine=machine)
    document = {
        "schema": J.RESULT_SCHEMA,
        "role": J.ROLE_REFERENCE,
        "label": f"cell reference {cell.get('id') or ''}".strip(),
        "timing_status": verdict["timing_status"],
        "objective_cycles": V.objective_cycles(verdict),
        "verdict": verdict,
        "machine": dict(spec),
        "device": {
            "machine": DEVICE_MACHINE,
            "artifact": machine,
            "binary_sha256": machine,
            "rung": "gsim",
            "timing_basis": "cell_sum",
        },
    }
    Path(out).mkdir(parents=True, exist_ok=True)
    (Path(out) / "result.json").write_text(json.dumps(document, indent=1, default=str) + "\n", encoding="utf-8")
    return document


def transplant(screen: Any, package: Path, *, cell_id: str, cell_digest: str, why: str) -> dict[str, Any]:
    """Request a cell's winning bytes on the WHOLE-MODEL screen, where the board adjudicates.  The
    request carries the store's coverage gate like any candidate; the transplant is recorded in the
    screen's store (``transplants.jsonl``) with the cell result it came from."""
    if not str(why or "").strip():
        raise CellError("a transplant states why")
    job = screen.request(Path(package), label=f"cell transplant {cell_id}", role=J.ROLE_CANDIDATE)
    entry = {
        "at": now(),
        "cell": cell_id,
        "cell_result_package_sha256": cell_digest,
        "whole_model_job": job.get("job_key") or job.get("package_sha256"),
        "aliased_from": job.get("aliased_from"),
        "why": str(why).strip(),
    }
    with (Path(screen.root) / "transplants.jsonl").open("a", encoding="utf-8") as log:
        log.write(json.dumps(entry, sort_keys=True) + "\n")
    return {**entry, "job_state": job.get("state")}


