"""CELL mode: the inner loop measures a candidate on form-perf cells, the whole model adjudicates.

A cell is a named set of compute groups of the objective model (its form-perf capsules: one group's
form at model shapes, on the model's own inputs, with a vendor-reference arm), plus optionally groups of
held-out models the package is graded on without being tuned for.  Each is built as its own program
and timed on the elaborated-RTL emulator, graded EXACTLY, the package program's whole ELF held to the
instruction rule.  No whole-model program is built, so a try costs one program per cell group whose
bytes changed.

THE OBJECTIVE is the sum of the objective model's cell groups' cycles, and only when every cell group
AND every held-out group is correct and clean.

NO GAMING BY DECLINING, AND NO EMULATOR TIME FOR IT.  A cell group the package does not answer (the
library or host code would run in its place) refuses the candidate by name -- and it is refused
BEFORE any emulator time: timing the library's host fallback in its place once held both emulator
slots for over two hours per candidate, for a number nothing may use.  Held-out groups are reported by
who answered them (a transfer check, not a coverage claim).

COLLATERAL: A CELL EDIT MUST NOT BREAK THE REST OF THE MODEL.  The package is shared by every group of
the model, so an edit made for the cell's own groups changes the others too.  Measured on the old line:
a stem-conv candidate that sped its cell up 28% made every 1x1 contraction decline (an exception in
shared lowering code), each fell to host code, and the whole model went from about 40M cycles to 28.4
BILLION -- invisible to the cell's own groups and to a same-form held-out group.  ``cell.collateral``
names one representative group of every OTHER form of the objective model, each with the BASELINE
package's own standalone cycles (:func:`collateral_representatives`, :func:`measure_collateral_baseline`).
The candidate's program for each is built and timed the same way, and the candidate is REFUSED when any
representative is no longer answered by the package (quoting the package's own reason), is wrong, or is
slower than its baseline by more than ``collateral.tolerance``.  A representative's emulator bound is
derived from its baseline, so a regression is refused at the bound rather than run to the end; a
representative whose program is unchanged is the measurer's to read back from its timing cache.

THE EMULATOR BOUND IS DERIVED, NOT FLAT.  A program's cycle budget is its baseline's worst group times a
factor plus setup (a one-group program loads, then runs the group twice: one untimed warm invocation,
one timed).  Collateral representatives take it from ``cell.collateral``; the objective's own groups,
for a candidate, from ``cell.baseline`` (the same groups measured on the verified baseline package when
the cell was prepared, :func:`measure_cell_baseline`).  Measured on the old line, 2026-10-01: a 1x1
candidate whose groups take at most 0.6M cycles deadlocked and ran every program to a flat 60M bound --
5.5 h each -- before it could be refused.  The reference arm (the library, which can be far slower than
the package) and held-out groups have no baseline here and keep the flat bound; every row records the
bound it ran under and its basis.

A CELL NUMBER RANKS; IT IS NEVER A BOARD COUNT.  A candidate a cell ranks best is TRANSPLANTED: its
exact bytes are requested on the whole-model screen (:func:`transplant`), where FireSim adjudicates
with the reference control in the batch and the store's coverage gate applies.

How a program is built, scanned and timed is the measurer's: the cell machine names a MEASURER
(``module:callable`` returning an object with ``programs``, ``scan`` and ``time``, see
:class:`CellMeasurer`) -- :func:`.group_capsules.cell_measurer`, one-group programs generated by the
target's own whole-model driver and timed on the elaborated-RTL emulator, is the real one.  The measurer
receives the cell machine's spec plus the job's ``build_options`` (the package arm's recipe).  Nothing
here names a target, a model or a group.
"""

from __future__ import annotations

