# ---- chain_image_profile -----------------------------------------------------------------------

MARKER = "/* Generated by merlin.runtime.harness.output_observation. Do not edit. */"
RESET = """
void merlin_group_profile_reset(void) {
  merlin_group_count = 0;
  merlin_group_dropped = 0;
}
"""


def prepare(program, directory, *, nm, timeout):
    original = program["by_name"].get("group_profile.o")
    if original is None:
        return prepare_completed(program, directory, nm=nm, timeout=timeout)
    table = objects.symbols(nm, objects.reopen(original), timeout=timeout)
    if table.get("merlin_group_profile_dump") != "T":
        raise ValueError("retained profiling object lacks the generated dump hook")
    if table.get("merlin_group_profile_reset") == "T":
        return program, None
    command = layout.command(program, "group_profile.o")
    sources = [row for row in command["inputs"] if row["path"].endswith(".c")]
    if len(sources) != 1:
        raise ValueError("retained profiling compilation lacks one pinned C source")
    source = objects.payload(sources[0]).decode("utf-8")
    if (
        not source.startswith(MARKER + "\n")
        or source.count("static uint64_t merlin_group_count, merlin_group_dropped;") != 1
        or source.count("void merlin_group_profile_dump(uint64_t forward_start, uint64_t forward_end) {") != 1
        or "merlin_group_profile_reset" in source
    ):
        raise ValueError("unsupported retained profiling source ABI")
    objects.reopen(command["executable"])
    directory.mkdir()
    generated, product = directory / "group_profile.c", directory / "group_profile.o"
    generated.write_text(source + RESET)
    inputs = tuple(objects.reopen(row) for row in command["inputs"])
    invocation_record.run(
        layout.compile_argv(command, generated, product),
        directory=directory,
        stage="chain_image_profile_reset",
        inputs=(*inputs, objects.reopen(original), generated),
        outputs=(product,),
        dependencies=(Path(__file__), Path(layout.__file__)),
        capture_output=True,
        text=True,
        check=True,
        timeout=timeout,
    )
    updated = objects.pin(product)
    result = {
        **program,
        "objects": [updated if row == original else row for row in program["objects"]],
        "by_name": {**program["by_name"], "group_profile.o": updated},
    }
    record = {
        "original_object": original,
        "original_source": sources[0],
        "source": objects.pin(generated),
        "object": updated,
        "invocations": [objects.pin(p) for p in directory.glob("invocations/*/invocation.json")],
        "scope": "host profiling reset only; graph/device/weight objects unchanged",
    }
    return result, record


def verify(record):
    if record is not None:
        keys = (
            ("source", "object", "bindings")
            if record.get("schema") == "merlin.completed_program_group_profile.v1"
            else ("original_object", "original_source", "source", "object")
        )
        for key in keys:
            objects.reopen(record[key])
        for row in (*record.get("inputs", ()), *record.get("original_objects", ())):
            objects.reopen(row)
        for row in record["invocations"]:
            invocation_record.verify(objects.reopen(row))


# ---- chain_image_profile_new -------------------------------------------------------------------
# Add ordinary counter wrappers to completed unprofiled program objects.
#
# Only generated host observation code is compiled. All original model, device,
# weights and runtime objects remain inputs to the normal recurrent-image link.


def prepare_completed(program, directory, *, nm, timeout):
    directory.mkdir()
    model = objects.reopen(program["by_name"]["model.o"])
    undefined = {
        name for name, kind in objects.symbols(nm, model, timeout=timeout, directory=directory).items() if kind == "U"
    }
    sidecar = program["receipt"]["output"]["device_sidecar"]
    routing = json.loads(objects.payload(sidecar))
    bindings, observed = completed_sibling_bindings(program, routing, undefined)
    missing = {
        row["symbol"]
        for row in routing.get("routed", ())
        if row["symbol"] not in bindings
        and row["symbol"] not in undefined
        and "_mlir_ciface_" + row["symbol"] not in undefined
    }
    if missing:
        descriptor, pins = completed_descriptor_bindings(program, routing, undefined)
        if bindings.keys() & descriptor.keys():
            raise ValueError("completed profile has overlapping original ABI bindings")
        bindings.update(descriptor)
        observed.extend(pins)
    command = layout.command(program, "model.o")
    if len(command["inputs"]) != 1:
        raise ValueError("completed profile requires the actual unique model compiler input")
    original_source = objects.reopen(command["inputs"][0])
    observations = [
        program["receipt_pin"],
        program["recipe_pin"],
        sidecar,
        program["by_name"]["model.o"],
        command["inputs"][0],
        *observed,
    ]
    source, flags = emit_profile(
        directory,
        routing,
        routing,
        undefined,
        bindings=bindings,
        source=original_source,
        model_object=model,
        source_kind="compiled_model_input",
        observations=observations,
    )
    product = directory / "group_profile.o"
    driver = layout.command(program, "model_main.o")
    invocation_record.run(
        layout.compile_argv(driver, source, product),
        directory=directory,
        stage="chain_image_completed_group_profile",
        inputs=(source,),
        outputs=(product,),
        dependencies=(Path(__file__), Path(layout.__file__)),
        capture_output=True,
        text=True,
        check=True,
        timeout=timeout,
    )
    selected = objects.pin(product)
    wraps = objects.wrap_names(flags)
    result = {
        **program,
        "objects": [*program["objects"], selected],
        "by_name": {**program["by_name"], "group_profile.o": selected},
        "profile_wraps": wraps,
    }
    record = dict(
        schema="merlin.completed_program_group_profile.v1",
        source=objects.pin(source),
        object=selected,
        bindings=objects.pin(directory / "group_profile_bindings.json"),
        inputs=observations,
        invocations=[objects.pin(p) for p in directory.glob("invocations/*/invocation.json")],
        wraps=list(wraps),
        original_objects=program["objects"],
        boundary="inclusive external ABI call: bridge, selected leaf and its readout; not pure device time",
        scope="host counter wrapper only; original graph/device/weights sections unchanged",
    )
    return result, record


# ---- chain_image_profile_descriptor ------------------------------------------------------------
# Observe completed descriptor bridge ABIs without restoring effect owners.
#
# Only profiling names and pointer arities are returned. Source, compiled shim,
# native checkpoint and completed lowering witnesses remain separate retained
# inputs; serialized effects never become a live lifetime or numerical grant.


def _functions(module):
    result = {}
    for op in module.body.block.ops:
        if isinstance(op, func.FuncOp):
            name = op.sym_name.data
            if name in result:
                raise ReadbackError("descriptor profile source has duplicate functions")
            result[name] = op
    return result


def _source_binding(row, original, selected):
    """Check the actual typed wrapper, including its returned destination."""
    names = [row[key] for key in ("symbol", "borrowed_symbol", "wrapper_symbol")]
    if any(not isinstance(n, str) or not n.isascii() or not n.isidentifier() for n in names):
        raise ReadbackError("descriptor profile requires ordinary distinct symbols")
    if len(set(names)) != 3 or any(n in original for n in names[1:]):
        raise ReadbackError("descriptor profile wrapper names are ambiguous")
    symbol, borrowed, wrapper = names
    declaration = original.get(symbol)
    if declaration is None or declaration.body.blocks or declaration.arg_attrs is None:
        raise ReadbackError("descriptor profile lacks its original tensor declaration")
    types = tuple(declaration.function_type.inputs)
    output = row["result_argument"]
    if (
        type(output) is not int
        or not 0 <= output < len(types)
        or len(types) > 64
        or any(not isinstance(t, TensorType) for t in types)
        or [str(t) for t in types] != row["argument_types"]
        or tuple(declaration.function_type.outputs) != (types[output],)
    ):
        raise ReadbackError("descriptor profile tensor signature changed")
    accesses = tuple(a.data["bufferization.access"].data for a in declaration.arg_attrs)
    layouts = tuple(a.data.get("bufferization.buffer_layout", NoneAttr()) for a in declaration.arg_attrs)
    if list(accesses) != row["argument_access"] or list(map(str, layouts)) != row.get(
        "argument_layouts", [str(NoneAttr())] * len(types)
    ):
        raise ReadbackError("descriptor profile argument access or layouts changed")
    # Observation data only: never instantiate or reconstruct a checked effect owner.
    observation = SimpleNamespace(
        symbol=symbol,
        borrowed_symbol=borrowed,
        wrapper_symbol=wrapper,
        argument_types=types,
        argument_access=accesses,
        argument_layouts=layouts,
        result_argument=output,
    )
    buffers = identities.argument_buffer_types(observation)
    block = Block(arg_types=types)
    arguments = []
    for index, (argument, typ) in enumerate(zip(block.args, buffers, strict=True)):
        op = linalg_mlir.layout_to_buffer_type().build(
            operands=[argument],
            result_types=[typ],
            properties={} if index == output else {"read_only": UnitAttr()},
        )
        block.add_op(op)
        arguments.append(op.results[0])
    block.add_op(func.CallOp(borrowed, arguments, []))
    result = bufferization.ToTensorOp(arguments[output], restrict=True, writable=True)
    block.add_ops([result, func.ReturnOp(result.tensor)])
    expected = func.FuncOp(wrapper, (types, (types[output],)), Region(block), visibility="private")
    expected.properties["arg_attrs"] = declaration.arg_attrs
    external = func.FuncOp(borrowed, (buffers, ()), Region(), visibility="private")
    external.attributes["llvm.emit_c_interface"] = UnitAttr()
    for name, value in ((symbol, declaration), (wrapper, expected), (borrowed, external)):
        if name not in selected or not value.clone().is_structurally_equivalent(selected[name]):
            raise ReadbackError(f"descriptor profile source differs from its exact pointer wrapper: {name}")
    return observation, dict(
        borrowed_symbol=borrowed,
        buffers=len(types),
        argument_ranks=[len(t.get_shape()) for t in types],
        wrapper_symbol=wrapper,
    )


def completed_descriptor_bindings(program, routing, undefined):
    """Read a verified completed program's actual descriptor pointer-call ABI.

    Return existing profiler bindings plus ordinary immutable artifact pins.
    This grants neither original effects nor numerical or timing qualification.
    """
    output = program["receipt"]["output"]
    if not (output.get("descriptor_results") or {}).get("selected"):
        return {}, []
    root, preparation = Path(program["root"]), program["recipe"]["preparation"]
    pins = {}

    def retain(pin):
        value = objects.payload(pin)
        actual = objects.pin(Path(pin["path"]))
        if actual["path"] in pins and pins[actual["path"]] != actual:
            raise ReadbackError("descriptor profile has conflicting artifact identities")
        pins[actual["path"]] = actual
        return value

    def bound(path):
        matches = [p for p in preparation.values() if Path(p["path"]) == path]
        if not matches or any(p != matches[0] for p in matches):
            raise ReadbackError("descriptor profile artifact is absent from completed compilation")
        return retain(matches[0])

    for key in ("receipt_pin", "recipe_pin"):
        retain(program[key])
    if json.loads(bound(root / "device_signatures.json")) != routing:
        raise ReadbackError("descriptor profile routing differs from completed source")
    lower_dir = root / "lower"
    report_bytes = bound(lower_dir / "descriptor-result-identity.json")
    report = json.loads(report_bytes)
    lower = json.loads(bound(lower_dir / "lowering_recipe.json"))
    if (
        report.get("schema") != "merlin.descriptor_result_preparation.v1"
        or lower.get("status") != "returned"
        or lower.get("descriptor_result_identity", {}).get("report", {}).get("sha256") != sha256_bytes(report_bytes)
    ):
        raise ReadbackError("descriptor profile lacks the consumed lowering join")
    actual_llvm = bound(lower_dir / "model.ll")
    if lower.get("returned_llvm_ir") != {"sha256": sha256_bytes(actual_llvm), "bytes": len(actual_llvm)}:
        raise ReadbackError("descriptor profile returned LLVM differs from completed lowering")
    sources = lower["sources"]
    native = json.loads(retain(sources["borrowed_lifetime_report"]))
    checkpoint = retain(sources["borrowed_lifetime_checkpoint"])
    if (
        native.get("status") != "checked"
        or native.get("violations") != []
        or native.get("checkpoint_sha256") != sha256_bytes(checkpoint)
    ):
        raise ReadbackError("descriptor profile native checkpoint is absent or changed")
    original = _functions(linalg_mlir.parse_mlir_text(retain(report["original_source"]).decode()))
    selected = _functions(linalg_mlir.parse_mlir_text(retain(report["selected_source"]).decode()))
    shim_source_path, shim_path = root / "device" / "device_shim.c", root / "device" / "device_shim.o"
    shim_source = bound(shim_source_path).decode()
    shim_pin = program["by_name"].get(shim_path.name)
    if shim_pin is None or Path(shim_pin["path"]) != shim_path:
        raise ReadbackError("descriptor profile shim is absent from actual final link")
    retain(shim_pin)
    # Locate its actually observed C compilation, rather than guessing a prototype from a name.
    observations = []
    for pin in preparation.values():
        if Path(pin["path"]).name != "invocation.json":
            continue
        observed = json.loads(objects.payload(pin))
        if any(Path(p["path"]) == shim_path for p in observed.get("outputs", [])):
            observations.append((pin, observed))
    if len(observations) != 1:
        raise ReadbackError("descriptor profile needs one observed compiled shim")
    invocation_pin, observed = observations[0]
    retain(invocation_pin)
    verified = invocation_record.verify(Path(invocation_pin["path"]))
    if (
        verified != observed
        or shim_pin["sha256"] not in {p["sha256"] for p in observed["outputs"]}
        or not any(
            Path(p["path"]) == shim_source_path and p["sha256"] == pins[str(shim_source_path)]["sha256"]
            for p in observed["inputs"]
        )
    ):
        raise ReadbackError("descriptor profile source differs from observed compiled shim")
    wanted = {r["symbol"] for r in routing.get("routed", [])}
    calls = {r["symbol"]: r for r in report["calls"] if r.get("calls")}
    result = {}
    for row in report["selection"]:
        symbol = row["symbol"]
        if symbol not in wanted or symbol not in calls:
            continue
        observation, binding = _source_binding(row, original, selected)
        actual = "_mlir_ciface_" + binding["borrowed_symbol"]
        if actual not in undefined:
            continue
        if symbol in undefined or "_mlir_ciface_" + symbol in undefined:
            raise ReadbackError("descriptor profile original and borrowed ABI both remain referenced")
        if not {binding["borrowed_symbol"], binding["wrapper_symbol"]} <= set(native["accepted_symbols"]):
            raise ReadbackError("descriptor profile wrapper lacks its actual native observation")
        variants = [_merlin_device_shim_1._logical_borrowed_result_wrapper(observation)]
        if len(observation.argument_types) == 3 and len(set(binding["argument_ranks"])) == 1:
            variants.append(
                device_shim._borrowed_result_wrapper(symbol, binding["argument_ranks"][0], binding["borrowed_symbol"])
            )
        if not any(shim_source.count(variant) == 1 for variant in variants):
            raise ReadbackError("descriptor profile compiled shim has a different pointer prototype")
        if (
            not sections.symbol_bytes(shim_path, actual)
            or actual in {"_mlir_ciface_" + value["borrowed_symbol"] for value in result.values()}
            or symbol in result
        ):
            raise ReadbackError("descriptor profile compiled bridge is absent or ambiguous")
        result[symbol] = binding
    for module in (objects, sections, identities, device_shim, linalg_mlir):
        retain(objects.pin(Path(module.__file__).resolve()))
    retain(objects.pin(Path(__file__).resolve()))
    for pin in tuple(pins.values()):
        objects.reopen(pin)
    return result, list(pins.values())


# ---- chain_group_profile -----------------------------------------------------------------------
# Separate per-invocation profiling from complete-chain numerical transport.
#
# Gaps include wrapper bookkeeping. Dropped calls make host/device attribution
# incomplete even when the complete counter window still reconciles.


def separate(text):
    ordinary, profiles, active, current_step = [], {}, None, None
    for line in text.splitlines():
        fields = line.split()
        if fields and fields[0] in ("CHAIN_PROFILE_BEGIN", "CHAIN_PROFILE_END"):
            if len(fields) != 4 or fields[1] != "v1" or any(not n.isdecimal() for n in fields[2:]):
                raise ValueError("malformed chain group profile boundary")
            key = tuple(map(int, fields[2:]))
            if fields[0] == "CHAIN_PROFILE_BEGIN":
                if active is not None or key in profiles or key != current_step:
                    raise ValueError("duplicate, nested or displaced chain group profile")
                active = (key, [])
            else:
                if active is None or active[0] != key:
                    raise ValueError("unmatched chain group profile boundary")
                profile = parse_group_profile("\n".join(active[1]))
                if profile is None:
                    raise ValueError("empty chain group profile")
                profiles[key] = profile
                active = None
        elif active is not None:
            if fields and fields[0].startswith("CHAIN_"):
                raise ValueError("chain transport inside an unfinished group profile")
            active[1].append(line)
        else:
            ordinary.append(line)
            if fields and fields[0] == "CHAIN_STEP" and len(fields) == 6:
                current_step = tuple(map(int, fields[2:4]))
            elif fields and fields[0].startswith("CHAIN_"):
                current_step = None
    if active is not None:
        raise ValueError("truncated chain group profile")
    return "\n".join(ordinary), profiles


def reconcile(profiles, schedule, cycles, *, enabled):
    expected = {(step["program"], step["step"]) for step in schedule}
    if set(profiles) != (expected if enabled else set()):
        raise ValueError("chain group profiling differs from its selected complete step roster")
    result = []
    for step, counter in zip(schedule, cycles, strict=True):
        key = step["program"], step["step"]
        if key not in profiles:
            continue
        profile = profiles[key]
        group_cycles = sum(row["cycles"] for row in profile["groups"])
        gaps = profile["tail_gap"] + sum(row["gap_before"] for row in profile["groups"])
        if group_cycles + gaps != counter["cycles"]:
            raise ValueError("group and gap cycles do not reconcile with the invocation window")
        complete = profile["dropped"] == 0
        result.append(
            {
                "program": counter["program"],
                "step": step["step"],
                **profile,
                "group_cycles": group_cycles,
                "gap_cycles": gaps,
                "host_gap_cycles": gaps if complete else None,
                "complete": complete,
                "scope": "instrumented routed calls and gaps including wrapper bookkeeping; no timing qualification",
            }
        )
    return result


# ---- chain_image_timing ------------------------------------------------------------------------
# Decode a continuous chain diagnostic that carries no numerical verdict.
#
# The generated guest retains scalar counters until all forwards finish. Output
# arrays are neither copied nor printed, and no reference is selected. A separate
# complete-output execution remains necessary for numerical qualification.


def _ticks(value):
    result = int(value)
    if str(result) != value or not 0 <= result < 1 << 64:
        raise ValueError("noncanonical chain timing counter")
    return result


def decode_timing(image, console):
    if image["transport"] != "timing_only_v1" or image.get("group_profile", {}).get("enabled", False):
        raise ValueError("continuous chain timing cannot contain group profile transport")
    if b"OUT_BIN_" in console or b"CHAIN_PROFILE_" in console:
        raise ValueError("timing-only transport cannot carry arrays or group profiles")
    rows = [
        line.split() for line in console.decode("ascii").splitlines() if line.startswith("CHAIN_") or line == "DONE"
    ]
    schedule = image["plan"]["schedule"]
    if len(rows) != len(schedule) + 3 or image["chain_steps"] != len(schedule):
        raise ValueError("incomplete continuous chain timing roster")
    steps = []
    for expected, row in zip(schedule, rows, strict=False):
        if (
            len(row) != 6
            or row[:2] != ["CHAIN_STEP", "v1"]
            or [_ticks(v) for v in row[2:4]] != [expected["program"], expected["step"]]
        ):
            raise ValueError("missing/duplicate/reordered chain timing step")
        steps.append(
            {
                "program": image["plan"]["programs"][expected["program"]]["name"],
                "step": expected["step"],
                "cycles": _ticks(row[4]),
                "memref_rank_mismatches": _ticks(row[5]),
            }
        )
    terminal, timing, done = rows[-3:]
    if terminal != ["CHAIN_END", "v1", str(len(schedule)), "0", "0"] or done != ["DONE"]:
        raise ValueError("timing-only terminal cannot claim numerical comparisons")
    if len(timing) != 5 or timing[:2] != ["CHAIN_TIMING", "v1"]:
        raise ValueError("missing continuous whole-chain counter")
    total, forwards, readback = map(_ticks, timing[2:])
    if forwards != sum(row["cycles"] for row in steps) or forwards > total:
        raise ValueError("whole-chain interval does not enclose its forward intervals")
    return {
        "schema": "merlin.chain_image.readback.v1",
        "transport": "timing_only_v1",
        "complete_chain_steps": len(steps),
        "output_array_count": 0,
        "declared_output_array_count": len(image["output_roster"]),
        "comparisons": [],
        "step_cycles": steps,
        "timing": {
            "units": "selected_counter_ticks",
            "counter": image.get("counter"),
            "whole_chain": total,
            "forward_sum": forwards,
            "session_overhead": total - forwards,
            "readback_transport": readback,
            "whole_chain_scope": (
                "input/state transfers, arena reset, descriptors, forwards and scalar timing bookkeeping"
            ),
            "excluded": "initial boot/validation, array readback/comparison, final reporting and termination",
            "readback_scope": "buffered CHAIN_STEP and CHAIN_END reporting; excludes CHAIN_TIMING and DONE",
            "physical_cycles_verified": False,
        },
        "runtime_status": "pass" if all(not row["memref_rank_mismatches"] for row in steps) else "fail",
        "numerical_status": "not_evaluated_timing_only",
        "execution_origin_verified": False,
        "scientific_qualification": False,
        "scope": "Diagnostic continuous session; no numerical, placement or hardware qualification transferred.",
    }


# ---- chain_image_readback ----------------------------------------------------------------------
# Decode complete-chain transport without granting placement/hardware credit.


def verify_image(record):
    image = json.loads(payload(record))
    if (
        image.get("schema") != "merlin.post_freeze.firesim.chain_image.v1"
        or image.get("execution_scope") != "complete_chain"
    ):
        raise ValueError("not a complete-chain image manifest")
    verify_completed_recipe(
        reopen(image["recipe"]), executable=reopen(image["boot_elf"]), expected_recipe_sha256=image["recipe"]["sha256"]
    )
    for field in ("selection", "workload_contract", "producer"):
        reopen(image[field])
    selection = json.loads(payload(image["selection"]))
    declared_map = selection["memory_map"]
    binding = MemoryMapBinding(reopen(declared_map), declared_map["sha256"], selection["execution_identity"])
    memory = admit_execution_memory(
        reopen(image["boot_elf"]),
        binding,
        (MemoryReservation("activation_arena", **selection["layout"]["arena"], alignment=64),),
    )
    if memory != image["memory_admission"]:
        raise ValueError("complete-chain execution memory admission changed")
    invocation_record.verify(reopen(image["boot"]["invocation"]))
    for record in (*image["plan"]["source_pins"], *image["reference"]["source_pins"], *image["producer_sources"]):
        reopen(record)
    for program in image["namespace"]:
        for record in (*program["objects"], program["mapping"]):
            reopen(record)
        for record in program["invocations"]:
            invocation_record.verify(reopen(record))
    for record in image.get("group_profile", {}).get("support", []):
        verify(record)
    verify_counter_support(image.get("counter_support"))
    reopen(image["plan"]["input_blob"])
    reopen(image["reference"]["blob"])
    expected_steps = [{"program": p["index"], "step": i} for p in image["plan"]["programs"] for i in range(p["steps"])]
    if [{k: row[k] for k in ("program", "step")} for row in image["plan"]["schedule"]] != expected_steps:
        raise ValueError("chain manifest does not schedule its complete declared program roster")
    roster = [
        {"stage": p["name"], "step": i, "index": n, "shape": shape, "dtype": dtype}
        for p in image["plan"]["programs"]
        for i in range(p["steps"])
        for n, (shape, dtype) in enumerate(p["outputs"])
    ]
    if roster != image["output_roster"] or len(expected_steps) != image["chain_steps"]:
        raise ValueError("chain manifest output roster differs from its actual declared schedule")
    return image


def _integer(token):
    value = int(token)
    if str(value) != token or not 0 <= value < 1 << 64:
        raise ValueError("noncanonical chain counter/extent")
    return value


def _hex(token):
    if len(token) != 16 or any(c not in "0123456789abcdef" for c in token):
        raise ValueError("noncanonical chain bit-pattern/digest")
    return int(token, 16)


def _double(token):
    value = struct.unpack("<d", struct.pack("<Q", _hex(token)))[0]
    if math.isnan(value) or value < 0:
        raise ValueError("invalid nonnegative chain error summary")
    return value if math.isfinite(value) else None


def _fnv(data):
    value = 0xCBF29CE484222325
    for byte in data:
        value = ((value ^ byte) * 0x100000001B3) & ((1 << 64) - 1)
    return value


def decode(image, console):
    """Require every scheduled counter/array exactly once in temporal order.

    Compact acceptance comes from the pinned guest's all-element comparison,
    never digest/sample equality. This pure decoder supplies no execution origin.
    The caller must bind the actually consumed image and native placement gates.
    """
    if image["transport"] == "timing_only_v1":
        return decode_timing(image, console)
    compact = image["transport"] == "all_element_comparison_v1"
    if not compact and image["transport"] != "full_arrays_v1":
        raise ValueError("unknown chain readback transport")
    if compact:
        if b"OUT_BIN_" in console:
            raise ValueError("mixed complete-chain transports")
        text, frames, outputs = console, {}, {}
    else:
        outputs, _, frames = parse_binary_console_details(console)
        text = binary_console_diagnostics(console)
    ordinary, profiles = separate(text.decode("ascii"))
    rows = [line.split() for line in ordinary.splitlines() if line.startswith("CHAIN_") or line == "DONE"]
    at, comparisons, cycles, mismatches = 0, [], [], 0
    reference = reopen(image["reference"]["blob"])
    with reference.open("rb") as expected:
        for ordinal, step in enumerate(image["plan"]["schedule"]):
            program, index = image["plan"]["programs"][step["program"]], step["step"]
            if at >= len(rows):
                raise ValueError("truncated complete-chain step transport")
            row = rows[at]
            at += 1
            if (
                row[:2] != ["CHAIN_STEP", "v1"]
                or len(row) != 6
                or list(map(_integer, row[2:4])) != [step["program"], index]
            ):
                raise ValueError("missing/duplicate/reordered chain step counter")
            cycles.append(
                {
                    "program": program["name"],
                    "step": index,
                    "cycles": _integer(row[4]),
                    "memref_rank_mismatches": _integer(row[5]),
                }
            )
            for output, (shape, dtype) in enumerate(program["outputs"]):
                elements = math.prod(shape)
                binding = {"stage": program["name"], "step": index, "index": output, "dtype": dtype, "shape": shape}
                if compact:
                    if at >= len(rows):
                        raise ValueError("truncated complete-chain array transport")
                    row = rows[at]
                    at += 1
                    if (
                        len(row) < 13
                        or row[:2] != ["CHAIN_ARRAY", "v1"]
                        or list(map(_integer, row[2:6])) != [step["program"], index, output, elements]
                    ):
                        raise ValueError("missing/duplicate/reordered compact array")
                    failed, finite, samples = _integer(row[6]), _integer(row[7]), _integer(row[12])
                    if (
                        failed > elements
                        or finite not in (0, 1)
                        or (not finite and not failed)
                        or samples != min(failed, 4)
                        or len(row) != 13 + 3 * samples
                    ):
                        raise ValueError("inconsistent complete-array comparison summary")
                    locations = list(map(_integer, row[13::3]))
                    if len(set(locations)) != len(locations) or any(i >= elements for i in locations):
                        raise ValueError("invalid compact mismatch sample positions")
                    sample_values = [(_hex(row[i]), _hex(row[i + 1])) for i in range(14, len(row), 3)]
                    if any(max(pair) >= 1 << (8 * DT_BYTES[dtype]) for pair in sample_values):
                        raise ValueError("compact sample exceeds its declared storage width")
                    expected.seek(image["reference"]["offsets"][ordinal][output])
                    payload = expected.read(elements * DT_BYTES[dtype])
                    if len(payload) != elements * DT_BYTES[dtype] or _hex(row[11]) != _fnv(payload):
                        raise ValueError("guest compared a different selected reference array")
                    maximum, square = _double(row[8]), _double(row[9])
                    comparisons.append(
                        {
                            **binding,
                            "elements": elements,
                            "mismatched": failed,
                            "finite": bool(finite),
                            "max_abs_error": maximum if finite else None,
                            "rms_error": math.sqrt(square / elements) if finite and square is not None else None,
                            "actual_fnv1a64": row[10],
                            "reference_fnv1a64": row[11],
                            "samples": [
                                {"index": i, "actual_bits": a, "reference_bits": b}
                                for i, (a, b) in zip(locations, sample_values, strict=True)
                            ],
                            "pass": failed == 0 and finite == 1,
                        }
                    )
                    _hex(row[10])
                    mismatches += failed
                else:
                    name = f"p{step['program']}_s{index}_out{output}"
                    if name not in frames:
                        raise ValueError("complete-chain raw output array is missing")
                    frame = frames[name]
                    columns = shape[-1] if shape else 1
                    if (frame.rows, frame.cols, frame.word_bytes, frame.signed) != (
                        elements // columns,
                        columns,
                        DT_BYTES[dtype],
                        dtype in {"i8", "i16", "i32", "i64"},
                    ):
                        raise ValueError("chain raw output has another storage ABI")
                    comparisons.append({**binding, "elements": elements, "frame": name, "pass": None})
    if (
        len(rows) != at + 2
        or rows[at] != ["CHAIN_END", "v1", str(len(cycles)), str(len(comparisons)), str(mismatches)]
        or rows[-1] != ["DONE"]
    ):
        raise ValueError("complete-chain terminal counts are absent or inconsistent")
    if not compact and set(outputs) != {r["frame"] for r in comparisons}:
        raise ValueError("full readback added or omitted an array")
    group_profiles = reconcile(
        profiles,
        image["plan"]["schedule"],
        cycles,
        enabled=image.get("group_profile", {}).get("enabled", False),
    )
    return {
        "schema": "merlin.chain_image.readback.v1",
        "transport": image["transport"],
        "complete_chain_steps": len(cycles),
        "output_array_count": len(comparisons),
        "comparisons": comparisons,
        "step_cycles": cycles,
        **({"group_profiles": group_profiles} if image.get("group_profile", {}).get("enabled", False) else {}),
        "runtime_status": "pass" if all(row["memref_rank_mismatches"] == 0 for row in cycles) else "fail",
        "numerical_status": ("pass" if not mismatches else "fail") if compact else "pending_all_output_checker",
        "execution_origin_verified": False,
        "scientific_qualification": False,
        "scope": "Pinned guest transport only; actual consumed-image/hardware/source-placement gates remain separate.",
    }
