"""Recognize the current generated private NHWC halo transport structurally.

This recognizes one existing byte emitter, not arbitrary pointer arithmetic.
The caller still owns source-buffer accessibility, target effects, completion,
stock translation/optimization custody and the final compiled object.
"""

from dataclasses import dataclass
from hashlib import sha256
from math import prod

from xdsl.dialects import llvm
from xdsl.dialects.builtin import ModuleOp, i8

from merlin.compile.scheduling.window_transfer import Window2D
from merlin.xdsl_dialects._common import text

from .convolution_packing import emit_nhwc_window_panel
from .host_builder import PTR, FnBuilder


def _constant(op):
    return op.name == "llvm.mlir.constant"


def _key(op):
    if set(op.attributes) & set(op.properties):
        raise ValueError("ambiguous generated byte operation attributes")
    return (op.name, tuple(sorted((name, str(value)) for name, value in
                                 {**op.attributes, **op.properties}.items())),
            tuple(str(value.type) for value in op.results))


def _same(before, after, mapping):
    # The ordinary LLVM parser moves inherent loop annotations from attributes
    # into properties. Compare their complete named values after that transport.
    if (before.regions or after.regions or _key(before) != _key(after)
            or mapping.get(before.parent) is not after.parent
            or tuple(mapping.get(v, v) for v in before.operands) != tuple(after.operands)
            or tuple(mapping.get(b, b) for b in before.successors) != tuple(after.successors)):
        return False
    mapping.update(zip(before.results, after.results, strict=True))
    return True


def _digest(module):
    return sha256(text(module, generic=True).encode()).hexdigest()


@dataclass(frozen=True)
class GeneratedByteTransport:
    """A live recognition result; its serialized record supplies no authority."""

    module: ModuleOp
    entry_symbol: str
    source_argument: int
    window: Window2D
    maximum_private_bytes: int
    source_sha256: str
    private_bytes: int
    matched_operations: int

    def revalidate(self):
        if _digest(self.module) != self.source_sha256:
            raise ValueError("recognized byte-transport source changed")
        current = recognize_nhwc_halo_transport(
            self.module, entry_symbol=self.entry_symbol, source_argument=self.source_argument,
            window=self.window, maximum_private_bytes=self.maximum_private_bytes,
        )
        if current.record() != self.record():
            raise ValueError("recognized byte-transport binding changed")
        return current

    def record(self):
        return dict(
            schema="merlin.generated_nhwc_halo_transport.v1",
            source_sha256=self.source_sha256, entry_symbol=self.entry_symbol,
            source_argument=self.source_argument, private_bytes=self.private_bytes,
            matched_operations=self.matched_operations,
            initialization="complete original byte rows and integer-zero halo before every private consumer",
            scope="generated host byte movement only; target borrowing/completion and compiled custody remain caller-owned",
        )


def recognize_nhwc_halo_transport(
    module, *, entry_symbol, source_argument, window, maximum_private_bytes
):
    """Reproduce and match exactly one fixed private complete halo preparation.

    The original complete 1x1 row-span emitter supplies byte bounds and full
    initialization. Every generated CFG edge, operand, intrinsic and count must
    match the current source. Other allocation, host stores and calls refuse.
    Opaque target instructions outside this prefix are not qualified here.
    """
    if type(module) is not ModuleOp or type(window) is not Window2D:
        raise ValueError("current typed module and original window required")
    window.__post_init__()
    if window.kernel != (1, 1) or window.stride != (1, 1) or not any(window.padding):
        raise ValueError("complete unit-window halo transport required")
    capacity = window.input_shape[0] * prod(window.output_spatial) * window.input_shape[-1]
    if type(maximum_private_bytes) is not int or not 0 < capacity <= maximum_private_bytes < 1 << 63:
        raise ValueError("private halo exceeds the original bounded capacity")
    functions = [op for op in module.body.block.ops
                 if isinstance(op, llvm.FuncOp) and op.sym_name.data == entry_symbol]
    if len(functions) != 1:
        raise ValueError("one actual byte-transport entry required")
    function = functions[0]
    blocks = tuple(function.body.blocks)
    if (not blocks or type(source_argument) is not int
            or not 0 <= source_argument < len(blocks[0].args)
            or any(arg.type != PTR for arg in blocks[0].args)
            or function.function_type.output != llvm.LLVMVoidType()):
        raise ValueError("original pointer-only void entry and source position required")
    allocations = [op for op in function.walk() if op.name == "llvm.alloca"]
    if len(allocations) != 1 or allocations[0].parent != blocks[0]:
        raise ValueError("exactly one entry-private byte allocation required")
    allocation = allocations[0]

    expected = FnBuilder([arg.type for arg in blocks[0].args])
    private = expected.add(llvm.AllocaOp(expected.const(capacity), i8, alignment=16)).res
    receipt = emit_nhwc_window_panel(
        expected, window, expected.entry.args[source_argument], private, expected.const(0),
        window.input_shape[0] * prod(window.output_spatial),
        source_destination_disjoint=True, maximum_panel_bytes=maximum_private_bytes,
    )
    if receipt.get("transport") != "complete_unit_window_row_spans":
        raise ValueError("current byte emitter did not select complete bounded row spans")
    expected.finish()
    template = tuple(expected.region.blocks)
    if len(blocks) < len(template):
        raise ValueError("generated halo CFG is absent")
    mapping = dict(zip(template, blocks, strict=False))
    for before, after in zip(template, blocks):
        if tuple(arg.type for arg in before.args) != tuple(arg.type for arg in after.args):
            raise ValueError("generated halo CFG argument types changed")
        mapping.update(zip(before.args, after.args, strict=True))

    constants = {}
    for op in blocks[0].ops:
        if _constant(op):
            constants.setdefault(_key(op), []).append(op)
    matched = set()
    for op in expected.entry.ops:
        if _constant(op):
            options = constants.get(_key(op), ())
            if len(options) != 1 or not _same(op, options[0], mapping):
                raise ValueError("generated halo constant changed or is ambiguous")
            matched.add(options[0])

    actual_entry = [op for op in blocks[0].ops if not _constant(op)]
    start = actual_entry.index(allocation)
    entry_tail = actual_entry[start:]
    expected_entry = [op for op in expected.entry.ops if not _constant(op)]
    if len(entry_tail) != len(expected_entry):
        raise ValueError("unexpected operation inside generated halo entry")
    for before, after in zip(expected_entry, entry_tail, strict=True):
        if not _same(before, after, mapping):
            raise ValueError("generated halo entry allocation or edge changed")
        matched.add(after)

    exit_block = expected.blk
    for before in template[1:]:
        if before is exit_block:
            if [op.name for op in before.ops] != ["llvm.return"]:
                raise ValueError("unexpected generated halo exit")
            continue
        after = mapping[before]
        if len(tuple(before.ops)) != len(tuple(after.ops)):
            raise ValueError("generated halo block changed")
        for left, right in zip(before.ops, after.ops, strict=True):
            if not _same(left, right, mapping):
                raise ValueError("generated halo byte operation or bound changed")
            matched.add(right)

    interior = {mapping[block] for block in template[1:] if block is not exit_block}
    for block in blocks:
        for op in block.ops:
            if op not in matched and any(successor in interior for successor in op.successors):
                raise ValueError("consumer reenters private halo preparation")
            if op not in matched and (
                op.name in {"llvm.alloca", "llvm.store", "llvm.call", "llvm.call_intrinsic",
                            "llvm.invoke", "llvm.callbr"}
                or op.name.startswith("llvm.intr.")
            ):
                raise ValueError("unrecognized host allocation, store or call outside byte transport")
    # No private address is published by the recognized fragment. Outside it,
    # only address derivation may reach opaque target instructions. Those
    # instructions require the original target owner's separate noescape law.
    pending = [allocation.res]
    seen = set()
    while pending:
        value = pending.pop()
        if value in seen:
            continue
        seen.add(value)
        for use in value.uses:
            user = use.operation
            if user in matched:
                continue
            if user.parent in interior or user.parent is blocks[0]:
                raise ValueError("private consumer precedes complete initialization")
            if user.name not in {"llvm.getelementptr", "llvm.ptrtoint", "llvm.inline_asm"}:
                raise ValueError("private halo address has an unknown escape")
            if user.name != "llvm.inline_asm":
                pending.extend(user.results)
    module.verify()
    return GeneratedByteTransport(module, entry_symbol, source_argument, window,
                                  maximum_private_bytes, _digest(module), capacity, len(matched))
