"""Add a recurrent reset hook to retained Merlin profiling support only.

Original graph, device and weight objects remain inputs. An explicit profiling
selection may rebuild this generated host wrapper from its pinned source and
original ABI flags; its new source/object and compiler invocation are recorded.
"""

from pathlib import Path

from merlin.common import invocation_record

from . import chain_image_layout as layout
from . import chain_image_objects as objects

MARKER = "/* Generated by merlin.runtime.whole_model_readback. Do not edit. */"
RESET = """
void merlin_group_profile_reset(void) {
  merlin_group_count = 0;
  merlin_group_dropped = 0;
}
"""


def prepare(program, directory, *, nm, timeout):
    original = program["by_name"].get("group_profile.o")
    if original is None:
        raise ValueError("selected program has no retained group profiling object")
    table = objects.symbols(nm, objects.reopen(original), timeout=timeout)
    if table.get("merlin_group_profile_dump") != "T":
        raise ValueError("retained profiling object lacks the generated dump hook")
    if table.get("merlin_group_profile_reset") == "T":
        return program, None
    command = layout.command(program, "group_profile.o")
    sources = [row for row in command["inputs"] if row["path"].endswith(".c")]
    if len(sources) != 1:
        raise ValueError("retained profiling compilation lacks one pinned C source")
    source = objects.payload(sources[0]).decode("utf-8")
    if (
        not source.startswith(MARKER + "\n")
        or source.count("static uint64_t merlin_group_count, merlin_group_dropped;") != 1
        or source.count("void merlin_group_profile_dump(uint64_t forward_start, uint64_t forward_end) {") != 1
        or "merlin_group_profile_reset" in source
    ):
        raise ValueError("unsupported retained profiling source ABI")
    objects.reopen(command["executable"])
    directory.mkdir()
    generated, product = directory / "group_profile.c", directory / "group_profile.o"
    generated.write_text(source + RESET)
    inputs = tuple(objects.reopen(row) for row in command["inputs"])
    invocation_record.run(
        layout.compile_argv(command, generated, product),
        directory=directory,
        stage="chain_image_profile_reset",
        inputs=(*inputs, objects.reopen(original), generated),
        outputs=(product,),
        dependencies=(Path(__file__), Path(layout.__file__)),
        capture_output=True, text=True, check=True, timeout=timeout,
    )
    updated = objects.pin(product)
    result = {
        **program,
        "objects": [updated if row == original else row for row in program["objects"]],
        "by_name": {**program["by_name"], "group_profile.o": updated},
    }
    record = {
        "original_object": original, "original_source": sources[0],
        "source": objects.pin(generated), "object": updated,
        "invocations": [objects.pin(p) for p in directory.glob("invocations/*/invocation.json")],
        "scope": "host profiling reset only; graph/device/weight objects unchanged",
    }
    return result, record


def verify(record):
    if record is not None:
        for key in ("original_object", "original_source", "source", "object"):
            objects.reopen(record[key])
        for row in record["invocations"]:
            invocation_record.verify(objects.reopen(row))
