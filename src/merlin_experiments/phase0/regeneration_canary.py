"""Replay a sealed corpus slice through today's grouping, group writer and admission.

The sealed Phase 0 corpus was generated by the code of its day. When admission or generation later
becomes stricter, nothing notices until someone regenerates the corpus -- which happened weeks
after the fact, when a regeneration refused every whole-model capsule whose residual-add group the
sealed corpus admitted ("required composition is not admitted; unresolved SW constraints:
scale_granularity"). A canary that replays a few sealed cases on every test run moves that discovery
to the commit that introduces the change.

The input is a fixture written by ``build_tools/scripts/extract_regeneration_canary.py``: one sealed
model capsule's interface program, the sealed corpus's qualifying groups of it (their written
programs and the admission status sealed with them), the evidence views admission reads and the
recipe's datapath. Nothing here names a target; the fixture does.

Two replays, each compared with what the sealed corpus contains:

* **admission** -- each sealed group's own written program, screened by today's admission;
* **generation** -- the model regrouped by today's grouping, each group rewritten by today's writer and
  screened, matched to the sealed group of the same form name.

A finding is a sealed-admitted group that today's code refuses, leaves unknown, or no longer forms.
The fixture may list ``accepted_drift`` rows (group, replay, reason) a reviewer has accepted; an
accepted row that no longer reproduces is itself reported, so the list cannot outlive its cause.

The grouping oracle resolves the target's contract and RTL facts by name, so run this in a process
whose ``MERLIN_TARGET_CONTRACT`` and ``MERLIN_RTL_FACTS`` select the fixture's copies; ``main`` does.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path
from types import SimpleNamespace

import yaml

SCHEMA = "merlin.phase0_regeneration_canary.v1"
REPORT_SCHEMA = "merlin.phase0_regeneration_canary_report.v1"
_MODULE = "merlin_experiments.phase0.regeneration_canary"


def _sidecar(fixture: Path, row: dict) -> bytes:
    raw = gzip.decompress((fixture / row["file"]).read_bytes())
    if hashlib.sha256(raw).hexdigest() != row["sha256"]:
        raise ValueError(f"canary fixture member changed: {row['file']}")
    return raw


def load(fixture: Path) -> dict:
    document = json.loads((Path(fixture) / "canary.json").read_text(encoding="utf-8"))
    if document.get("schema") != SCHEMA:
        raise ValueError(f"unsupported regeneration canary fixture: {fixture}")
    return document


def _form(name: str) -> str:
    """A group's form name without its category or its numerical-identity suffix."""
    base = Path(str(name)).name
    stem, _, suffix = base.rpartition("_q")
    return stem if stem and len(suffix) == 12 and all(c in "0123456789abcdef" for c in suffix) else base


def _screen(capsule: dict, program: str, directory: Path, evidence) -> dict:
    from .program_admission import screen_written

    directory.mkdir(parents=True, exist_ok=True)
    (directory / str(capsule.get("interface_mlir") or "capsule.interface.mlir")).write_text(program, encoding="utf-8")
    (directory / "capsule.yaml").write_text(yaml.safe_dump(capsule, sort_keys=False), encoding="utf-8")
    screen = screen_written(capsule, directory, target=evidence.target, evidence=evidence) or {}
    return {
        "status": screen.get("status", "unscreened"),
        "reason": screen.get("reason", ""),
        "program_sha256": hashlib.sha256(program.encode()).hexdigest(),
    }


def replay(fixture: Path, scratch: Path) -> dict:
    """Both replays of one fixture; ``findings`` lists every unaccepted refusal."""
    from merlin.common import mlir_query as mq
    from merlin.targetgen import corpus_spec as CS
    from merlin.targetgen import group_capsule_entries as G

    fixture = Path(fixture)
    document = load(fixture)
    views = json.loads(_sidecar(fixture, document["views"]))
    facts = json.loads(_sidecar(fixture, document["loaded_facts"]))
    target = document["target"]
    evidence = SimpleNamespace(
        target=target,
        software_spec=views["software_spec"],
        contract=views["contract"],
        host_capabilities=views["host_capabilities"],
        readout_facets=tuple(views["readout_facets"]),
        isa_taxonomy=views["isa_taxonomy"],
        loaded_facts=facts,
        whole_program_admission=None,
    )
    binding = CS.derive_binding(
        SimpleNamespace(target=target, sim_via=None),
        document["datapath"],
        contract=views["contract"],
        facts=facts,
        taxonomy=views["isa_taxonomy"],
    )
    sealed = {_form(row["capsule"]): row for row in document["groups"]}
    rows: list[dict] = []
    for form, row in sorted(sealed.items()):
        observed = _screen(row["capsule_record"], row["program"], scratch / "sealed" / form, evidence)
        rows.append({"replay": "admission", "group": form, "sealed": row["sealed_status"], **observed})

    interface = scratch / "model.interface.mlir"
    interface.write_bytes(_sidecar(fixture, document["interface"]))
    weight_args = None
    if document.get("weights_manifest"):
        from merlin.xdsl_dialects.lowering import stream_plan

        weight_args = stream_plan.weight_args_of(document["weights_manifest"])
    stated = G.entries(
        target,
        mq.parse(str(interface)),
        weight_args=weight_args,
        model=document["model"],
        with_raw=False,
        numerical_variants=True,
    )
    regenerated: dict[str, list[dict]] = {}
    for entry_row in stated["entries"]:
        entry = {
            **dict(entry_row["entry"]),
            "label": "public",
            "numerical_semantics": document.get("numerical_semantics") or {},
            "source_reference": f"isolated verification of a device group of {document['model']}",
        }
        capsule, program = G.interface_capsule(entry, binding)
        form = _form(entry["name"])
        observed = _screen(capsule, program, scratch / "regenerated" / entry["name"], evidence)
        regenerated.setdefault(form, []).append(observed)
    for form, row in sorted(sealed.items()):
        found = regenerated.get(form)
        if not found:
            rows.append(
                {
                    "replay": "generation",
                    "group": form,
                    "sealed": row["sealed_status"],
                    "status": "absent",
                    "reason": "today's grouping no longer forms this sealed group",
                }
            )
            continue
        worst = next((o for o in found if o["status"] != "admitted"), found[0])
        rows.append(
            {
                "replay": "generation",
                "group": form,
                "sealed": row["sealed_status"],
                **worst,
                "program_changed": worst["program_sha256"] != row.get("sealed_program_sha256"),
            }
        )

    accepted = {(r["group"], r["replay"]): r for r in document.get("accepted_drift") or []}
    findings, reproduced = [], set()
    for row in rows:
        if row["sealed"] != "admitted" or row["status"] == "admitted":
            continue
        key = (row["group"], row["replay"])
        if key in accepted:
            reproduced.add(key)
            continue
        findings.append(row)
    stale = [accepted[key] for key in accepted if key not in reproduced]
    return {
        "schema": REPORT_SCHEMA,
        "fixture": str(fixture),
        "model": document["model"],
        "target": target,
        "rows": rows,
        "unstated": stated.get("unstated") or {},
        "findings": findings,
        "accepted": [accepted[key] for key in sorted(reproduced)],
        "stale_accepted_drift": stale,
    }


def describe(report: dict) -> str:
    lines = []
    for row in report["findings"]:
        lines.append(
            f"  {row['replay']}: sealed-admitted group {row['group']} of {report['model']} is now "
            f"{row['status']}: {row['reason']}"
        )
    for row in report["stale_accepted_drift"]:
        lines.append(f"  accepted drift no longer reproduces (remove it from the fixture): {row}")
    for name, count in sorted(report["unstated"].items()):
        lines.append(f"  today's grouping cannot state {count} group(s): {name}")
    return "\n".join(lines)


def run_isolated(fixture: Path, *, python: str | None = None, timeout: float = 600) -> dict:
    """Replay in a fresh process whose target contract and RTL facts are the fixture's copies."""
    fixture = Path(fixture).resolve()
    document = load(fixture)
    with tempfile.TemporaryDirectory(prefix="regeneration-canary-") as scratch:
        root = Path(scratch)
        facts = root / "facts.json"
        facts.write_bytes(_sidecar(fixture, document["rtl_facts"]))
        contract = root / "target_contract.json"
        contract.write_bytes(_sidecar(fixture, document["capability_contract"]))
        env = {
            **os.environ,
            "MERLIN_RTL_FACTS": str(facts),
            "MERLIN_TARGET_CONTRACT": str(contract),
            "PYTHONPATH": os.pathsep.join(p for p in sys.path if p),
            "PYTHONDONTWRITEBYTECODE": "1",
        }
        command = [python or sys.executable, "-m", _MODULE, "--in-process", str(fixture), "--scratch", str(root)]
        done = subprocess.run(command, env=env, capture_output=True, text=True, timeout=timeout, check=False)
        if done.returncode != 0:
            raise RuntimeError(f"canary replay crashed ({done.returncode}):\n{done.stderr[-4000:]}")
        return json.loads(done.stdout)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("fixture", type=Path)
    parser.add_argument("--in-process", action="store_true", help="replay here (the environment is already set)")
    parser.add_argument("--scratch", type=Path, help="where replayed programs are written (--in-process)")
    args = parser.parse_args(argv)
    if args.in_process:
        # The isolated child reports; only a crash is a non-zero exit, so the parent can tell them apart.
        args.scratch.mkdir(parents=True, exist_ok=True)
        print(json.dumps(replay(args.fixture, args.scratch), sort_keys=True))
        return 0
    report = run_isolated(args.fixture)
    print(json.dumps(report, indent=2, sort_keys=True))
    return 1 if report["findings"] or report["stale_accepted_drift"] else 0


if __name__ == "__main__":
    sys.exit(main())
