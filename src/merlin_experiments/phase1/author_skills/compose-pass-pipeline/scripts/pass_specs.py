"""List every declared pass contract (``PassSpec``) in a compiler source tree, and check an order.

The library states pass ordering as data: each ``merlin.transforms.pipeline_state.PassSpec`` names its
stage, the analyses it ``requires`` and ``produces``, what it ``invalidates`` and whether it mutates IR,
and ``validate_pass_order`` rejects an order whose prerequisites are missing or stale. This script reads
those declarations structurally (``ast``; nothing is imported from the scanned tree) so you can see the
pipeline an entry point builds before you insert, move or replace a pass.

    python pass_specs.py                         # every declaration under the importable merlin package
    python pass_specs.py --root path/to/merlin   # your own (edited) tree
    python pass_specs.py --grep schedule_pipeline --json
    python pass_specs.py --check compile_schedule --order semantic_admission,storage,completion,emission,final_program

``--check`` builds the constant declarations of the one function whose ``module:function`` contains the
given text, puts them in ``--order`` (default: source order) and asks the library's own
``validate_pass_order``; it reports the first prefix that fails and why. Fields computed at run time
are shown as ``<expr>`` and such a function cannot be checked here: run its real entry point.
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path

REFERENCE_HEADER = """# Declared pass contracts (generated)

Generated by `python scripts/pass_specs.py --reference` from the library as shipped; a test fails
when it is stale. Rows are in source order (an inserted pass appears where it is declared, with
the `rewire` that adds its product to the consumer). `<expr>` is computed at run time. Your
workspace may hold a subset or an edited copy: rerun the script on your own tree for line numbers.

"""
FIELDS = ("name", "stage", "requires", "produces", "invalidates", "mutates_ir", "ir_level")
DEFAULTS = {"requires": (), "produces": (), "invalidates": (), "mutates_ir": True, "ir_level": "structured"}


class Dynamic(str):
    """A field whose value is computed at run time; kept as its source expression."""


def _value(node):
    try:
        value = ast.literal_eval(node)
    except (ValueError, TypeError, SyntaxError, MemoryError, RecursionError):
        return Dynamic(ast.unparse(node))
    return tuple(value) if isinstance(value, list) else value


def _is_call_to(node, name):
    func = node.func
    return (isinstance(func, ast.Name) and func.id == name) or (isinstance(func, ast.Attribute) and func.attr == name)


class _Collector(ast.NodeVisitor):
    def __init__(self, module):
        self.module, self.scope, self.rows = module, [], []

    def _scoped(self, node):
        self.scope.append(node.name)
        self.generic_visit(node)
        self.scope.pop()

    visit_FunctionDef = visit_AsyncFunctionDef = visit_ClassDef = _scoped

    def visit_Call(self, node):
        where = {"module": self.module, "function": ".".join(self.scope) or "<module>", "line": node.lineno}
        if _is_call_to(node, "PassSpec"):
            row = {**where, "kind": "declare", **DEFAULTS}
            for field, arg in zip(FIELDS, node.args):
                row[field] = _value(arg)
            for keyword in node.keywords:
                row[keyword.arg if keyword.arg in FIELDS else "**"] = _value(keyword.value)
            row.setdefault("name", Dynamic("?"))
            row.setdefault("stage", Dynamic("?"))
            self.rows.append(row)
        elif (_is_call_to(node, "declare") and len(node.args) == 2 and isinstance(node.args[0], ast.Constant)
              and isinstance(node.args[0].value, str) and any(k.arg == "entry" for k in node.keywords)):
            # merlin.common.compile_trace.declare(pipeline, stages, entry=..., summary=...): the ordered stages
            # an entry point records (lower_model, lower_module, ...). Starred parts stay <expr>.
            stages = node.args[1].elts if isinstance(node.args[1], (ast.Tuple, ast.List)) else [node.args[1]]
            keywords = {k.arg: _value(k.value) for k in node.keywords}
            self.rows.append({**where, "kind": "stages", "pipeline": node.args[0].value,
                              "entry": keywords.get("entry"), "summary": keywords.get("summary"),
                              "stages": tuple(_value(stage) for stage in stages)})
        elif _is_call_to(node, "replace") and node.args and any(k.arg in FIELDS for k in node.keywords):
            # dataclasses.replace(spec, requires=...): the library's way to rewire a consumer when a pass is
            # inserted in front of it (see compile_schedule). Listed so an insertion point is visible.
            changes = {k.arg: _value(k.value) for k in node.keywords if k.arg in FIELDS}
            self.rows.append({**where, "kind": "rewire", "target": ast.unparse(node.args[0]), **changes})
        self.generic_visit(node)


def scan(root):
    """Rows for every ``PassSpec(...)`` and ``replace(spec, <field>=...)`` under ``root`` (a package dir)."""
    root = Path(root).resolve()
    rows = []
    for path in sorted(root.rglob("*.py")):
        if "__pycache__" in path.parts:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if "PassSpec" not in text and "entry=" not in text:
            continue
        try:
            tree = ast.parse(text, filename=str(path))
        except SyntaxError:
            continue
        relative = path.relative_to(root.parent).with_suffix("")
        module = ".".join(relative.parts[:-1] if relative.name == "__init__" else relative.parts)
        collector = _Collector(module)
        collector.visit(tree)
        if any(row["kind"] in ("declare", "stages") for row in collector.rows):
            rows.extend(row for row in collector.rows if row["kind"] != "rewire" or "PassSpec" in text)
    return rows


def stage_pipelines(rows):
    """Declared stage orders of entry points: ``[{pipeline, entry, summary, stages, module, line}]``."""
    return [row for row in rows if row["kind"] == "stages"]


def pipelines(rows):
    """``{"module:function": [rows in source order]}``, only functions that declare a pass."""
    grouped = {}
    for row in rows:
        if row["kind"] == "stages":
            continue
        grouped.setdefault(f"{row['module']}:{row['function']}", []).append(row)
    return {key: value for key, value in grouped.items() if any(row["kind"] == "declare" for row in value)}


def _text(value):
    if isinstance(value, Dynamic):
        return f"<{value}>"
    if isinstance(value, tuple):
        return ", ".join(map(str, value)) or "-"
    return str(value)


def markdown(rows, *, lines=True):
    out = []
    staged = stage_pipelines(rows)
    if staged:
        out += ["## Entry-point stage orders (`compile_trace.declare`)", ""]
        for row in staged:
            where = f"{row['module']}" + (f":{row['line']}" if lines else "")
            out.append(f"- `{row['pipeline']}` via `{_text(row['entry'])}` ({where}): "
                       + " -> ".join(_text(stage) for stage in row["stages"]))
        out += ["", "## Pass contracts (`PassSpec`) by declaring function", ""]
    for key, items in pipelines(rows).items():
        out += [f"### `{key}`", "", "| stage | pass | requires | produces | invalidates | mutates_ir | ir_level |"
                + (" line |" if lines else ""), "|---|---|---|---|---|---|---|" + ("---|" if lines else "")]
        for row in items:
            tail = f" {row['line']} |" if lines else ""
            if row["kind"] == "declare":
                out.append("| " + " | ".join(_text(row[f]) for f in ("stage", "name", "requires", "produces",
                                                                     "invalidates", "mutates_ir", "ir_level"))
                           + " |" + tail)
            else:
                changed = "; ".join(f"{f}={_text(row[f])}" for f in FIELDS if f in row)
                out.append(f"| | rewire `{row['target']}` | {changed} | | | | |" + tail)
        out.append("")
    return "\n".join(out)


def _jsonable(rows):
    return [{k: ({"dynamic": str(v)} if isinstance(v, Dynamic) else v) for k, v in row.items()} for row in rows]


def check(rows, function, order=None):
    """Validate one function's constant declarations in ``order`` with the library's own checker."""
    from merlin.transforms.pipeline_state import PassSpec, validate_pass_order

    matches = [key for key in pipelines(rows) if function in key]
    if len(matches) != 1:
        return {"status": "ambiguous" if matches else "not_found", "matches": matches}
    declared = [row for row in pipelines(rows)[matches[0]] if row["kind"] == "declare"]
    names = list(order) if order else [str(row["name"]) for row in declared]
    selected = [row for row in declared if row["name"] in names]
    unknown = [name for name in names if name not in {row["name"] for row in selected}]
    if unknown:
        return {"status": "unknown_pass", "function": matches[0], "passes": unknown,
                "declared": [str(row["name"]) for row in declared]}
    dynamic = [row["name"] for row in selected if "**" in row or any(isinstance(row[f], Dynamic) for f in FIELDS)]
    twice = sorted({row["name"] for row in selected if [r["name"] for r in selected].count(row["name"]) > 1})
    if dynamic or twice:
        return {"status": "dynamic", "function": matches[0], "passes": [str(n) for n in dynamic + twice],
                "reason": "computed fields or alternative declarations of one name; run the real entry point"}
    by_name = {row["name"]: PassSpec(**{f: row[f] for f in FIELDS}) for row in selected}
    for end in range(1, len(names) + 1):
        try:
            validate_pass_order(tuple(by_name[name] for name in names[:end]))
        except ValueError as error:
            return {"status": "invalid", "function": matches[0], "order": names, "failing_pass": names[end - 1],
                    "reason": str(error)}
    return {"status": "valid", "function": matches[0], "order": names}


def _default_root():
    import merlin

    return Path(merlin.__file__).resolve().parent


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, help="package directory to scan (default: the importable merlin)")
    parser.add_argument("--grep", default="", help="only module:function keys containing this text")
    parser.add_argument("--json", action="store_true", help="print rows as JSON instead of markdown")
    parser.add_argument("--no-lines", action="store_true", help="omit source line numbers")
    parser.add_argument("--reference", action="store_true", help="print the generated reference file")
    parser.add_argument("--check", metavar="FUNCTION", help="validate one function's declared order")
    parser.add_argument("--order", default="", help="comma-separated pass names for --check")
    args = parser.parse_args(argv)
    rows = scan(args.root or _default_root())
    if args.check:
        result = check(rows, args.check, [n for n in args.order.split(",") if n] or None)
        print(json.dumps(result, indent=2))
        return 0 if result["status"] == "valid" else 1
    if args.reference:
        print(REFERENCE_HEADER + markdown(rows, lines=False), end="")
        return 0
    if args.grep:
        keep = set(key for key in pipelines(rows) if args.grep in key)
        rows = [row for row in rows if f"{row['module']}:{row['function']}" in keep
                or row["kind"] == "stages" and any(args.grep in str(row[k]) for k in ("module", "entry", "pipeline"))]
    print(json.dumps(_jsonable(rows), indent=1) if args.json else markdown(rows, lines=not args.no_lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
